#!/usr/bin/env python3
"""Emit pure pattern-matching controls that amortize native loop ownership."""
from pathlib import Path
import argparse
import subprocess

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / 'src/binary/wide_groups_wbtest.mbt'


def function(width, quotient):
    name = f'wide_group_{width}_' + ('divide' if quotient else 'remainder')
    result = '(Binary, Binary)' if quotient else 'Binary'
    args = 'xs : @core.Chain[Bool], divisor : Binary, '
    if quotient:
        args += 'q : @core.Chain[Bool], '
    args += 'r : Binary'
    def steps(count):
        lines = []
        for i in range(count):
            previous = 'r' if i == 0 else f'r{i-1}'
            lines += [f'let next{i} = Binary::{{ bits: low_bit(b{i}, {previous}.bits), }}',
                      f'let order{i} = compare(next{i}, divisor)',
                      f'let r{i} = match order{i} {{', f'  Less => next{i}']
            if not quotient:
                lines.append('  Equal => zero()')
            lines += [f'  _ => from_bits(subtract_bits(next{i}.bits, divisor.bits, false))', '}']
            if quotient:
                prior_q = 'q' if i == 0 else f'q{i-1}'
                lines.append(f'let q{i} = low_bit(match order{i} {{ Less => false; _ => true }}, {prior_q})')
        final_args = f'tail, divisor, ' + (f'q{count-1}, ' if quotient else '') + f'r{count-1}'
        return lines + [f'{name}_loop({final_args})']
    pattern = 'tail'
    for i in reversed(range(width)):
        pattern = f'Cons(b{i}, {pattern})'
    lines = ['///|', f'fn {name}_loop({args}) -> {result} {{', '  match xs {',
             '    Nil => ' + ('({ bits: q, }, r)' if quotient else 'r'),
             '    ' + pattern + ' => {']
    lines += ['      '+line for line in steps(width)] + ['    }', '    Cons(b0, tail) => {']
    lines += ['      '+line for line in steps(1)] + ['    }', '  }', '}', '', '///|',
              f'fn {name}(xs : @core.Chain[Bool], divisor : Binary) -> {result} {{',
              f'  {name}_loop(@core.reverse(xs), divisor, ' + ('Nil, ' if quotient else '') + 'zero())', '}']
    return '\n'.join(lines)


def generate():
    sections = ['// Generated by tools/generate_wide_groups.py; no numeric kernel operations.']
    sections += [function(width, q) for width in [2,4,8] for q in [False,True]]
    lines = ['///|', 'test "grouped wide loops match the independent integer quotient and remainder" {',
             '  for a in 0..<128 { for b in 1..<128 {',
             '    let xs = @oracle.binary(a).bits', '    let divisor = @oracle.binary(b)',
             '    let q = @oracle.binary(a / b)', '    let r = @oracle.binary(a % b)']
    for width in [2,4,8]:
        lines += [f'    assert_eq(wide_group_{width}_remainder(xs, divisor), r)',
                  f'    assert_eq(wide_group_{width}_divide(xs, divisor), (q, r))']
    lines += ['  }}', '}', '', '///|',
              'test "unrolled reverse loops and native ownership controls" (b : @bench.T) {',
              '  for (width, modulus) in [(128,3), (512,31), (4096,3)] {',
              '    let word = pair(@oracle.nat(width), @oracle.binary(5))',
              '    let divisor = @oracle.binary(modulus)',
              '    b.bench(name="recursive rem \\{width}", fn() { b.keep(remainder_bits(word.bits, divisor)) })',
              '    b.bench(name="reverse rem \\{width}", fn() { b.keep(reversed_remainder_bits(word.bits, divisor)) })',
              '    b.bench(name="recursive div \\{width}", fn() { b.keep(divide_bits(word.bits, divisor)) })']
    for width in [2,4,8]:
        for q in [False,True]:
            suffix = 'divide' if q else 'remainder'
            lines.append(f'    b.bench(name="group{width} {suffix} \\{{width}}", fn() {{ b.keep(wide_group_{width}_{suffix}(word.bits, divisor)) }})')
    lines += ['  }', '}']
    sections.append('\n'.join(lines))
    return subprocess.run([str(ROOT/'.tools/moon/bin/moonfmt'), '-'],
                          input='\n\n'.join(sections)+'\n', text=True,
                          capture_output=True, check=True).stdout


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true')
    args=p.parse_args()
    source=generate()
    if args.check:
        if not DEST.exists() or DEST.read_text()!=source:
            raise SystemExit('Wide grouping controls drifted')
    else:
        DEST.write_text(source)


if __name__=='__main__': main()
