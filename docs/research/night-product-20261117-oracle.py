#!/usr/bin/env python3
"""Independent dict/Fraction convolution; writes fixtures or validates --check."""
from fractions import Fraction as Q
from pathlib import Path
import json,argparse,re
ROOT=Path(__file__).resolve().parents[2]
def product(a,b):
 p={}
 for an,ad,ae in a:
  for bn,bd,be in b:
   e=tuple(x+y for x,y in zip(ae,be));p[e]=p.get(e,Q(0))+Q(an,ad)*Q(bn,bd)
 return [(p[e].numerator,p[e].denominator,list(e)) for e in sorted(p,reverse=True) if p[e]]
def mb(ts):return '['+', '.join(f'({n}, {d}, ['+', '.join(map(str,e))+'])' for n,d,e in ts)+']'
specs=[
 {'name':'sparse-multivariate','n':3,'a':[(i%5-2,1,[i*2,i%3,0]) for i in range(32)],'b':[(j%3-1,1,[0,j*3,j%2]) for j in range(18)],'iterations':300},
 {'name':'dense-univariate','n':1,'a':[(i%5-2,1,[i]) for i in range(24)],'b':[(j%7-3,1,[j]) for j in range(24)],'iterations':1000},
 {'name':'unequal-sparse','n':2,'a':[(i%3-1,1,[i*2,0]) for i in range(40)],'b':[(1,1,[0,0]),(-1,1,[0,3])],'iterations':1500},
 {'name':'rational-cancellation','n':1,'a':[((-1)**i,(i%4)+2,[i]) for i in range(20)],'b':[(1,(j%4)+2,[j]) for j in range(20)],'iterations':800},
]
for s in specs:s['expected']=product(s['a'],s['b'])
cases=[]
for n in [0,1,2,3]:
 for size in [0,1,2,3,8,12]:
  a=[((i%5)-2,(i%3)+1,[(i*(j+1)+j)%5 for j in range(n)]) for i in range(size)]
  b=[((j%3)-1,(j%4)+1,[(j*(k+2)+1)%4 for k in range(n)]) for j in range((size+1)//2)]
  cases.append((n,a,b,product(a,b)))
for s in specs:cases.append((s['n'],s['a'],s['b'],s['expected']))
lines=['// Generated by docs/research/night-product-20261117-oracle.py (independent Python Fraction).','///|','fn product_fixture(n : Int32, data : Array[(Int32, Int32, Array[Int32])]) -> Polynomial {','  polynomial(@oracle.nat(n), @oracle.chain(data.map(fn(t) { Term::{ coefficient: @oracle.rational(t.0,t.1), exponents: @oracle.chain(t.2.map(@oracle.nat)), } }))).unwrap()','}','///|','fn old_sequential_product(a : Polynomial, b : Polynomial) -> Result[Polynomial, PolyError] {','  match @core.compare(a.variables,b.variables) {','    Equal => Ok({ variables:a.variables,terms:@core.fold_left(a.terms,Nil,fn(found,term) { merge_terms(found,term_times(term,b.terms)) }), })','    _ => Err(DimensionMismatch)','  }','}']
for i,(n,a,b,w) in enumerate(cases):
 assert all(abs(v)<2147483648 and d<2147483648 for v,d,_ in w)
 lines += ['///|',f'test "Fraction full convolution fixture {i}" {{',f' let a=product_fixture({n},{mb(a)})',f' let b=product_fixture({n},{mb(b)})',f' let expected=product_fixture({n},{mb(w)})',' assert_eq(multiply(a,b),Ok(expected))',' assert_eq(multiply(a,b),old_sequential_product(a,b))',' assert_eq(multiply(b,a),Ok(expected))','}']
lines += ['///|','test "product empty dimensions still reject before shortcuts" {',' let z=zero(@oracle.nat(2))',' let wrong=zero(@oracle.nat(1))',' assert_eq(multiply(z,wrong),Err(DimensionMismatch))',' assert_eq(multiply(wrong,z),Err(DimensionMismatch))','}']
out='\n\n'.join(lines)+'\n';fixture=ROOT/'src/polynomial/product_fraction_20261117_wbtest.mbt';data=ROOT/'docs/research/night-product-20261117-oracle-cases.json'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
def tokens(s):return re.sub(r',(?=[\]\)}])','',''.join(s.split()))
if args.check:
 assert tokens(fixture.read_text())==tokens(out),'fixture drift'
 assert json.loads(data.read_text())==json.loads(json.dumps(specs)),'CLI expectation drift'
else:
 fixture.write_text(out);data.write_text(json.dumps(specs,indent=2)+'\n')
print(f'{len(cases)} independent full-product fixtures '+('checked' if args.check else 'generated'))
