"""Independent full-system Python Fraction Gauss-Jordan oracle, seed frozen."""
from fractions import Fraction as Q
from random import Random
from pathlib import Path
import json
rng=Random(20261117)
root=Path(__file__).resolve().parents[3]

def solve(columns, vector):
    n=len(columns)
    a=[[c[i] for c in columns]+[v] for i,v in enumerate(vector)]
    row=0
    for col in range(n):
        k=next(k for k in range(row,len(a)) if a[k][col])
        a[row],a[k]=a[k],a[row]
        q=a[row][col]
        a[row]=[x/q for x in a[row]]
        for k in range(len(a)):
            if k!=row:
                q=a[k][col]
                a[k]=[x-q*y for x,y in zip(a[k],a[row])]
        row+=1
    if any(all(x==0 for x in r[:-1]) and r[-1] for r in a): return None
    return [a[i][-1] for i in range(n)]

cases=[]
for d in range(1,6):
    for trial in range(3):
        columns=[];vectors=[];answers=[]
        # A reversed coordinate flag forces pivot positions out of row order.
        for i in reversed(range(d)):
            v=[Q(0) if j<i else Q(rng.choice([-3,-2,1,2,3]),rng.choice([2,3,5])) for j in range(d)]
            vectors.append(v)
        # Zero, fractional combinations, repeated columns and arbitrary vectors.
        vectors += [[Q(0)]*d]
        for _ in range(3):
            weights=[Q(rng.randrange(-3,4),rng.choice([2,3,5])) for _ in range(d)]
            vectors.append([sum((weights[k]*vectors[k][j] for k in range(d)),Q(0)) for j in range(d)])
        vectors += [vectors[0]]
        for v in vectors:
            answer=solve(columns,v)
            answers.append(answer)
            if answer is None: columns.append(v)
        cases.append(dict(dimension=d,vectors=vectors,answers=answers))

def q(q):return f'({q.numerator}, {q.denominator})'
def v(v):return '['+', '.join(map(q,v))+']'
lines=['// Generated by docs/research/incremental-span-20261117-raw/generate_fraction_fixtures.py; Python fractions.Fraction full-system oracle.','']
for i,c in enumerate(cases):
    lines += ['///|',f'test "Python Fraction incremental span fixture {i}" {{',f'  fraction_fixture({c["dimension"]}, ['+', '.join(map(v,c['vectors']))+'], ['+', '.join('None' if a is None else 'Some('+v(a)+')' for a in c['answers'])+'])','}','']
(root/'src/linearspan/python_fraction_wbtest.mbt').write_text('\n'.join(lines))
Path(__file__).with_name('fraction-fixtures.json').write_text(json.dumps(cases,default=lambda x:[x.numerator,x.denominator],indent=2)+'\n')
print('generated',len(cases),'cases with',sum(len(c['vectors']) for c in cases),'checked decisions')
