 out={}
 for sign,terms in [(1,a),(-1,b)]:
  for n,d,e in terms:
   e=tuple(e);out[e]=out.get(e,Q(0))+sign*Q(n,d)
 return [(out[e].numerator,out[e].denominator,list(e)) for e in sorted(out,reverse=True) if out[e]]
