 lines+=['///|',f'test "Fraction full polynomial subtraction fixture {i}" {{',f' let a=subtraction_fixture({n},{mb(a)})',f' let b=subtraction_fixture({n},{mb(b)})',f' let expected=subtraction_fixture({n},{mb(want)})',' assert_eq(subtract(a,b),Ok(expected))',' assert_eq(subtract(a,b),old_composed_subtraction(a,b))',' assert_eq(subtract(b,a),Ok(negate(expected)))',' assert_eq(subtract(a,a),Ok(zero(@oracle.nat('+str(n)+'))))','}']
