#!/usr/bin/env python3
"""Generate pure Bool MTBDD prototypes for the finite 4-bit GCD domain.

This is a construction oracle, not kernel arithmetic. MoonBit tests compare
all 256 inputs with a separately written integer Euclidean oracle.
"""
from __future__ import annotations
import argparse
import functools
import itertools
import json
import math
from pathlib import Path
import random
import subprocess

ROOT = Path(__file__).resolve().parent
WORDS = ('zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen').split()
VARS = ('a_low', 'a_next', 'a_third', 'a_high', 'b_low', 'b_next', 'b_third', 'b_high')
TRUTH = tuple(math.gcd(index & 15, index >> 4) for index in range(256))


def build(order):
    reordered = []
    for assignment in range(256):
        original = sum(((assignment >> depth) & 1) << var for depth, var in enumerate(order))
        reordered.append(TRUTH[original])
    nodes = {}
    intern = {}
    @functools.cache
    def visit(values):
        if all(value == values[0] for value in values):
            return values[0]
        depth = 8 - (len(values).bit_length() - 1)
        low = visit(values[::2]); high = visit(values[1::2])
        if low == high:
            return low
        key = (order[depth], low, high)
        if key not in intern:
            index = 16 + len(nodes)
            intern[key] = index
            nodes[index] = key
        return intern[key]
    root = visit(tuple(reordered))
    return root, nodes


def bits(value):
    if not value:
        return '@core.Nil'
    return '@core.Cons(' + ('true' if value & 1 else 'false') + ', ' + bits(value >> 1) + ')'


def constants(prefix):
    return '\n\n'.join('///|\nlet ' + prefix + '_value_' + word + ' : @binary.Binary = @binary.from_bits(' + bits(value) + ')' for value, word in enumerate(WORDS))


def decode(prefix):
    return f'''///|
fn {prefix}_decode(value : @binary.Binary) -> (Bool, Bool, Bool, Bool) {{
  fn pop(bits : @core.Chain[Bool]) -> (Bool, @core.Chain[Bool]) {{
    match bits {{ @core.Nil => (false, @core.Nil); @core.Cons(bit, rest) => (bit, rest) }}
  }}
  let (low, rest) = pop(@binary.bits(value))
  let (next, rest) = pop(rest)
  let (third, rest) = pop(rest)
  let (high, _) = pop(rest)
  (low, next, third, high)
}}'''


def arguments():
    return '''  let (a_low, a_next, a_third, a_high) = {prefix}_decode(a)
  let (b_low, b_next, b_third, b_high) = {prefix}_decode(b)
'''


def table(prefix):
    lines = ['///|', f'fn {prefix}_table(a : @binary.Binary, b : @binary.Binary) -> @binary.Binary {{', arguments().format(prefix=prefix).rstrip(), '  match (' + ', '.join(VARS) + ') {']
    for index, value in enumerate(TRUTH):
        pattern = ', '.join('true' if index & (1 << var) else 'false' for var in range(8))
        lines.append(f'    ({pattern}) => {prefix}_value_{WORDS[value]}')
    lines.extend(['  }', '}'])
    return '\n'.join(lines)


def dag(prefix, name, order):
    root, nodes = build(order)
    used = {}
    for index, (var, low, high) in nodes.items():
        used[index] = {var} | used.get(low,set()) | used.get(high,set())
    def call(index):
        if index < 16:
            return f'{prefix}_value_{WORDS[index]}'
        params = ', '.join(VARS[var] for var in sorted(used[index]))
        return f'{prefix}_{name}_node_{index}({params})'
    lines = []
    for index, (var, low, high) in nodes.items():
        params = ', '.join(VARS[var] + ' : Bool' for var in sorted(used[index]))
        lines.extend(['///|', f'fn {prefix}_{name}_node_{index}({params}) -> @binary.Binary {{', f'  match {VARS[var]} {{', f'    false => {call(low)}', f'    true => {call(high)}', '  }', '}', ''])
    lines.extend(['///|', f'fn {prefix}_{name}(a : @binary.Binary, b : @binary.Binary) -> @binary.Binary {{', arguments().format(prefix=prefix).rstrip(), '  '+call(root), '}'])
    return '\n'.join(lines)


def search():
    all_orders = list(itertools.permutations(range(8)))
    random_orders = random.Random(0x4BCD).sample(all_orders,512)
    seeds = [(0,4,1,5,2,6,3,7),(4,0,5,1,6,2,7,3),tuple(range(8)),tuple(reversed(range(8)))]
    candidates = sorted(set(seeds + random_orders))
    ranked = sorted((len(build(order)[1]),order) for order in candidates)
    return ranked, len(candidates)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--winner', choices=('table','first','second','third'))
    args = parser.parse_args()
    ranked, count = search()
    selected = ranked[:3]
    prefix = 'candidate_gcd'
    source = '// Generated by generate_tiny_gcd.py; exhaustive 4-bit domain only.\n\n' + constants(prefix) + '\n\n' + decode(prefix) + '\n\n' + table(prefix) + '\n\n' + '\n\n'.join(dag(prefix,name,order) for name,(_,order) in zip(('first','second','third'), selected)) + '\n'
    formatter = ROOT.parents[1] / '.tools/moon/bin/moonfmt'
    source = subprocess.run([str(formatter), '-'], input=source, text=True, check=True, capture_output=True).stdout
    destination = ROOT / 'tiny_candidates_wbtest.mbt'
    if args.check:
        if destination.read_text() != source:
            raise SystemExit('Generated prototype drift; regenerate then format.')
    else:
        destination.write_text(source)
    if args.winner:
        production_prefix = 'tiny_gcd'
        if args.winner == 'table':
            implementation = table(production_prefix).replace('fn tiny_gcd_table(', 'fn tiny_gcd_lookup(')
        else:
            rank = ('first','second','third').index(args.winner)
            implementation = dag(production_prefix,'selected',selected[rank][1]).replace('fn tiny_gcd_selected(', 'fn tiny_gcd_lookup(')
        production = '// Generated by generate_tiny_gcd.py --winner ' + args.winner + '; caller must establish inputs below sixteen.\n\n' + constants(production_prefix) + '\n\n' + decode(production_prefix) + '\n\n' + implementation + '\n'
        production = subprocess.run([str(formatter), '-'], input=production, text=True, check=True, capture_output=True).stdout
        production_path = ROOT / 'tiny_gcd.mbt'
        if args.check:
            if production_path.read_text() != production:
                raise SystemExit('Generated production lookup drift.')
        else:
            production_path.write_text(production)
    print(json.dumps({'orders_searched':count,'best_three':[{'nodes':size,'order':list(order)} for size,order in selected],'production_algorithm':args.winner},indent=2))

if __name__ == '__main__':
    main()
