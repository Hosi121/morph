#!/usr/bin/env python3
"""Committed Smith diagonals from independent SymPy integer normal forms."""
from pathlib import Path
import random
import sympy
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import smith_normal_form

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    rng = random.Random(20261115)
    cases = [(0, 0, []), (0, 3, []), (3, 0, [[], [], []])]
    for m, n in [(2, 2), (3, 3), (2, 3), (3, 2), (3, 4), (4, 3), (4, 4)]:
        for _ in range(6):
            cases.append((m, n, [[rng.randrange(-10, 11) for _ in range(n)] for _ in range(m)]))
    cases += [(3, 3, [[2, 4, 6], [4, 8, 12], [0, 0, 0]]),
              (2, 3, [[6, 0, 0], [0, 10, 0]])]
    out = f'// Generated by tools/generate_smith.py with SymPy {sympy.__version__}; fixed seed.\n'
    out += '///|\ntest "Smith diagonals match committed independent SymPy fixtures" {\n'
    for m, n, rows in cases:
        matrix = Matrix(m, n, [x for row in rows for x in row])
        result = smith_normal_form(matrix, domain=ZZ)
        expected = [[abs(int(result[i, j])) for j in range(n)] for i in range(m)]
        out += f'  check_fixture({n}, {rows!r}, {expected!r})\n'
    out += '}\n'
    (ROOT / 'src/smith/vectors_wbtest.mbt').write_text(out)


if __name__ == '__main__':
    main()
