#!/usr/bin/env python3
"""Generate the finite four-bit product kernel; numeric arithmetic stays here."""
import argparse
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def bits(value):
    if value == 0:
        return 'Nil'
    return 'Cons('+('true' if value & 1 else 'false')+', '+bits(value >> 1)+')'


def generate(sharing=True):
    lines = ['// Generated by tools/generate_binary_tiny_products.py; exhaustive canonical four-bit products.', '']
    products = sorted({a*b for a in range(16) for b in range(16)})
    suffixes = set()
    for value in products:
        while value:
            suffixes.add(value)
            value //= 2
    if sharing:
        lines += ['// One canonical one cell already exists; every other suffix is one Cons.',
                  '///|', 'let tiny_product_bits_1 : @core.Chain[Bool] = bits(canonical_one())', '']
        for value in sorted(suffixes - {1}):
            bit = 'true' if value & 1 else 'false'
            lines += ['///|', f'let tiny_product_bits_{value} : @core.Chain[Bool] = Cons({bit}, tiny_product_bits_{value//2})', '']
    for value in products:
        representation = 'tiny_product_bits_'+str(value) if sharing else bits(value)
        expr = ('canonical_zero()' if value == 0 else 'canonical_one()') if value < 2 else '{ bits: '+representation+', }'
        lines += ['///|', f'let tiny_product_value_{value} : Binary? = Some({expr})', '']
    lines += ['///|', '// Values outside the finite table retain the existing recursive kernel.', 'fn tiny_product(a : Binary, b : Binary) -> Binary? {', '  match (a.bits, b.bits) {']
    for a in range(16):
        for b in range(16):
            lines += [f'    ({bits(a)}, {bits(b)}) => tiny_product_value_{a*b}']
    lines += ['    _ => None', '  }', '}', '']
    return '\n'.join(lines), len(products)


FLAT_BENCHMARK = '''
///|
test "flat literal and shared suffix lookups in the same executable" (b : @bench.T) {
  let pairs = []
  for a in 3..<16 {
    for c in 3..<16 {
      pairs.push((@oracle.binary(a), @oracle.binary(c)))
    }
  }
  b.bench(name="flat lookup169", fn() {
    for pair in pairs { b.keep(flat_tiny_product(pair.0, pair.1)) }
  })
  b.bench(name="DAG lookup169", fn() {
    for pair in pairs { b.keep(tiny_product(pair.0, pair.1)) }
  })
}

///|
test "flat literal and shared suffix lookup preserve the same canonical values" {
  for a in 0..<17 {
    for b in 0..<17 {
      let x = @oracle.binary(a)
      let y = @oracle.binary(b)
      assert_eq(flat_tiny_product(x,y), tiny_product(x,y))
      match tiny_product(x,y) {
        Some(value) => {
          assert_eq(value, @oracle.binary(a*b))
          match @core.reverse(value.bits) {
            Nil => assert_eq(a*b,0)
            Cons(high,_) => assert_true(high)
          }
        }
        None => assert_true(a >= 16 || b >= 16)
      }
    }
  }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--flat-control', action='store_true', help='emit a temporary WB comparison against unshared suffix literals')
    args = parser.parse_args()
    source, count = generate(sharing=not args.flat_control)
    if args.flat_control:
        import re
        source = re.sub(r'(?<![\w])tiny_product', 'flat_tiny_product', source)
        source += FLAT_BENCHMARK
    formatter = ROOT / '.tools/moon/bin/moonfmt'
    if not formatter.is_file():
        formatter = shutil.which('moonfmt')
        if formatter is None:
            raise SystemExit('MoonBit formatter is missing; run tools/bootstrap.')
    source = subprocess.run([str(formatter), '-'], input=source, text=True,
                            capture_output=True, check=True).stdout
    destination = ROOT / ('src/binary/tiny_products_flat_control_wbtest.mbt' if args.flat_control else 'src/binary/tiny_products.mbt')
    if args.check:
        if destination.read_text() != source:
            raise SystemExit('Generated tiny product table drift; regenerate.')
    else:
        destination.write_text(source)
    print(f'4-bit product table checked: 256 cases, {count} shared results; suffix sharing={not args.flat_control}.')


if __name__ == '__main__':
    main()
