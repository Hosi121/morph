#!/usr/bin/env python3
"""Independent SymPy QQ/lex Groebner fixtures for the symbolic F4 package."""
from pathlib import Path
import json
import subprocess
import sympy as sp
from random import Random

ROOT = Path(__file__).resolve().parents[1]
x, y, z, w = sp.symbols('x y z w')
cases = [
    ((x,y), [x*x-y,x*y-1]),
    ((x,y), [x+y,x-y]),
    ((x,y), [x*x+y*y-1,x-y]),
    ((x,y), [x*x+y*y-1,x*y-sp.Rational(1,4)]),
    ((x,y), [x*x+y,x*y+1,y*y+x]),
    ((x,y), [2*x*x-3*y,3*x*y-2,x-y*y]),
    ((x,y), [(x-y)**2,x-y]),
    ((x,y,z), [x+y+z,x*y+y*z+z*x,x*y*z-1]),
    ((x,y,z), [x*x+y*y+z*z-1,x-y,y-z]),
    ((x,y,z), [x*y-z,y*z-x,z*x-y]),
    ((x,y,z), [x*y,x*z,y*z]),
    ((x,y), [x*x,x*y,y*y]),
    ((x,y,z,w), [x+y+z+w,x-y,y-z,z-w]),
    ((x,y,z), [x+2*y+2*z-1,x*x+2*y*y+2*z*z-x,2*x*y+2*y*z-y]),
    ((x,y), [sp.Rational(2,3)*x*x-sp.Rational(3,5)*y,sp.Rational(7,11)*x*y-sp.Rational(13,17)]),
]


# Small fixed-seed systems, independently reduced by SymPy. The input is
# quadratic in two variables, keeping the exact symbolic matrix sizes modest.
rng = Random(20261116)
monomials = [x*x, x*y, y*y, x, y, sp.Integer(1)]
for _ in range(48):
    system = []
    for _ in range(2 + rng.randrange(2)):
        expression = sum(rng.randrange(-2, 3)*m for m in monomials)
        if expression:
            system.append(expression)
    cases.append(((x,y), system))


def terms(expr, variables):
    return [(int(c.p),int(c.q),list(exps)) for exps,c in sp.Poly(expr,*variables,domain=sp.QQ).terms() if c]


def render(items):
    return '['+', '.join(f'({a}, {b}, ['+', '.join(map(str,es))+'])' for a,b,es in items)+']'


lines = ['// Generated by tools/generate_f4_fixtures.py; independent SymPy QQ/lex oracle.','']
records = []
for i,(variables,inputs) in enumerate(cases):
    basis = sp.groebner(inputs,*variables,order='lex',domain=sp.QQ)
    source = [terms(p,variables) for p in inputs]
    expected = [terms(p.as_expr(),variables) for p in basis.polys if p]
    records.append(dict(variables=[str(v) for v in variables],inputs=source,basis=expected))
    lines += ['///|', f'test "SymPy rational F4 lex fixture {i}" {{',
              f'  assert_sympy_fixture({len(variables)},',
              '    ['+', '.join(render(p) for p in source)+'],',
              '    ['+', '.join(render(p) for p in expected)+'])','}','']
(ROOT/'src/f4/sympy_wbtest.mbt').write_text('\n'.join(lines))
output = ROOT/'.tools/f4-20261116/sympy-fixtures.json'
output.parent.mkdir(parents=True,exist_ok=True)
output.write_text(json.dumps(dict(sympy=sp.__version__,order='lex',domain='QQ',cases=records),indent=2)+'\n')
subprocess.run([str(ROOT/'tools/moon'), 'fmt', 'src/f4/sympy_wbtest.mbt'], cwd=ROOT, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
print(f'generated {len(cases)} F4 fixtures using SymPy {sp.__version__}')
