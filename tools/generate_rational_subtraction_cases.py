#!/usr/bin/env python3
"""Emit independent wide Fraction subtraction expectations as canonical hex."""
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
cases = []
for width in [17, 64, 127, 257, 512]:
    high = 1 << width
    for left_sign in [-1, 1]:
        for right_sign in [-1, 1]:
            cases.append((Fraction(left_sign * (high + 3), high - 1),
                          Fraction(right_sign * (high + 5), high - 1)))
    cases.append((Fraction((1 << (width // 2)) + 3, high - 1),
                  Fraction(-((1 << (width // 2)) + 5), high + 1)))
    cases.append((Fraction(17, 15 * (high - 1)), Fraction(19, 21 * (high - 1))))


def fields(value):
    return f'{str(value.numerator < 0).lower()}, "{abs(value.numerator):x}", "{value.denominator:x}"'


rows = ',\n'.join('    (' + ', '.join(fields(v) for v in [a, b, a-b]) + ')' for a, b in cases)
source = '''// Generated by tools/generate_rational_subtraction_cases.py; Python Fraction oracle.

///|
fn subtraction_fixture(negative : Bool, numerator : String, denominator : String) -> Rational {
  let numerator = positive(@oracle.binary_from_hex(numerator))
  let numerator = if negative { negate(numerator) } else { numerator }
  ratio(numerator, @oracle.binary_from_hex(denominator)).unwrap()
}

///|
test "direct rational subtraction matches wide Python Fraction fixtures" {
  for (an, a, ad, bn, b, bd, rn, r, rd) in [
'''+rows+'''
  ] {
    let actual = subtract_rationals(subtraction_fixture(an,a,ad), subtraction_fixture(bn,b,bd))
    assert_eq(negative(actual.numerator), rn)
    assert_eq(actual.numerator.magnitude, @oracle.binary_from_hex(r))
    assert_eq(actual.denominator, @oracle.binary_from_hex(rd))
  }
}
'''
(ROOT / 'src/exact/subtraction_oracle_wbtest.mbt').write_text(source)
print(f'Wrote {len(cases)} wide Python Fraction cases.')
