#!/usr/bin/env python3
"""Small prime-field GS fixtures from independent exhaustive message oracles.

All message enumeration is confined to this numeric test generator. The symbolic
kernel uses Hasse interpolation and coefficient-by-coefficient RR root picking.
"""
from __future__ import annotations
import argparse
from itertools import product
import json
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'src/listdecode/oracle_wbtest.mbt'
ARTIFACT = ROOT / '.tools/listdecode-20261116/oracle-summary.json'


def evaluate(p: int, message: tuple[int, ...], x: int) -> int:
    value = 0
    for coefficient in reversed(message):
        value = (value * x + coefficient) % p
    return value


def nearest(p: int, xs: list[int], k: int, agreements: int, received: list[int]) -> list[tuple[int, ...]]:
    return [message for message in product(range(p), repeat=k)
            if sum(evaluate(p, message, x) == y for x, y in zip(xs, received)) >= agreements]


def literal(values) -> str:
    return '[' + ', '.join(literal(value) if isinstance(value, (list, tuple)) else str(value) for value in values) + ']'


def fixtures() -> tuple[str, list[dict]]:
    rng = random.Random(202611161)
    specifications = [
        (3, [0, 1, 2], 2, 2, 2, 3),
        (5, [0, 1, 2, 3], 2, 3, 1, 2),
        (7, list(range(6)), 2, 3, 2, 5),
        (11, list(range(9)), 2, 4, 1, 3),
        (11, list(range(9)), 3, 5, 2, 9),
        (11, list(range(10)), 3, 5, 3, 14),
        (13, [12, 0, 10, 2, 8, 4, 6, 1, 3, 5, 7], 3, 6, 2, 11),
        (13, list(range(12)), 4, 7, 2, 13),
        (17, list(range(13)), 4, 7, 3, 20),
    ]
    lines = ['// Generated by tools/generate_listdecode.py; independent full-message test oracle.']
    summaries = []
    for p, xs, k, a, s, d in specifications:
        assert p > 1 and all(p % divisor for divisor in range(2, p))
        n = len(xs)
        monomials = [(x, y) for y in range(d // (k-1) + 1) for x in range(d-(k-1)*y+1)]
        constraints = n*s*(s+1)//2
        assert len(monomials) > constraints and d < s*a
        for variant in range(3):
            message = tuple(rng.randrange(p) for _ in range(k))
            sent = [evaluate(p, message, x) for x in xs]
            if variant == 0:
                received = sent[:]
                for position in rng.sample(range(n), n-a):
                    received[position] = (received[position] + rng.randrange(1, p)) % p
            elif variant == 1:
                other = tuple(rng.randrange(p) for _ in range(k))
                received = [sent[i] if i < a else evaluate(p, other, x) for i, x in enumerate(xs)]
            else:
                received = [rng.randrange(p) for _ in xs]
            candidates = nearest(p, xs, k, a, received)
            if variant < 2:
                assert message in candidates
            index = len(summaries)
            lines += ['', '///|', f'test "independent GS fixture {index} F{p} n{n} k{k} s{s}" {{',
                      '  assert_fixture(', f'    {p}, {literal(xs)}, {k}, {a}, {s}, {d},',
                      f'    {literal(received)},', f'    {literal(candidates)},', '  )', '}']
            summaries.append(dict(index=index, p=p, points=xs, k=k, agreements=a,
                                  multiplicity=s, degree_bound=d, monomials=len(monomials),
                                  constraints=constraints, radius=n-a, unique_radius=(n-k)//2,
                                  received=received, candidates=candidates))
    return '\n'.join(lines) + '\n', summaries


def tokens(source: str) -> list[str]:
    source = re.sub(r',\s*([\]\)])', r'\1', source)
    return re.findall(r'"(?:\\.|[^"\\])*"|\S', source)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, summaries = fixtures()
    if args.check:
        assert tokens(OUTPUT.read_text()) == tokens(content), 'listdecode fixture regeneration drift'
    else:
        OUTPUT.write_text(content)
    ARTIFACT.parent.mkdir(parents=True, exist_ok=True)
    ARTIFACT.write_text(json.dumps(summaries, indent=2) + '\n')
    print(f"{'Checked' if args.check else 'Wrote'} {len(summaries)} independent prime-field list-decoding fixtures.")


if __name__ == '__main__':
    main()
