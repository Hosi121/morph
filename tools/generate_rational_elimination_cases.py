#!/usr/bin/env python3
"""Independent Fraction Gauss-Jordan oracle for the public QQ API."""
from fractions import Fraction as Q
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def rref(rows, width):
    a = [list(row) for row in rows]
    pivots = []
    rank = 0
    for col in range(width):
        chosen = next((i for i in range(rank, len(a)) if a[i][col]), None)
        if chosen is None:
            continue
        a[rank], a[chosen] = a[chosen], a[rank]
        divisor = a[rank][col]
        a[rank] = [x / divisor for x in a[rank]]
        for i in range(len(a)):
            if i != rank:
                multiple = a[i][col]
                a[i] = [x - multiple*y for x, y in zip(a[i], a[rank])]
        pivots.append(col)
        rank += 1
    return a, pivots


def solve(rows, width, rhs):
    a, pivots = rref([row + [value] for row, value in zip(rows, rhs)], width + 1)
    if any(all(not x for x in row[:width]) and row[width] for row in a):
        return 'Some(Inconsistent)'
    lookup = dict(zip(pivots, a))
    free = [j for j in range(width) if j not in lookup]
    particular = [lookup[j][width] if j in lookup else Q(0) for j in range(width)]
    if not free:
        return f'Some(Unique(fraction_vector({vec(particular)})))'
    basis = [[Q(1) if j == f else -lookup[j][f] if j in lookup else Q(0)
              for j in range(width)] for f in free]
    return f'Some(Affine(fraction_vector({vec(particular)}), @oracle.chain({arr([f"fraction_vector({vec(v)})" for v in basis])})))'


def arr(values):
    return '[' + ', '.join(values) + ']'


def vec(values):
    return arr([f'({v.numerator}, {v.denominator})' for v in values])


def mat(rows):
    return arr([vec(row) for row in rows])


source = ['// Generated by tools/generate_rational_elimination_cases.py; independent Python Fraction oracle.', '''
///|
fn fraction_vector(values : Array[(Int, Int)]) -> @core.Chain[@exact.Rational] {
  @oracle.chain(values.map(fn(value) { @oracle.rational(value.0, value.1) }))
}

///|
fn fraction_matrix(values : Array[Array[(Int, Int)]], width : Int) -> @matrix.Matrix[@exact.Rational] {
  @matrix.matrix(@oracle.nat(width), @oracle.chain(values.map(fraction_vector))).unwrap()
}
''']
shapes = [(2, 2), (2, 3), (3, 2)]
case_count = 0
for height, width in shapes:
    # Exhaustive ternary rational alphabet for each of the three shapes.
    fixtures = []
    for values in product([Q(-1, 2), Q(0), Q(2, 3)], repeat=height*width):
        rows = [list(values[i*width:(i+1)*width]) for i in range(height)]
        reduced, pivots = rref(rows, width)
        rhs = [Q(1 if i % 2 == 0 else -1, i+2) for i in range(height)]
        fixtures.append(f'({mat(rows)}, {mat(reduced)}, {arr([str(i) for i in pivots])}, {solve(rows, width, rhs)})')
        case_count += 1
    source.append(f'''\n///|
test "Fraction oracle exhaustive {height} by {width} rational matrices" {{
  for (rows, expected, pivots, solution) in [
    ''' + ',\n    '.join(fixtures) + f'''
  ] {{
    let input = fraction_matrix(rows, {width})
    let reduced = rref(input).unwrap()
    assert_eq(reduced.matrix, fraction_matrix(expected, {width}))
    assert_eq(reduced.pivots, @oracle.chain(pivots.map(@oracle.nat)))
    let generic = @rowreduce.rref(arithmetic(), input).unwrap()
    assert_eq(reduced.matrix, generic.matrix)
    assert_eq(reduced.pivots, generic.pivots)
    assert_eq(reduced.factor, generic.factor)
    assert_eq(solve(input, fraction_vector({vec([Q(1 if i % 2 == 0 else -1, i+2) for i in range(height)])})), solution)
    assert_eq(inverse(input), @rowreduce.inverse(arithmetic(), input))
  }}
}}
''')
(ROOT / 'src/linear/fraction_oracle_wbtest.mbt').write_text('\n'.join(source))
print(f'Wrote {case_count} exhaustive Fraction matrix/rank/solve cases and generic inverse/factor comparisons.')
