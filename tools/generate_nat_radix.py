#!/usr/bin/env python3
"""Generate pure-ADT radix grouping candidates for the unary converter."""
from pathlib import Path
import argparse
import subprocess

ROOT = Path(__file__).resolve().parent.parent
DESTINATION = ROOT / "src/binary/nat_radix_wbtest.mbt"


def succ(count, tail):
    return 'Succ(' * count + tail + ')' * count


def candidate(width, shared):
    base = 1 << width
    name = f'radix_{base}_' + ('shared' if shared else 'rebuild')
    result_type = '(@core.Nat, ' + ', '.join(['Bool'] * width) + ')'
    def result(tail, remainder):
        bits = [('true' if remainder & (1 << bit) else 'false') for bit in range(width)]
        return '(' + ', '.join([tail] + bits) + ')'
    lines = ['///|', f'fn {name}_split(n : @core.Nat) -> {result_type} {{',
             f'  fn walk(fast : @core.Nat, slow : @core.Nat) -> {result_type} {{',
             '    match ' + ('(fast, slow)' if shared else 'fast') + ' {']
    for r in range(base):
        pattern = succ(r, 'Zero')
        if shared:
            pattern = '(' + pattern + ', ' + succ(r, 'tail') + ')'
        lines.append('      ' + pattern + ' => ' + result('tail' if shared else 'slow', r))
    if shared:
        lines.append('      (' + succ(base, 'rest') + ', ' + succ(base - 1, 'tail') + ') => walk(rest, tail)')
        lines.append('      _ => ' + result('Zero', 0))
    else:
        lines.append('      ' + succ(base, 'rest') + ' => walk(rest, Succ(slow))')
    lines += ['    }', '  }', '  walk(n, ' + ('n' if shared else 'Zero') + ')', '}', '',
              '///|', f'fn {name}(n : @core.Nat) -> Binary {{',
              '  fn convert(n : @core.Nat) -> @core.Chain[Bool] {',
              '    match n {', '      Zero => Nil', '      Succ(_) => {',
              '        let (q, ' + ', '.join('b'+str(i) for i in range(width)) + f') = {name}_split(n)']
    expr = 'convert(q)'
    for i in reversed(range(width)):
        expr = f'low_bit(b{i}, {expr})'
    lines += ['        ' + expr, '      }', '    }', '  }', '  { bits: convert(n), }', '}']
    return '\n'.join(lines)


def generate():
    names = [f'radix_{1<<w}_' + ('shared' if s else 'rebuild') for w in [2,3,4] for s in [True,False]]
    sections = ['// Generated by tools/generate_nat_radix.py; candidate functions use only ADTs.']
    sections += [candidate(w, s) for w in [2,3,4] for s in [True,False]]
    names += ['from_nat_grouped']
    tests = ['///|', 'test "radix candidates agree with an independent integer conversion oracle" {',
             '  let candidates = [' + ', '.join(names) + ']',
             '  for value in 0..<=1024 {', '    let n = @oracle.nat(value)',
             '    let expected = @oracle.binary(value)',
             '    for convert in candidates { assert_eq(convert(n), expected) }', '  }',
             '  for value in [4095,4096,4097,65535,65536,65537,100000] {',
             '    let n = @oracle.nat(value)', '    let expected = @oracle.binary(value)',
             '    for convert in candidates { assert_eq(convert(n), expected) }', '  }', '}', '',
             '///|', 'test "grouping unary input into several bits at a time" (b : @bench.T) {',
             '  for value in [4096,100000] {', '    let n = @oracle.nat(value)',
             '    b.bench(name="two shared \\{value}", fn() { b.keep(shared_nat_binary(n)) })',
             '    b.bench(name="two rebuild \\{value}", fn() { b.keep(rebuilding_nat_binary(n)) })']
    for name in names:
        tests.append(f'    b.bench(name="{name} \\{{value}}", fn() {{ b.keep({name}(n)) }})')
    tests += ['  }', '}', '', '///|',
              'test "small unary grouping cohort" (b : @bench.T) {',
              '  for value in [0,1,2,7,8,9,16,63,64,255] {',
              '    let n = @oracle.nat(value)',
              '    b.bench(name="two shared \\{value}", fn() { b.keep(shared_nat_binary(n)) })',
              '    b.bench(name="eight shared \\{value}", fn() { b.keep(radix_8_shared(n)) })',
              '    b.bench(name="public converter \\{value}", fn() { b.keep(from_nat(n)) })',
              '    b.bench(name="grouped helper \\{value}", fn() { b.keep(from_nat_grouped(n)) })',
              '  }', '}']
    sections.append('\n'.join(tests))
    source = '\n\n'.join(sections) + '\n'
    formatter = ROOT / '.tools/moon/bin/moonfmt'
    return subprocess.run([str(formatter), '-'], input=source, text=True, capture_output=True, check=True).stdout


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    source = generate()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != source:
            raise SystemExit('Nat radix candidates are stale')
    else:
        DESTINATION.write_text(source)


if __name__ == '__main__':
    main()
