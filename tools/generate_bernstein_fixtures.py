#!/usr/bin/env python3
"""Independent Fraction oracle: expand basis in x, solve its linear system.

No power-to-Bernstein formula is used. Every fixture also checks a bounded
five-point-per-axis rational grid against the exact coefficient enclosure.
"""
from argparse import ArgumentParser
from fractions import Fraction as Q
from itertools import product
from math import comb
from pathlib import Path
import shutil
import subprocess


def basis_axis(a, b, n, i):
    terms = {}
    for r in range(i + 1):
        for s in range(n - i + 1):
            c = (Q(comb(n, i), 1) / (b-a)**n * comb(i, r) *
                 (-a)**(i-r) * comb(n-i, s) * b**(n-i-s) * (-1)**s)
            terms[r+s] = terms.get(r+s, Q(0)) + c
    return terms


def basis(box, degrees, index):
    parts = [basis_axis(a, b, n, i) for (a, b), n, i in zip(box, degrees, index)]
    terms = {}
    for items in product(*(list(p.items()) for p in parts)):
        exponent = tuple(e for e, _ in items)
        coefficient = Q(1)
        for _, c in items:
            coefficient *= c
        terms[exponent] = terms.get(exponent, Q(0)) + coefficient
    return terms


def solve(matrix, rhs):
    rows = [list(row) + [value] for row, value in zip(matrix, rhs)]
    for column in range(len(rows)):
        pivot = next(i for i in range(column, len(rows)) if rows[i][column])
        rows[column], rows[pivot] = rows[pivot], rows[column]
        divisor = rows[column][column]
        rows[column] = [x / divisor for x in rows[column]]
        for i, row in enumerate(rows):
            if i != column:
                multiplier = row[column]
                rows[i] = [x - multiplier*y for x, y in zip(row, rows[column])]
    return [row[-1] for row in rows]


def evaluate(terms, point):
    value = Q(0)
    for exponent, c in terms.items():
        for x, e in zip(point, exponent):
            c *= x**e
        value += c
    return value


def oracle(terms, box, degrees):
    indices = list(product(*(range(n+1) for n in degrees)))
    expanded = [basis(box, degrees, i) for i in indices]
    coefficients = solve([[p.get(e, Q(0)) for p in expanded] for e in indices],
                         [terms.get(e, Q(0)) for e in indices])
    # A second exact re-expansion checks the solved vector.
    for exponent in indices:
        assert sum((c*p.get(exponent, Q(0)) for c, p in zip(coefficients, expanded)), Q(0)) == terms.get(exponent, Q(0))
    for point in product(*([a+(b-a)*Q(i, 4) for i in range(5)] for a, b in box)):
        assert min(coefficients) <= evaluate(terms, point) <= max(coefficients)
    return coefficients


CASES = [
    ("zero", {}, [(Q(0), Q(1))], [0]),
    ("constant degree elevation", {(0, 0): Q(-7, 3)}, [(Q(-2), Q(3)), (Q(1, 2), Q(5, 2))], [2, 1]),
    ("xy cross term", {(1, 1): Q(1)}, [(Q(0), Q(1)), (Q(0), Q(1))], [1, 1]),
    ("positive needs subdivision", {(2,): Q(1), (1,): Q(-1), (0,): Q(3, 8)}, [(Q(0), Q(1))], [2]),
    ("negative nonunit boxes", {(3, 1): Q(2, 3), (1, 2): Q(-5, 7), (0, 0): Q(11, 9)}, [(Q(-2), Q(-1, 2)), (Q(-3, 2), Q(5, 2))], [3, 2]),
    ("higher degree elevated", {(4, 0): Q(1, 3), (2, 2): Q(-2), (0, 3): Q(3, 5), (0, 0): Q(1)}, [(Q(-1), Q(2)), (Q(0), Q(3, 2))], [4, 3]),
    ("zero dimensional", {(): Q(5, 4)}, [], []),
]


def qcode(q):
    return f"@oracle.rational({q.numerator}, {q.denominator})"


def array(items):
    return "[" + ", ".join(items) + "]"


def generate():
    lines = ["// Generated by tools/generate_bernstein_fixtures.py; independent Fraction oracle."]
    for name, terms, box, degrees in CASES:
        coefficients = oracle(terms, box, degrees)
        ts = array(f"({qcode(c)}, {list(e)})" for e, c in terms.items())
        bs = array(f"({qcode(a)}, {qcode(b)})" for a, b in box)
        lines.extend(["", "///|", f'test "Fraction oracle: {name}" {{',
                      f"  verify_fixture({len(box)}, {ts}, {bs}, {degrees},",
                      "    " + array(qcode(c) for c in coefficients) + ")", "}"])
    return "\n".join(lines) + "\n"


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "src/bernstein/fixtures_wbtest.mbt"
    local = root / ".tools/moon/bin/moonfmt"
    formatter = str(local) if local.is_file() else shutil.which("moonfmt")
    if formatter is None:
        raise SystemExit("moonfmt is required to canonicalize generated MoonBit fixtures")
    content = subprocess.run([formatter, "-"], input=generate(), text=True,
                             check=True, capture_output=True).stdout
    if args.check:
        if target.read_text() != content:
            raise SystemExit(f"stale Bernstein fixture: {target}")
    else:
        target.write_text(content)
    print(f"{len(CASES)} independently solved and grid-checked Bernstein fixtures")


if __name__ == "__main__":
    main()
