#!/usr/bin/env python3
"""Independent affine finite-extension oracle; no morph code is executed.

Pure host integer polynomial arithmetic, exhaustive point sets and addition tables.
--check compares all MoonBit tokens (allowing formatter whitespace) and exact JSON bytes.
"""
from argparse import ArgumentParser
from pathlib import Path
import gzip,json,sys,re


class Field:
    def __init__(self,p,modulus):
        self.p=p;self.modulus=tuple(modulus);self.degree=len(modulus)-1;self.q=p**self.degree
        assert modulus[-1]==1 and self.degree>0
        self.zero=(0,)*self.degree;self.one=(1,)+(0,)*(self.degree-1)
        self.values=[self.decode(i) for i in range(self.q)]
        for x in self.values[1:]:
            assert self.mul(x,self.power(x,self.q-2))==self.one, 'modulus is not a field'
    def decode(self,n):
        out=[]
        for _ in range(self.degree):out.append(n%self.p);n//=self.p
        assert n==0
        return tuple(out)
    def coefficients(self,x):
        v=list(x)
        while v and v[-1]==0:v.pop()
        return v
    def embed(self,x):return tuple((list(x)+[0]*self.degree)[:self.degree])
    def add(self,x,y):return tuple((a+b)%self.p for a,b in zip(x,y))
    def neg(self,x):return tuple(-a%self.p for a in x)
    def sub(self,x,y):return self.add(x,self.neg(y))
    def mul(self,x,y):
        a=[0]*(2*self.degree-1)
        for i,u in enumerate(x):
            for j,v in enumerate(y):a[i+j]=(a[i+j]+u*v)%self.p
        for k in range(len(a)-1,self.degree-1,-1):
            c=a[k]
            for j in range(self.degree):a[k-self.degree+j]=(a[k-self.degree+j]-c*self.modulus[j])%self.p
        return tuple(a[:self.degree])
    def power(self,x,n):
        result=self.one
        while n:
            if n&1:result=self.mul(result,x)
            x=self.mul(x,x);n>>=1
        return result
    def divide(self,x,y):
        if y==self.zero:raise ZeroDivisionError
        return self.mul(x,self.power(y,self.q-2))
    def times_int(self,x,n):return self.mul(x,self.decode(n%self.p))


def case(name,p,modulus,a,b,associativity):
    f=Field(p,modulus);a=f.embed(a);b=f.embed(b)
    disc=f.add(f.times_int(f.mul(f.mul(a,a),a),4),f.times_int(f.mul(b,b),27));assert disc!=f.zero
    def rhs(x):return f.add(f.add(f.mul(f.mul(x,x),x),f.mul(a,x)),b)
    points=[None]+[(x,y) for x in f.values for y in f.values if f.mul(y,y)==rhs(x)]
    index={point:i for i,point in enumerate(points)}
    def add(P,Q):
        if P is None:return Q
        if Q is None:return P
        x,y=P;u,v=Q
        if x==u and f.add(y,v)==f.zero:return None
        if x==u:
            assert y==v
            slope=f.divide(f.add(f.times_int(f.mul(x,x),3),a),f.times_int(y,2))
        else:slope=f.divide(f.sub(v,y),f.sub(u,x))
        xx=f.sub(f.sub(f.mul(slope,slope),x),u)
        yy=f.sub(f.mul(slope,f.sub(x,xx)),y)
        result=(xx,yy);assert result in index
        return result
    sums=[[index[add(P,Q)] for Q in points] for P in points]
    n=len(points);orders=[]
    for i in range(n):
        value=i;order=1
        while value:
            value=sums[value][i];order+=1;assert order<=n
        orders.append(order)
    for i in range(n):
        assert sums[0][i]==i and sums[i][0]==i
        assert any(sums[i][j]==0 for j in range(n))
        for j in range(n):
            assert sums[i][j]==sums[j][i]
            if associativity:
                for k in range(n):assert sums[sums[i][j]][k]==sums[i][sums[j][k]]
    large_index=max(range(1,n),key=lambda i:(orders[i],any(points[i][0][1:]),i))
    scalar=(1<<200)+17
    value=0;temp=large_index;remaining=scalar
    while remaining:
        if remaining&1:value=sums[value][temp]
        temp=sums[temp][temp];remaining>>=1
    return dict(name=name,p=p,modulus=modulus,a=f.coefficients(a),b=f.coefficients(b),points=[None if P is None else [f.coefficients(P[0]),f.coefficients(P[1])] for P in points],sums=sums,orders=orders,large_scalar=str(scalar),large_index=large_index,large_expected=value,associativity=associativity)


def data():
    cases=[case('gf25-base-coefficients',5,[2,0,1],[1],[1],True),case('gf25-extension-coefficients',5,[2,0,1],[0,1],[1,1],True),case('gf49-base-coefficients',7,[1,0,1],[1],[1],False)]
    f=Field(5,[2,0,1]);singular=[]
    for a in f.values:
        for b in f.values:
            d=f.add(f.times_int(f.mul(f.mul(a,a),a),4),f.times_int(f.mul(b,b),27));singular.append(d==f.zero)
    return dict(schema_version=1,oracle='independent Python affine arithmetic over integer polynomial residues',cases=cases,gf25_singularity=singular)


def arr(xs):return '['+', '.join(str(x) for x in xs)+']'


def render(d):
    out=['// Generated by tools/extension-curves-20261118-oracle.py; independent affine tables.','']
    for c in d['cases']:
        out+=['///|',f'test "host affine oracle {c["name"]}" {{','  ec_verify_case(',f'    {c["p"]},',f'    {arr(c["modulus"])},',f'    {arr(c["a"])},',f'    {arr(c["b"])},','    [']
        for P in c['points']:out.append('      None,' if P is None else f'      Some(({arr(P[0])}, {arr(P[1])})),')
        out+=['    ],','    [']
        out += [f'      {n},' for row in c['sums'] for n in row]
        out+=['    ],','    [']+[f'      {n},' for n in c['orders']]+['    ],',f'    {c["large_index"]},',f'    {c["large_expected"]},',f'    {str(c["associativity"]).lower()},','  )','}','','']
    out+=['///|','test "host oracle every coefficient pair singularity over gf25" {','  ec_verify_singularity([']+['    '+str(x).lower()+',' for x in d['gf25_singularity']]+['  ])','}','']
    return '\n'.join(out)


def main():
    parser=ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    root=Path(__file__).resolve().parents[1];fixture=root/'src/extensioncurve/host_fixtures_wbtest.mbt';receipt=root/'docs/research/extension-curves-20261118-oracle.json.gz'
    d=data();text=render(d);raw=(json.dumps(d,sort_keys=True,indent=2)+'\n').encode()
    if args.check:
        def tokens(source):
            return [token for token in re.findall(r'"(?:\\.|[^"\\])*"|//[^\n]*|\w+|[^\s]',source) if not token.startswith('//')]
        if not fixture.exists() or tokens(fixture.read_text())!=tokens(text):sys.exit('extension curve MoonBit fixture tokens differ; regenerate')
        if not receipt.exists() or gzip.decompress(receipt.read_bytes())!=raw:sys.exit('extension curve raw oracle differs; regenerate')
    else:
        fixture.write_text(text);receipt.parent.mkdir(parents=True,exist_ok=True);receipt.write_bytes(gzip.compress(raw,mtime=0))
    print(json.dumps({'cases':[{k:c[k] for k in ('name','p','modulus','associativity')}|{'points':len(c['points']),'pairs':len(c['points'])**2,'triples':len(c['points'])**3 if c['associativity'] else 0} for c in d['cases']],'singularity_pairs':len(d['gf25_singularity'])}))


if __name__=='__main__':main()
