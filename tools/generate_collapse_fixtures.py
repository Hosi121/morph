#!/usr/bin/env python3
"""Independent finite elementary-collapse oracle; no MoonBit implementation.

Enumerate all 167 complexes on subsets of four labelled vertices. Determine
free pairs by set containment, independently of checking closure after deletion.
Construct numeric boundary matrices and full integer chain contractions, with
explicit zero-dimensional matrix shapes, and verify all four identities.
The generated MoonBit fixtures also drive a second machine-array oracle in tests.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from itertools import combinations
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/collapse/fixtures_wbtest.mbt"


def closure(generators):
    return {s for g in generators for n in range(1, len(g) + 1)
            for s in combinations(g, n)}


def all_complexes():
    possible = [s for n in range(1, 5) for s in combinations(range(4), n)]
    for mask in range(1 << len(possible)):
        faces = {s for i, s in enumerate(possible) if mask & (1 << i)}
        if closure(faces) == faces:
            yield faces


def free_pairs(faces):
    return [(a, b) for a in sorted(faces) for b in sorted(faces)
            if len(b) == len(a) + 1 and set(a) < set(b)
            and [f for f in sorted(faces) if set(a) < set(f)] == [b]]


@dataclass(frozen=True)
class Matrix:
    rows: tuple[tuple[int, ...], ...]
    width: int

    def __post_init__(self):
        assert all(len(row) == self.width for row in self.rows)


def matrix(height, width, entry=lambda i, j: 0):
    return Matrix(tuple(tuple(entry(i, j) for j in range(width))
                        for i in range(height)), width)


def identity(n):
    return matrix(n, n, lambda i, j: int(i == j))


def multiply(a, b):
    assert a.width == len(b.rows)
    return matrix(len(a.rows), b.width,
                  lambda i, j: sum(a.rows[i][k] * b.rows[k][j]
                                   for k in range(a.width)))


def combine(a, b, sign=1):
    assert (len(a.rows), a.width) == (len(b.rows), b.width)
    return matrix(len(a.rows), a.width,
                  lambda i, j: a.rows[i][j] + sign * b.rows[i][j])


def basis(faces, k):
    return sorted(f for f in faces if len(f) == k + 1)


def boundary(faces, k):
    rows, columns = basis(faces, k - 1) if k else [], basis(faces, k)
    result = [[0] * len(columns) for _ in rows]
    for j, simplex in enumerate(columns):
        if k:
            for deleted in range(len(simplex)):
                result[rows.index(simplex[:deleted] + simplex[deleted + 1:])][j] = (-1) ** deleted
    return Matrix(tuple(tuple(row) for row in result), len(columns))


def contraction(faces, a, b):
    target = faces - {a, b}
    assert closure(target) == target
    epsilon = (-1) ** next(i for i in range(len(b)) if b[:i] + b[i + 1:] == a)
    maximum = max(map(len, faces), default=0)
    inclusions, projections, homotopies = [], [], []
    previous_h = matrix(len(basis(faces, 0)), 0)
    for k in range(maximum + 1):
        s, t, snext = basis(faces, k), basis(target, k), basis(faces, k + 1)
        h = matrix(len(snext), len(s), lambda i, j: epsilon if (snext[i], s[j]) == (b, a) else 0)
        i = matrix(len(s), len(t), lambda r, c: int(s[r] == t[c]))
        q = combine(combine(identity(len(s)), multiply(boundary(faces, k + 1), h), -1),
                    multiply(previous_h, boundary(faces, k)), -1)
        p = Matrix(tuple(q.rows[s.index(simplex)] for simplex in t), len(s))
        assert multiply(p, i) == identity(len(t))
        assert combine(identity(len(s)), multiply(i, p), -1) == combine(
            multiply(boundary(faces, k + 1), h), multiply(previous_h, boundary(faces, k)))
        previous_i = inclusions[-1] if k else matrix(0, 0)
        previous_p = projections[-1] if k else matrix(0, 0)
        assert multiply(boundary(target, k), p) == multiply(previous_p, boundary(faces, k))
        assert multiply(boundary(faces, k), i) == multiply(previous_i, boundary(target, k))
        inclusions.append(i)
        projections.append(p)
        homotopies.append(h)
        previous_h = h
    return target


def array(value):
    if isinstance(value, (tuple, list)):
        return "[" + ", ".join(array(x) for x in value) + "]"
    return str(value)


def render():
    complexes, pair_count, candidate_count = list(all_complexes()), 0, 0
    assert len(complexes) == 167
    lines = ["// Generated by tools/generate_collapse_fixtures.py; do not edit.",
             "///|", "fn collapse_fixtures() -> Array[(Array[Array[Int32]], Array[(Array[Int32], Array[Int32])])] {", "  ["]
    for faces in complexes:
        pairs = free_pairs(faces)
        candidate_count += len(faces) ** 2
        pair_count += len(pairs)
        for a, b in pairs:
            contraction(faces, a, b)
        facets = sorted(f for f in faces if not any(set(f) < set(g) for g in faces))
        encoded_pairs = "[" + ", ".join(f"({array(a)}, {array(b)})" for a, b in pairs) + "]"
        lines.append(f"    ({array(facets)}, {encoded_pairs}),")
    lines += ["  ]", "}", ""]
    return "\n".join(lines), pair_count, candidate_count


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatter = ROOT / ".tools/moon/bin/moonfmt"
    executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None:
        raise SystemExit("moonfmt is required to canonicalize generated fixtures")
    source, pair_count, candidate_count = render()
    content = subprocess.run([executable, "-"], input=source, text=True,
                             capture_output=True, check=True).stdout
    if args.check:
        assert OUTPUT.read_text() == content, f"stale fixture: {OUTPUT}"
    else:
        OUTPUT.write_text(content)
    print(f"167 complexes; {candidate_count} ordered candidates; {pair_count} elementary pairs; all integer contraction identities checked")


if __name__ == "__main__":
    main()
