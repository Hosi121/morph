#!/usr/bin/env python3
"""Exact Gaussian oracle: shift expansion + Wick pairings, not Stein recursion."""
from fractions import Fraction as Q
from functools import lru_cache
from itertools import product
from pathlib import Path
import argparse
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'src/gaussian/fixtures_wbtest.mbt'


def raw_moment(mean, covariance, powers):
    axes = tuple(i for i, power in enumerate(powers) for _ in range(power))

    @lru_cache(None)
    def centered(indices):
        if not indices:
            return Q(1)
        if len(indices) % 2:
            return Q(0)
        a, rest = indices[0], indices[1:]
        return sum((covariance[a][b] * centered(rest[:j] + rest[j+1:])
                    for j, b in enumerate(rest)), Q(0))

    result = Q(0)
    # Expand each X_i = mean_i + Z_i independently before pairing the Z's.
    for mask in range(1 << len(axes)):
        unpaired = Q(1)
        residual = []
        for j, axis in enumerate(axes):
            if mask & (1 << j):
                residual.append(axis)
            else:
                unpaired *= mean[axis]
        result += unpaired * centered(tuple(residual))
    return result


def fixture():
    examples = [
        ([Q(1,2)], [[Q(3,2)]], [(i,) for i in range(13)]),
        ([Q(1), Q(-1,2)], [[Q(2), Q(1,2)], [Q(1,2), Q(1)]],
         list(product(range(5), repeat=2)) + [(8,0),(0,8),(6,2)]),
        ([Q(0), Q(1,2), Q(-1,3)],
         [[Q(2),Q(1),Q(0)],[Q(1),Q(2),Q(1,2)],[Q(0),Q(1,2),Q(1)]],
         [p for p in product(range(7),repeat=3) if sum(p)<=6]),
    ]
    lines = ['// Generated by tools/generate_gaussian_fixtures.py; do not edit.', '']
    cases = 0
    for index, (mean, covariance, powers) in enumerate(examples):
        q = lambda value: f'q({value.numerator}, {value.denominator})'
        vector = lambda values: '@oracle.chain([' + ', '.join(map(q, values)) + '])'
        rows = '@oracle.chain([' + ', '.join(map(vector, covariance)) + '])'
        lines += ['///|', f'test "Wick pairing oracle Gaussian {index}" {{',
                  f'  let source = checked_gaussian({vector(mean)}, matrix({rows}, {len(mean)}))']
        for powers in powers:
            expected = raw_moment(mean, covariance, powers)
            n, d = expected.numerator, expected.denominator
            exponents = '@oracle.chain([' + ', '.join(f'@oracle.nat({a})' for a in powers) + '])'
            value = f'fraction("{abs(n):x}", {str(n<0).lower()}, "{d:x}")'
            lines += [f'  assert_eq(moment(source, {exponents}), Ok({value}))']
            cases += 1
        lines += ['}', '']
    return '\n'.join(lines) + '\n', cases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count = fixture()
    content = subprocess.run([str(ROOT / '.tools/moon/bin/moonfmt'), '-'],
                             input=content, text=True, check=True,
                             capture_output=True).stdout
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Gaussian fixtures are stale')
        print(f'Gaussian Wick oracle: {count} complete moments, formatted bytes verified.')
    else:
        OUTPUT.write_text(content)
        print(f'Generated {count} complete moments.')


if __name__ == '__main__':
    main()
