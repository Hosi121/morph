#!/usr/bin/env python3
"""Independent SymPy multiplication-characteristic polynomial and real image oracle.
Minimal polynomial = squarefree part of regular-representation charpoly in a field.
Root selection uses Fraction termwise power intervals, not MoonBit's Horner image.
"""
from pathlib import Path
from fractions import Fraction as F
import subprocess,json,sys
import sympy as sp
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'.tools/numberfield-20261116/fraction-fixtures.json'
if not source.exists():subprocess.run([sys.executable,str(ROOT/'tools/generate_numberfield_fixtures.py')],cwd=ROOT,check=True)
data=json.loads(source.read_text());x=sp.Symbol('x')
def fs(a):return [F(*c) for c in a]
def expr(a):return sum((sp.Rational(c.numerator,c.denominator)*x**i for i,c in enumerate(a)),sp.Integer(0))
def arr(a):return '['+', '.join(f'({c.numerator}, {c.denominator})' for c in a)+']'
def pair(c):return f'({c.numerator}, {c.denominator})'
def pairs(a):return [(c.numerator,c.denominator) for c in a]
def image(a,lo,hi):
 lower=upper=F(0)
 for i,c in enumerate(a):
  if i%2:
   left,right=lo**i,hi**i
  else:
   left=F(0) if lo<=0<=hi and i else min(lo**i,hi**i)
   right=max(lo**i,hi**i)
  if c<0:left,right=right,left
  lower+=c*left;upper+=c*right
 return lower,upper
lines=['// Generated by tools/generate_numberfield_real_fixtures.py; independent charpoly/interval oracle.',''];records=[]
for i,record in enumerate(data['cases']):
 m=fs(record['modulus']);a=fs(record['a']);reduced=fs(record['residue'])
 matrix=sp.Matrix([[sp.Rational(n,d) for n,d in row] for row in record['matrix']])
 characteristic=matrix.charpoly(x).as_poly();minimal=characteristic.sqf_part().monic()
 assert minimal.is_irreducible
 cs=[F(int(c.p),int(c.q)) for c in reversed(minimal.all_coeffs())]
 mp=sp.Poly(expr(m),x);lo,hi=map(F,record['interval']);padding=F(1)
 for attempt in range(256):
  lower,upper=image(reduced,lo,hi);lower-=padding;upper+=padding
  if minimal.count_roots(sp.Rational(lower.numerator,lower.denominator),sp.Rational(upper.numerator,upper.denominator))==1:break
  midpoint=(lo+hi)/2
  if mp.count_roots(sp.Rational(lo.numerator,lo.denominator),sp.Rational(midpoint.numerator,midpoint.denominator))==1:hi=midpoint
  else:lo=midpoint
  padding/=2
 else:raise AssertionError('independent interval did not isolate')
 # Direct expression minpoly check for a small separate known-root subset.
 alpha=[sp.Integer(0),sp.Integer(2),sp.sqrt(2),(1+sp.sqrt(5))/2,sp.real_root(2,3),sp.CRootOf(x**3-x-1,0),sp.sqrt(2)+sp.sqrt(3),sp.sqrt(2)/2][record['family']]
 direct_checked=i%8 in (1,2)
 if direct_checked:
  direct=sp.Poly(sp.minimal_polynomial(expr(reduced).subs(x,alpha),x),x,domain=sp.QQ).monic()
  assert direct==sp.Poly(minimal,x,domain=sp.QQ)
 assert all(abs(n)<2**63 and 0<d<2**63 for n,d in pairs(cs)+pairs([lower,upper])), 'test adapter Int64 range'
 records.append(dict(source=i,minimal=pairs(cs),lower=pairs([lower])[0],upper=pairs([upper])[0],refinements=attempt,direct_sympy_minpoly=direct_checked))
 lines+=['///|',f'test "Independent number field minimal polynomial and real root fixture {i}" {{',
  f'  assert_real_fixture({arr(m)}, ({record["interval"][0]}, 1), ({record["interval"][1]}, 1),',
  f'    {arr(a)}, {arr(cs)}, {pair(lower)}, {pair(upper)})','}','']
path=ROOT/'src/numberfield/real_oracle_wbtest.mbt';path.write_text('\n'.join(lines))
subprocess.run([str(ROOT/'tools/moon'),'fmt',str(path)],cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
(ROOT/'.tools/numberfield-20261116/real-fixtures.json').write_text(json.dumps(dict(oracle='SymPy regular multiplication charpoly squarefree part; Fraction termwise power image; exact SymPy root counts',sympy=sp.__version__,direct_minpoly_checks=sum(r['direct_sympy_minpoly'] for r in records),cases=records),indent=2)+'\n')
print(f'generated {len(records)} independent minimal polynomial/selected-real-root fixtures; {sum(r["direct_sympy_minpoly"] for r in records)} direct SymPy minpoly checks')
