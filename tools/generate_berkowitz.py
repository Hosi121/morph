#!/usr/bin/env python3
"""Fraction/Leibniz oracle; no characteristic-polynomial library or Berkowitz."""
from fractions import Fraction as Q
from itertools import permutations
from pathlib import Path
import argparse
import json
import random
import re

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "src/berkowitz/leibniz_wbtest.mbt"


def plus(p, q):
    out = [Q(0)] * max(len(p), len(q))
    for i, x in enumerate(p):
        out[i] += x
    for i, x in enumerate(q):
        out[i] += x
    return out


def times(p, q):
    out = [Q(0)] * (len(p) + len(q) - 1)
    for i, x in enumerate(p):
        for j, y in enumerate(q):
            out[i+j] += x*y
    return out


def sign(perm):
    return (-1) ** sum(perm[i] > perm[j]
                       for i in range(len(perm)) for j in range(i+1, len(perm)))


def det(a):
    n = len(a)
    result = Q(0)
    for perm in permutations(range(n)):
        value = Q(sign(perm))
        for i, j in enumerate(perm):
            value *= a[i][j]
        result += value
    return result


def characteristic(a):
    n = len(a)
    result = [Q(0)] * (n+1)
    for perm in permutations(range(n)):
        term = [Q(sign(perm))]
        for i, j in enumerate(perm):
            term = times(term, [-a[i][j], Q(i == j)])
        result = plus(result, term)
    return list(reversed(result))


def adjugate(a):
    return [[(-1)**(i+j)*det([[a[r][c] for c in range(len(a)) if c != i]
                             for r in range(len(a)) if r != j])
             for j in range(len(a))] for i in range(len(a))]


def pair(q):
    return f"({q.numerator}, {q.denominator})"


def row(xs):
    return "[" + ", ".join(map(pair, xs)) + "]"


def matrix(rows):
    return "[" + ", ".join(map(row, rows)) + "]"


def tokens(source):
    # Commas and whitespace are the only changes made by moon fmt here.
    return re.findall(r'"(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z_0-9]*|[0-9]+|[^\s,]', source)


def generate():
    rng = random.Random(20261116)
    cases = [[]]
    for n in range(1, 7):
        for k in range(12):
            denominator = 1 + k % 3
            a = [[Q(rng.randrange(-3, 4), denominator) for _ in range(n)]
                 for _ in range(n)]
            if k == 0:
                a = [[Q(0)]*n for _ in range(n)]
            if k == 1:
                a[-1] = list(a[0])
            cases.append(a)
    out = ["// Generated by tools/generate_berkowitz.py; Fraction/Leibniz oracle.", ""]
    records = []
    for index, a in enumerate(cases):
        p, adj = characteristic(a), adjugate(a)
        assert p[-1] == (-1)**len(a) * det(a)
        out += ["///|", f'test "Leibniz characteristic and cofactor oracle {index}" {{',
                f"  assert_leibniz_fixture({matrix(a)}, {row(p)}, {matrix(adj)})", "}", ""]
        records.append({"dimension":len(a), "matrix":[[str(x) for x in r] for r in a],
                        "characteristic":list(map(str,p)),
                        "adjugate":[[str(x) for x in r] for r in adj]})
    return "\n".join(out), records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, records = generate()
    if args.check:
        if not DEST.exists() or tokens(DEST.read_text()) != tokens(source):
            raise SystemExit("Berkowitz Leibniz fixtures drifted")
    else:
        DEST.write_text(source)
    artifacts = ROOT / ".tools/berkowitz-20261116"
    artifacts.mkdir(parents=True, exist_ok=True)
    (artifacts / "leibniz-oracle.json").write_text(json.dumps({
        "oracle":"stdlib Fraction polynomial determinant by signed permutations and adjugate by cofactors",
        "cases":records}, indent=2)+"\n")
    print(f"{'checked' if args.check else 'generated'} {len(records)} independent characteristic/adjugate fixtures")


if __name__ == "__main__":
    main()
