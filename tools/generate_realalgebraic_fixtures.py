#!/usr/bin/env python3
"""Independent exact SymPy resultant/minimal-polynomial/isolating fixtures."""
from argparse import ArgumentParser
from pathlib import Path
import json
import subprocess
import sympy as sp
ROOT=Path(__file__).resolve().parents[1]
x,y=sp.symbols('x y')
def coeffs(p): return [sp.Rational(c) for c in reversed(sp.Poly(p,x).all_coeffs())]
def data(p): return [[int(c.p),int(c.q)] for c in coeffs(p)]
def literal(p): return '['+', '.join(f'({a}, {b})' for a,b in data(p))+']'
def ratio(c):
 c=sp.Rational(c)
 return [int(c.p),int(c.q)]
def qliteral(c):
 a,b=ratio(c)
 return f'({a}, {b})'
def interval(expr,p):
 for (lo,hi),_ in sp.Poly(p,x).intervals(eps=sp.Rational(1,8)):
  if lo==hi:
   padding=sp.Rational(1,8)
   while sp.Poly(p,x).count_roots(lo-padding,hi)!=1 or sp.Poly(p,x).eval(lo-padding)==0: padding/=2
   lo-=padding
  if sp.sign(expr-lo)==1 and sp.sign(hi-expr) in (0,1):
   assert sp.Poly(p,x).count_roots(lo,hi)==1
   return lo,hi
 raise AssertionError(('exact interval selection failed',expr,p))
def root(expr):
 p=sp.minpoly(expr,x)
 lo,hi=interval(expr,p)
 assert sp.simplify(p.subs(x,expr))==0
 return p,lo,hi

def generate():
 cases=[(x*x-2,x*x-3),(x*x-2,x*x-2),(2*x*x-3,3*x-2),(x*x-2,x**3-x),(x,x),(x*x-x,x*x+x),(2*x**3+x-1,3*x*x+x+2)]
 lines=['// Generated by tools/generate_realalgebraic_fixtures.py; independent exact SymPy oracles.','']
 records=[]
 for i,(p,q) in enumerate(cases):
  p=sp.Poly(p,x).monic().as_expr();q=sp.Poly(q,x).monic().as_expr()
  n=sp.degree(q,x)
  for operation in ['Sum','Product']:
   transformed=q.subs(x,x-y) if operation=='Sum' else sp.cancel(y**n*q.subs(x,x/y)).expand()
   r=sp.resultant(p.subs(x,y),transformed,y).expand()
   assert sp.degree(r,x)==sp.degree(p,x)*sp.degree(q,x)
   records.append(dict(left=data(p),right=data(q),operation=operation,result=data(r)))
   lines+=['///|',f'test "SymPy interpolated resultant {i} {operation}" {{',f'  assert_resultant_fixture({literal(p)}, {literal(q)}, {operation}, {literal(r)})','}','']
 pairs=[(sp.sqrt(2),sp.sqrt(3)),(sp.sqrt(2),sp.sqrt(2)),(sp.sqrt(2),-sp.sqrt(2)),
        (-sp.sqrt(2),sp.sqrt(3)),(-sp.sqrt(2),-sp.sqrt(3)),
        (sp.Rational(-5,3),sp.Rational(7,4)),(sp.Integer(0),sp.sqrt(2)),
        (sp.sqrt(sp.Rational(1,2)),-sp.sqrt(sp.Rational(1,3))),
        (sp.real_root(2,3),sp.sqrt(3)),(sp.sqrt(2),sp.sqrt(sp.Rational(2049,1024)))]
 arithmetic=[]
 for i,(a,b) in enumerate(pairs):
  p,al,au=root(a);q,bl,bu=root(b)
  operations=[('Sum',a+b),('Product',a*b),('Quotient',a/b)]
  for operation,expr in operations:
   r,lo,hi=root(sp.simplify(expr))
   record=dict(left=dict(expression=str(a),polynomial=data(p),lower=ratio(al),upper=ratio(au)),right=dict(expression=str(b),polynomial=data(q),lower=ratio(bl),upper=ratio(bu)),operation=operation,result=dict(expression=str(expr),polynomial=data(r),lower=ratio(lo),upper=ratio(hi)))
   arithmetic.append(record)
   operation_literal="None" if operation=="Quotient" else f"Some({operation})"
   lines+=['///|',f'test "SymPy exact algebraic arithmetic {i} {operation}" {{',
           f'  assert_algebraic_fixture({literal(p)}, {qliteral(al)}, {qliteral(au)},',
           f'    {literal(q)}, {qliteral(bl)}, {qliteral(bu)}, {operation_literal},',
           f'    {literal(r)}, {qliteral(lo)}, {qliteral(hi)})','}','']
 unary=[]
 for i,a in enumerate([sp.sqrt(2),-sp.sqrt(3),sp.Rational(1,2),sp.Rational(-5,3),sp.real_root(2,3),sp.Integer(0)]):
  p,al,au=root(a)
  for operation,expr in [('Negation',-a)]+([('Reciprocal',1/a)] if a!=0 else []):
   r,lo,hi=root(expr)
   unary.append(dict(input=str(a),operation=operation,result=str(expr),polynomial=data(r),lower=ratio(lo),upper=ratio(hi)))
   lines+=['///|',f'test "SymPy exact algebraic unary {i} {operation}" {{',f'  assert_unary_fixture({literal(p)}, {qliteral(al)}, {qliteral(au)}, {operation},',f'    {literal(r)}, {qliteral(lo)}, {qliteral(hi)})','}','']
 text=subprocess.run([str(ROOT/'.tools/moon/bin/moonfmt'),'-'],input='\n'.join(lines),text=True,capture_output=True,check=True).stdout
 stats=dict(resultants=len(records),arithmetic=len(arithmetic),unary=len(unary))
 return {ROOT/'src/realalgebraic/fixtures_wbtest.mbt':text,ROOT/'docs/research/realalgebraic-20261116-fixtures.json':json.dumps(dict(sympy=sp.__version__,statistics=stats,resultants=records,arithmetic=arithmetic,unary=unary),indent=2)+'\n'},stats

def main():
 parser=ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 artifacts,stats=generate()
 for path,text in artifacts.items():
  if args.check:
   if not path.exists() or path.read_text()!=text: raise SystemExit(f'Stale artifact: {path.relative_to(ROOT)}')
  else:path.write_text(text)
 print(json.dumps(stats,sort_keys=True))
if __name__=='__main__':main()
