#!/usr/bin/env python3
"""Independent Python integer fixtures for compressed binary arithmetic."""
from pathlib import Path
import random
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def main():
    rng = random.Random(121)
    cases = []
    for width in (32, 64, 128, 256, 512):
        for _ in range(3):
            a, b = rng.getrandbits(width), rng.getrandbits(width)
            cases.append((a, b, rng.randrange(width + 4)))
    cases.extend(((2**128 - 1, 3, 64), (2**256 + 2**123 + 9, 97, 130),
                  (2**512 - 1, 2**255 + 3, 256)))
    lines = ["// Generated by tools/generate_runbinary.py; Python big-integer oracle.",
             'test "independent Python integer fixtures through 512 bits" {']
    for a, b, shift in cases:
        h = lambda n: f'@oracle.binary_from_hex("{n:x}")'
        lines += ["  {", f"    let a = from_binary({h(a)})", f"    let b = from_binary({h(b)})"]
        for actual, expected in (("add(a, b)", a+b), ("multiply(a, b)", a*b),
                                 (f"shift_left(a, @oracle.binary({shift}))", a << shift),
                                 (f"shift_right(a, @oracle.binary({shift}))", a >> shift)):
            lines.append(f"    assert_eq(expand({actual}, @oracle.binary(2048)), Some({h(expected)}))")
        expected_sub = "None" if a < b else f"Some(from_binary({h(a-b)}))"
        lines += [f"    assert_eq(subtract(a, b), {expected_sub})"]
        if b:
            lines += ["    match run_division(start_division(a, b).unwrap(), @oracle.nat(2048)) {",
                      "      Divided(result) => {",
                      f"        assert_eq(expand(quotient(result), @oracle.binary(2048)), Some({h(a//b)}))",
                      f"        assert_eq(expand(remainder(result), @oracle.binary(2048)), Some({h(a%b)}))",
                      "      }", '      _ => fail("Python division fixture did not finish")', "    }"]
        lines += ["  }"]
    lines += ["}", ""]
    destination = ROOT / "src/runbinary/oracle_wbtest.mbt"
    destination.write_text("\n".join(lines))
    subprocess.run([str(ROOT / "tools/moon"), "fmt", str(destination)], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
