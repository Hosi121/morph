#!/usr/bin/env python3
"""Committed discrete-log fixtures from Python pow and finite enumeration.

Prime certificate construction reuses the independent integer fixture builder;
normal MoonBit tests only consume the emitted trees and expected exponents.
"""
from pathlib import Path
from generate_primality import certificate, descendants

ROOT = Path(__file__).resolve().parent.parent
CASES = [
    (65537, 3, 10000, 10000),
    (65537, 3, 10000, 10001),
    (65537, 3, 10000, 16384),
    (998244353, 3, 50000, 65536),
    (2305843009213693951, 37, 3456, 4096),
]


def numeral(n: int) -> str:
    return f'@oracle.binary_from_hex("{n:x}")'


def chain(items: list[str]) -> str:
    result = 'Nil'
    for item in reversed(items):
        result = f'Cons({item}, {result})'
    return result


def least_log(p: int, g: int, h: int, bound: int) -> int | None:
    value = 1
    for exponent in range(bound):
        if value == h:
            return exponent
        value = value * g % p
    return None


def main() -> None:
    primes = {p for p, _, _, _ in CASES}
    needed = sorted({q for p in primes for q in descendants(p)})
    out = '// Generated by tools/generate_discretelog.py; Python integer oracle.\n'
    for p in needed:
        a, fs = certificate(p)
        expression = 'Two' if p == 2 else (
            f'Lucas({numeral(p)}, {numeral(a)}, '
            f'{chain([f"log_prime_{q}()" for q in fs])})')
        out += f'///|\nfn log_prime_{p}() -> @primality.Certificate {{\n  {expression}\n}}\n\n'
    out += '///|\ntest "multi-digit bounded logarithms match committed Python enumeration" {\n'
    for p, g, e, bound in CASES:
        h = pow(g, e, p)
        expected = least_log(p, g, h, bound)
        out += f'  let prime = @primality.check(log_prime_{p}()).unwrap()\n'
        out += '  let field = @primefield.from_prime(prime).unwrap()\n'
        out += f'  let instance = problem(field, {numeral(g)}, {numeral(h)}, {numeral(bound)}).unwrap()\n'
        expected_expr = 'None' if expected is None else f'Some({numeral(expected)})'
        out += f'  assert_eq(baby_step_giant_step(instance).map(exponent), {expected_expr})\n'
        if expected is not None:
            out += f'  assert_eq(@modular.power(@primefield.modulus(field), {numeral(g)}, {numeral(expected)}), {numeral(h)})\n'
    out += '}\n'
    (ROOT / 'src/discretelog/vectors_wbtest.mbt').write_text(out)


if __name__ == '__main__':
    main()
