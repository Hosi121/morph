#!/usr/bin/env python3
"""Exact SymPy radical roots, resultants and Fraction quadratic-field oracle."""
from pathlib import Path
from argparse import ArgumentParser
from fractions import Fraction as F
import json, subprocess
import sympy as sp
ROOT=Path(__file__).resolve().parents[1]
a,y=sp.symbols('a y')
def pair(c,d):
 p=sp.Poly(c,a).rem(sp.Poly(a*a-d,a));return tuple(int(p.nth(i)) for i in (0,1))
def sign(expr):
 s=sp.sign(sp.simplify(expr));assert s in (-1,0,1),(expr,s);return int(s)
def add(p,q):return (p[0]+q[0],p[1]+q[1])
def neg(p):return (-p[0],-p[1])
def mul(p,q,d):return (p[0]*q[0]+d*p[1]*q[1],p[0]*q[1]+p[1]*q[0])
def inv(p,d):
 z=p[0]*p[0]-d*p[1]*p[1];assert z;return (p[0]/z,-p[1]/z)
def trim(p):
 p=list(p)
 while p and p[-1]==(0,0):p.pop()
 return p
def div(p,q,d):
 p=trim(p);q=trim(q);out=[(F(0),F(0))]*max(0,len(p)-len(q)+1)
 while p and len(p)>=len(q):
  k=len(p)-len(q);c=mul(p[-1],inv(q[-1],d),d);out[k]=c
  for i,t in enumerate(q):p[i+k]=add(p[i+k],neg(mul(c,t,d)))
  p=trim(p)
 return trim(out),p
def prs(p,d):
 derivative=[(i*c[0],i*c[1]) for i,c in enumerate(p)][1:]
 out=[p]
 while derivative:
  out.append(derivative);_,r=div(p,derivative,d);p,derivative=derivative,[neg(c) for c in r]
 return out
def fraction_rows(seq):
 return "["+", ".join("["+", ".join("("+", ".join(map(str,(c[0].numerator,c[0].denominator,c[1].numerator,c[1].denominator)))+")" for c in row)+"]" for row in seq)+"]"
def literal(cs):return '['+', '.join('('+', '.join(map(str,c))+')' for c in cs)+']'
def ints(xs):return '['+', '.join(map(str,xs))+']'
def generate():
 lines=['// Generated by tools/generate_orderedsturm_fixtures.py. Exact branch roots and norm resultants.',''];records=[]
 for d in [2,3]:
  for negative in [False,True]:
   alpha=(-1 if negative else 1)*sp.sqrt(d)
   specs=[(y*y-a,[-sp.sqrt(alpha),sp.sqrt(alpha)] if sign(alpha)>0 else [],'quadratic relative'),((y*y-a)**2,[-sp.sqrt(alpha),sp.sqrt(alpha)] if sign(alpha)>0 else [],'repeated relative'),(y**3-a,[sp.real_root(alpha,3)],'cubic relative'),(y-a-1,[alpha+1],'linear algebraic'),((y-a)*(y+a),[-alpha,alpha],'conjugate field roots'),((y-1)**3*(y+a),[sp.Integer(1),-alpha],'repeated rational endpoint'),((y*y-a-2)*(y-a),[-sp.sqrt(alpha+2),sp.sqrt(alpha+2),alpha],'mixed radical'),(y*y+a*a+1,[],'no real root'),(sp.Integer(-3),[],'constant'),(y*(y-a),[sp.Integer(0),alpha],'zero endpoint')]
   for expression,roots,kind in specs:
    roots=list(dict.fromkeys(map(sp.simplify,roots)))
    cs=[pair(c,d) for c in reversed(sp.Poly(sp.expand(expression),y).all_coeffs())]
    # Independent Fraction field Euclidean oracle verifies square-free degree.
    p=[tuple(map(F,c)) for c in cs];seq=prs(p,d);g=seq[-1];sf,_=div(p,g,d)
    assert len(roots)<=len(sf)-1
    sf=[mul(c,inv(sf[-1],d),d) for c in sf]
    expected_sequence=prs(sf,d)
    norm=sp.Poly(sp.resultant(a*a-d,expression,a),y)
    normcs=[int(c) for c in reversed(norm.all_coeffs())]
    for r in roots:assert sp.simplify(norm.as_expr().subs(y,r))==0
    queries=[]
    for lo,hi in [(-5,5),(-1,0),(0,1),(1,3),(-3,-1)]:
     expected=sum(sign(r-lo)>0 and sign(r-hi)<=0 for r in roots);queries.append((lo,hi,expected))
    i=len(records)
    lines+=['///|',f'test "independent ordered field roots {i} {kind}" {{',f'  test_fixture({d}, {str(negative).lower()}, {literal(cs)}, {literal(queries)}, {len(roots)}, {ints(normcs)}, {fraction_rows(expected_sequence)})','}','']
    records.append(dict(d=d,embedding='negative' if negative else 'positive',kind=kind,coefficients=cs,exact_distinct_real_roots=list(map(str,roots)),relative_squarefree_degree=len(sf)-1,queries=queries,norm_resultant=normcs,fraction_sturm_sequence=[[[str(c[0]),str(c[1])] for c in row] for row in expected_sequence]))
 output=subprocess.run([str(ROOT/'.tools/moon/bin/moonfmt'),'-'],input='\n'.join(lines),text=True,capture_output=True,check=True).stdout
 stats=dict(cases=len(records),half_open_queries=sum(len(c['queries']) for c in records),relative_roots=sum(len(c['exact_distinct_real_roots']) for c in records),quadratic_field_fraction_prs=len(records),norm_resultants=len(records))
 return {ROOT/'src/orderedsturm/fixtures_wbtest.mbt':output,ROOT/'docs/research/orderedsturm-20261116-fixtures.json':json.dumps(dict(sympy=sp.__version__,statistics=stats,cases=records),indent=2)+'\n'},stats

