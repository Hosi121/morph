#!/usr/bin/env python3
"""Generate exact dense-basis fixtures independently of MoonBit polynomial code.

Only Python's Fraction and dense arrays are used. Inverses solve the rational
multiplication matrix with Gauss-Jordan elimination, rather than polynomial
extended Euclid. The seed and fixture count are fixed for reproducibility.
"""
from fractions import Fraction
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parent.parent


def multiply(a, b):
    d = len(a)
    result = [Fraction(0)] * d
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            result[(i + j) % d] += x * y * (-1 if i + j >= d else 1)
    return result


def inverse(a):
    d = len(a)
    columns = []
    for j in range(d):
        basis = [Fraction(i == j) for i in range(d)]
        columns.append(multiply(a, basis))
    matrix = [[columns[j][i] for j in range(d)] + [Fraction(i == 0)] for i in range(d)]
    for j in range(d):
        pivot = next(i for i in range(j, d) if matrix[i][j])
        matrix[j], matrix[pivot] = matrix[pivot], matrix[j]
        scalar = matrix[j][j]
        matrix[j] = [x / scalar for x in matrix[j]]
        for i in range(d):
            if i != j:
                scalar = matrix[i][j]
                matrix[i] = [x - scalar * y for x, y in zip(matrix[i], matrix[j])]
    answer = [row[-1] for row in matrix]
    assert multiply(a, answer) == [Fraction(i == 0) for i in range(d)]
    return answer


def conjugate(a):
    # For d>1, zeta^(-j) = -zeta^(d-j) at 0<j<d.
    return [a[0]] + [-a[-j] for j in range(1, len(a))]


def literal(values):
    for value in values:
        assert abs(value.numerator) < 2**31 and value.denominator < 2**31
    return "[" + ", ".join(f"({x.numerator}, {x.denominator})" for x in values) + "]"


def shift(values, exponent, field_order):
    if field_order == 1:
        return values[:]
    d = len(values)
    result = [Fraction(0)] * d
    for i, value in enumerate(values):
        quotient, remainder = divmod(i + exponent, d)
        result[remainder] += value * (-1 if quotient % 2 else 1)
    return result


def direct_dft(values, field_order, inverse=False):
    n = len(values)
    d = len(values[0])
    step = (field_order // n) * (-1 if inverse else 1)
    result = []
    for k in range(n):
        row = [Fraction(0)] * d
        for j, value in enumerate(values):
            row = [a + b for a, b in zip(row, shift(value, step * j * k, field_order))]
        result.append([x / n for x in row] if inverse else row)
    return result


def fft_fixtures():
    rng = random.Random(20261116)
    lines = ["// Generated by tools/generate_cyclotomic.py; exact dense Fraction DFT oracle."]
    cases = [(1, 1), (2, 2), (4, 4), (8, 8), (16, 16), (8, 4), (16, 8), (8, 1)]
    for field_order, n in cases:
        d = max(1, field_order // 2)
        values = [[Fraction(rng.randrange(-2, 3), rng.randrange(1, 4)) for _ in range(d)] for _ in range(n)]
        expected = direct_dft(values, field_order)
        assert direct_dft(expected, field_order, inverse=True) == values
        lines += ["", "///|", f'test "independent Fraction DFT of size {n} in field order {field_order}" {{', "  assert_dft_fixture(", f"    {field_order}, {n},"]
        for data in [values, expected]:
            lines += ["    ["] + [f"      {literal(row)}," for row in data] + ["    ],"]
        lines += ["  )", "}"]
    path = ROOT / "src/exactfft/oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(cases)} exact DFT fixtures to {path.relative_to(ROOT)}")


def main():
    rng = random.Random(20261115)
    lines = ["// Generated by tools/generate_cyclotomic.py; Python Fraction matrix oracle."]
    count = 0
    for n in [1, 2, 4, 8, 16]:
        d = max(1, n // 2)
        lines += ["", "///|", f'test "independent dense Fraction oracle at order {n}" {{']
        for _ in range(4):
            a = [Fraction(rng.randrange(-2, 3), rng.randrange(1, 4) if n <= 8 else 1) for _ in range(d)]
            b = [Fraction(rng.randrange(-2, 3), rng.randrange(1, 4) if n <= 8 else 1) for _ in range(d)]
            if not any(a):
                a[0] = Fraction(1)
            values = [a, b, multiply(a, b), inverse(a), conjugate(a)]
            lines += [f"  assert_fixture({n},"] + [f"    {literal(value)}," for value in values] + ["  )"]
            count += 1
        lines += ["}"]
    path = ROOT / "src/cyclotomic/oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {count} exact product/inverse/conjugation fixtures to {path.relative_to(ROOT)}")
    fft_fixtures()


if __name__ == "__main__":
    main()
