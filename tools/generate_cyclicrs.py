"""Independent Fraction/native polynomial oracles for recurrence and cyclic RS."""
from fractions import Fraction
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parent.parent


def consistent(sequence, length):
    rows = [[sequence[n-i] for i in range(1, length+1)] + [-sequence[n]] for n in range(length, len(sequence))]
    pivot = 0
    for column in range(length):
        found = next((i for i in range(pivot, len(rows)) if rows[i][column]), None)
        if found is None:
            continue
        rows[pivot], rows[found] = rows[found], rows[pivot]
        scalar = rows[pivot][column]
        rows[pivot] = [x / scalar for x in rows[pivot]]
        for i in range(len(rows)):
            if i != pivot:
                scalar = rows[i][column]
                rows[i] = [x - scalar*y for x, y in zip(rows[i], rows[pivot])]
        pivot += 1
    return all(any(row[:length]) or not row[-1] for row in rows)


