class NativeField:
    def __init__(self, p, modulus):
        self.p, self.modulus = p, modulus
        self.width = len(modulus) - 1
        self.size = p**self.width
        self.binary_modulus = sum(x << i for i, x in enumerate(modulus))

    def digits(self, value):
        result = []
        for _ in range(self.width):
            result.append(value % self.p)
            value //= self.p
        return result

    def encode(self, coefficients):
        return sum((x % self.p) * self.p**i for i, x in enumerate(coefficients))

    def add(self, a, b):
        return a ^ b if self.p == 2 else self.encode([x+y for x, y in zip(self.digits(a), self.digits(b))])

    def negate(self, a):
        return a if self.p == 2 else self.encode([-x for x in self.digits(a)])

    def multiply(self, a, b):
        if self.p == 2:
            result = 0
            while b:
                if b & 1:
                    result ^= a
                b >>= 1
                a <<= 1
                if a & self.size:
                    a ^= self.binary_modulus
            return result
        result = [0] * (self.width*2-1)
        for i, x in enumerate(self.digits(a)):
            for j, y in enumerate(self.digits(b)):
                result[i+j] += x*y
        for exponent in range(len(result)-1, self.width-1, -1):
            scalar = result[exponent] % self.p
            for j, coefficient in enumerate(self.modulus):
                result[exponent-self.width+j] -= scalar*coefficient
        return self.encode(result[:self.width])

    def power(self, a, exponent):
        result = 1
        while exponent:
            if exponent & 1:
                result = self.multiply(result, a)
            a = self.multiply(a, a)
            exponent >>= 1
        return result

    def product(self, a, b):
        if not a or not b:
            return []
        result = [0] * (len(a)+len(b)-1)
        for i, x in enumerate(a):
            for j, y in enumerate(b):
                result[i+j] = self.add(result[i+j], self.multiply(x, y))
        return result

    def evaluate(self, polynomial, point):
        result = 0
        for coefficient in reversed(polynomial):
            result = self.add(coefficient, self.multiply(point, result))
        return result


def trim(values):
    values = values[:]
    while values and not values[-1]:
        values.pop()
    return values


def rs_fixtures():
    rng = random.Random(202611152)
    specifications = [
        (2, [1, 1, 1], 2, 3, 3, 1, [2], [3]),
        (2, [1, 1, 0, 0, 1], 2, 15, 15, 2, [], []),
        (2, [1, 1, 0, 0, 1], 2, 15, 15, 2, [0], [15]),
        (2, [1, 1, 0, 0, 1], 2, 15, 15, 2, [14], [7]),
        (2, [1, 1, 0, 0, 1], 2, 15, 15, 2, [0, 14], [1, 2]),
        (2, [1, 1, 0, 0, 1], 2, 15, 11, 2, [0, 10], [15, 6]),
        (3, [1, 0, 1], 4, 8, 8, 2, [0, 7], [1, 8]),
        (3, [1, 0, 1], 4, 8, 8, 2, [2, 6], [3, 7]),
        (7, [0, 1], 3, 6, 6, 1, [5], [6]),
        (2, [1, 0, 1, 1, 1, 0, 0, 0, 1], 2, 255, 255, 2, [0, 254], [83, 202]),
        (2, [1, 0, 1, 1, 1, 0, 0, 0, 1], 2, 255, 255, 2, [], []),
        (2, [1, 0, 1, 1, 1, 0, 0, 0, 1], 2, 255, 255, 2, [100, 200], [255, 1]),
        (2, [1, 0, 1, 1, 1, 0, 0, 0, 1], 2, 255, 31, 2, [1, 30], [99, 187]),
    ]
    lines = ["// Generated by tools/generate_cyclicrs.py; native polynomial/syndrome/Forney oracle."]
    for index, (p, modulus, root, order, n, t, positions, magnitudes) in enumerate(specifications):
        field = NativeField(p, modulus)
        assert field.power(root, order) == 1 and all(field.power(root, k) != 1 for k in range(1, order))
        generator = [1]
        for j in range(1, 2*t+1):
            generator = field.product(generator, [field.negate(field.power(root, j)), 1])
        message = [rng.randrange(field.size) for _ in range(n-2*t)]
        shifted = [0]*(2*t) + message
        remainder = shifted[:]
        for exponent in range(n-1, 2*t-1, -1):
            scalar = remainder[exponent]
            for j, coefficient in enumerate(generator):
                remainder[exponent-2*t+j] = field.add(remainder[exponent-2*t+j], field.negate(field.multiply(scalar, coefficient)))
        encoded = [field.negate(x) for x in remainder[:2*t]] + message
        assert all(field.evaluate(encoded, field.power(root, j)) == 0 for j in range(1, 2*t+1))
        received = encoded[:]
        locator = [1]
        for position, magnitude in zip(positions, magnitudes):
            received[position] = field.add(received[position], magnitude)
            locator = field.product(locator, [1, field.negate(field.power(root, position))])
        syndromes = [field.evaluate(received, field.power(root, j)) for j in range(1, 2*t+1)]
        evaluator = trim(field.product(syndromes, locator)[:2*t])
        derivative = [field.multiply(coefficient, i % p) for i, coefficient in enumerate(locator)][1:]
        for position, magnitude in zip(positions, magnitudes):
            inverse_point = field.power(root, (-position) % order)
            numerator, denominator = field.evaluate(evaluator, inverse_point), field.evaluate(derivative, inverse_point)
            assert denominator
            assert field.negate(field.multiply(numerator, field.power(denominator, field.size-2))) == magnitude
        literal = lambda values: "[" + ", ".join(map(str, values)) + "]"
        lines += ["", "///|", f'test "native cyclic RS oracle fixture {index} over GF({field.size})" {{', "  assert_cyclic_fixture(", f"    {p}, {literal(modulus)}, {root}, {order}, {n}, {t},"]
        lines += [f"    {literal(values)}," for values in [message, encoded, positions, magnitudes, syndromes, locator, evaluator]]
        lines += ["  )", "}"]
    path = ROOT / "src/cyclicrs/oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(specifications)} native cyclic RS fixtures to {path.relative_to(ROOT)}")


