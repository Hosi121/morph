#!/usr/bin/env python3
"""Regenerate the frozen incremental-span corpus with a full-system oracle.

This Python Fraction solver eliminates the entire original basis each time.
It does not use the incremental residual/witness algorithm under test.
"""
import argparse
import json
import shutil
import subprocess
from fractions import Fraction as Q
from pathlib import Path
from random import Random

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/linearspan/python_fraction_wbtest.mbt"
CORPUS = ROOT / "docs/research/incremental-span-20261117-raw/fraction-fixtures.json"


def solve(columns, vector):
    """Unique coefficients or None; columns must be linearly independent."""
    n = len(columns)
    a = [[c[i] for c in columns] + [v] for i, v in enumerate(vector)]
    row = 0
    for col in range(n):
        pivot = next(k for k in range(row, len(a)) if a[k][col])
        a[row], a[pivot] = a[pivot], a[row]
        divisor = a[row][col]
        a[row] = [x / divisor for x in a[row]]
        for k in range(len(a)):
            if k != row:
                factor = a[k][col]
                a[k] = [x - factor * y for x, y in zip(a[k], a[row])]
        row += 1
    if any(all(x == 0 for x in r[:-1]) and r[-1] for r in a):
        return None
    return [a[i][-1] for i in range(n)]


def fixtures():
    rng = Random(20261117)
    cases = []
    for dimension in range(1, 6):
        for _ in range(3):
            columns, vectors, answers = [], [], []
            # Reverse pivot positions, rather than assuming insertion order
            # equals row order in the production incremental state.
            for i in reversed(range(dimension)):
                vectors.append([
                    Q(0) if j < i else Q(rng.choice([-3, -2, 1, 2, 3]),
                                          rng.choice([2, 3, 5]))
                    for j in range(dimension)
                ])
            vectors.append([Q(0)] * dimension)
            for _ in range(3):
                weights = [Q(rng.randrange(-3, 4), rng.choice([2, 3, 5]))
                           for _ in range(dimension)]
                vectors.append([
                    sum((weights[k] * vectors[k][j] for k in range(dimension)), Q(0))
                    for j in range(dimension)
                ])
            vectors.append(vectors[0])
            for vector in vectors:
                answer = solve(columns, vector)
                answers.append(answer)
                if answer is None:
                    columns.append(vector)
            cases.append(dict(dimension=dimension, vectors=vectors, answers=answers))
    return cases


def fraction(value):
    return f"({value.numerator}, {value.denominator})"


def vector(values):
    return "[" + ", ".join(map(fraction, values)) + "]"


def render(cases):
    lines = ["// Generated by tools/generate_linearspan_fixtures.py; Python fractions.Fraction full-system oracle.", ""]
    for i, case in enumerate(cases):
        vectors = ", ".join(map(vector, case["vectors"]))
        answers = ", ".join("None" if a is None else "Some(" + vector(a) + ")"
                            for a in case["answers"])
        lines += ["///|", f'test "Python Fraction incremental span fixture {i}" {{',
                  f'  fraction_fixture({case["dimension"]}, [{vectors}], [{answers}])',
                  "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cases = fixtures()
    corpus = json.dumps(cases, default=lambda x: [x.numerator, x.denominator], indent=2) + "\n"
    formatter = ROOT / ".tools/moon/bin/moonfmt"
    executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None:
        raise SystemExit("moonfmt is required to canonicalize generated fixtures")
    source = subprocess.run([executable, "-"], input=render(cases), text=True,
                            capture_output=True, check=True).stdout
    if args.check:
        assert OUTPUT.read_text() == source, f"stale fixture: {OUTPUT}"
        assert CORPUS.read_text() == corpus, f"stale reference corpus: {CORPUS}"
    else:
        OUTPUT.write_text(source)
        CORPUS.write_text(corpus)
    print(f"{len(cases)} frozen Fraction sequences; "
          f"{sum(len(c['vectors']) for c in cases)} full-system dependence decisions.")


if __name__ == "__main__":
    main()
