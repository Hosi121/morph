#!/usr/bin/env python3
"""Independent finite-set least/greatest fixed-point mu-calculus fixtures.

This test oracle never constructs a parity game, assigns a priority or calls the
MoonBit solver. Every nested binder iterates from a fresh bottom/top set in its
current environment, so de Bruijn scope and alternating dependencies are direct.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import random
import re

ROOT=Path(__file__).resolve().parent.parent
OUTPUT=ROOT/'src/mucalc/oracle_wbtest.mbt'
ARTIFACT=ROOT/'.tools/mucalc-20261116/oracle-summary.json'


def evaluate(formula,edges,labels,environment=()):
    kind=formula[0]
    universe=frozenset(range(len(edges)))
    if kind=='truth': return universe if formula[1] else frozenset()
    if kind=='prop': return frozenset(i for i,row in enumerate(labels) if (formula[1] in row)==formula[2])
    if kind=='bound': return environment[formula[1]]
    if kind in ('and','or'):
        left=evaluate(formula[1],edges,labels,environment)
        right=evaluate(formula[2],edges,labels,environment)
        return left&right if kind=='and' else left|right
    if kind in ('diamond','box'):
        target=evaluate(formula[1],edges,labels,environment)
        return frozenset(i for i,row in enumerate(edges) if
                         (any(j in target for j in row) if kind=='diamond' else all(j in target for j in row)))
    current=frozenset() if kind=='mu' else universe
    for _ in range(len(edges)+2):
        following=evaluate(formula[1],edges,labels,(current,)+environment)
        assert current<=following if kind=='mu' else following<=current
        if following==current: return current
        current=following
    raise AssertionError('positive finite-set fixed point failed to stabilize')


def moon(formula):
    kind=formula[0]
    if kind=='truth': return f'Truth({str(formula[1]).lower()})'
    if kind=='prop': return f'Proposition(@oracle.nat({formula[1]}), {str(formula[2]).lower()})'
    if kind=='bound': return f'Bound(@oracle.nat({formula[1]}))'
    names=dict(mu='Mu',nu='Nu',diamond='Diamond',box='Box',and_='And',or_='Or')
    name=names.get(kind+'_',names.get(kind))
    return name+'('+', '.join(moon(child) for child in formula[1:])+')'


def random_formula(rng,height,depth):
    if height==0:
        choices=[('truth',False),('truth',True),('prop',rng.randrange(2),rng.choice([False,True]))]
        choices += [('bound',i) for i in range(depth)]
        return rng.choice(choices)
    kind=rng.choice(['and','or','diamond','box','mu','nu'])
    if kind in ('and','or'):
        return (kind,random_formula(rng,height-1,depth),random_formula(rng,height-1,depth))
    return (kind,random_formula(rng,height-1,depth+(kind in ('mu','nu'))))


def examples():
    p=('prop',0,True)
    q=('prop',1,True)
    x=('bound',0)
    outer=('bound',1)
    return [
      ('mu',('or',p,('diamond',x))),
      ('nu',('and',p,('box',x))),
      ('mu',('or',p,('box',x))),
      ('nu',('and',p,('diamond',x))),
      ('nu',('mu',('or',('and',p,('diamond',outer)),('diamond',x)))),
      ('mu',('nu',('or',('and',p,('diamond',x)),('diamond',outer)))),
      ('nu',('mu',('or',('and',p,('box',outer)),('box',x)))),
      ('mu',('nu',('or',('and',p,('box',x)),('box',outer)))),
      ('mu',('nu',outer)),('nu',('mu',outer)),
      ('mu',('nu',x)),('nu',('mu',x)),
      ('mu',('nu',('mu',('or',('bound',2),('and',('bound',1),('bound',0)))))),
      ('nu',('and',p,('mu',('or',q,('diamond',outer))))),
      ('mu',('or',p,('nu',('and',q,('box',outer))))),
    ]


def generate():
    rng=random.Random(202611162)
    pool=examples()
    pool += [random_formula(rng,4,0) for _ in range(33)]
    lines=['// Generated by tools/generate_mucalc.py; independent finite-set fixed-point oracle.']
    records=[]
    for index in range(144):
        n=3+index%5
        edges=[[j for j in range(n) if rng.randrange(5)<(1+index%3)] for _ in range(n)]
        labels=[[p for p in range(2) if rng.randrange(2)] for _ in range(n)]
        formula=pool[index%len(pool)]
        expected=sorted(evaluate(formula,edges,labels))
        lines += ['', '///|',f'test "independent mu-calculus fixture {index}" {{','  assert_fixture(',
                  '    '+moon(formula)+',','    '+json.dumps(edges)+',','    '+json.dumps(labels)+',',
                  '    '+json.dumps(expected)+',','  )','}']
        records.append(dict(index=index,formula=formula,edges=edges,labels=labels,satisfying_ordinals=expected))
    return '\n'.join(lines)+'\n',records


def tokens(source):
    source=re.sub(r',\s*([\]\)])',r'\1',source)
    return re.findall(r'"(?:\\.|[^"\\])*"|\S',source)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    source,records=generate()
    if args.check: assert tokens(OUTPUT.read_text())==tokens(source),'mucalc fixture regeneration drift'
    else: OUTPUT.write_text(source)
    ARTIFACT.parent.mkdir(parents=True,exist_ok=True)
    ARTIFACT.write_text(json.dumps(dict(oracle='finite sets with fresh nested fixed-point iteration; no parity game',cases=records),indent=2)+'\n')
    print(f"{'Checked' if args.check else 'Wrote'} {len(records)} independent finite-set mu-calculus fixtures.")


if __name__=='__main__': main()
