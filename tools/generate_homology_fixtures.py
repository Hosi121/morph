#!/usr/bin/env python3
"""Independent finite homology fixtures; no MoonBit or Smith implementation.

Enumerate every abstract complex on a subset of four labelled vertices. Exact
Fraction elimination and GF(2) elimination compute ranks independently. For the
Sage RP2 triangulation, gcd of *all* maximal nonzero-rank minors of d2 establishes
the product of integral torsion factors as two. Determinants use Bareiss integer
elimination, with no Smith reduction and no imported numerical library.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
from functools import reduce
from itertools import combinations
from math import gcd
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/homology/fixtures_wbtest.mbt"

# Official Sage source, RealProjectivePlane and Torus; see research note.
RP2 = [(0, 1, 2), (0, 2, 3), (0, 1, 5), (0, 4, 5), (0, 3, 4),
       (1, 2, 4), (1, 3, 4), (1, 3, 5), (2, 3, 5), (2, 4, 5)]
TORUS = [(0, 1, 2), (1, 2, 4), (1, 3, 4), (1, 3, 6), (0, 1, 5),
         (1, 5, 6), (2, 3, 5), (2, 4, 5), (2, 3, 6), (0, 2, 6),
         (0, 3, 4), (0, 3, 5), (4, 5, 6), (0, 4, 6)]


def closure(facets):
    return set(s for f in facets for k in range(1, len(f) + 1)
               for s in combinations(f, k))


def boundary(faces, k):
    columns = sorted(f for f in faces if len(f) == k + 1)
    rows = sorted(f for f in faces if len(f) == k) if k else []
    position = {f: i for i, f in enumerate(rows)}
    matrix = [[0] * len(columns) for _ in rows]
    if k:
        for j, simplex in enumerate(columns):
            for deleted in range(len(simplex)):
                face = simplex[:deleted] + simplex[deleted + 1:]
                matrix[position[face]][j] = (-1) ** deleted
    return matrix, len(columns)


def rank(matrix, width, mod2=False):
    a = [[(x % 2 if mod2 else Fraction(x)) for x in row] for row in matrix]
    r = 0
    for c in range(width):
        pivot = next((i for i in range(r, len(a)) if a[i][c]), None)
        if pivot is None:
            continue
        a[r], a[pivot] = a[pivot], a[r]
        if not mod2:
            divisor = a[r][c]
            a[r] = [x / divisor for x in a[r]]
        for i in range(r + 1, len(a)):
            factor = a[i][c]
            if factor:
                a[i] = [(x + y) % 2 if mod2 else x - factor * y
                        for x, y in zip(a[i], a[r])]
        r += 1
    return r


def betti(faces, degrees=4, mod2=False):
    matrices = [boundary(faces, k) for k in range(degrees + 1)]
    ranks = [rank(m, w, mod2) for m, w in matrices]
    return [matrices[k][1] - ranks[k] - ranks[k + 1]
            for k in range(degrees)]


def determinant(matrix):
    if not matrix:
        return 1
    a = [row[:] for row in matrix]
    previous, sign = 1, 1
    for k in range(len(a) - 1):
        pivot = next((i for i in range(k, len(a)) if a[i][k]), None)
        if pivot is None:
            return 0
        if pivot != k:
            a[k], a[pivot] = a[pivot], a[k]
            sign *= -1
        value = a[k][k]
        for i in range(k + 1, len(a)):
            for j in range(k + 1, len(a)):
                numerator = a[i][j] * value - a[i][k] * a[k][j]
                assert numerator % previous == 0
                a[i][j] = numerator // previous
            a[i][k] = 0
        previous = value
    return sign * a[-1][-1]


def all_small_complexes():
    possible = [s for k in range(1, 5) for s in combinations(range(4), k)]
    result = []
    for mask in range(1 << len(possible)):
        faces = {s for i, s in enumerate(possible) if mask & (1 << i)}
        if closure(faces) != faces:
            continue
        facets = sorted(f for f in faces if not any(set(f) < set(g) for g in faces))
        result.append((facets, betti(faces), betti(faces, mod2=True)))
    assert len(result) == 167
    return result


def arr(value):
    if isinstance(value, (tuple, list)):
        return "[" + ", ".join(arr(x) for x in value) + "]"
    return str(value)


def render():
    small = all_small_complexes()
    rpfaces, tfaces = closure(RP2), closure(TORUS)
    assert betti(rpfaces) == [1, 0, 0, 0]
    assert betti(rpfaces, mod2=True) == [1, 1, 1, 0]
    assert betti(tfaces) == betti(tfaces, mod2=True) == [1, 2, 1, 0]
    d2, width = boundary(rpfaces, 2)
    assert rank(d2, width) == 10
    minors = [abs(determinant([d2[i] for i in indices]))
              for indices in combinations(range(15), 10)]
    torsion_product = reduce(gcd, minors, 0)
    assert len(minors) == 3003 and torsion_product == 2
    lines = ["// Generated by tools/generate_homology_fixtures.py; do not edit.",
             "///|", "fn small_fixtures() -> Array[(Array[Array[Int]], Array[Int], Array[Int])] {", "  ["]
    for facets, rational, gf2 in small:
        lines.append(f"    ({arr(facets)}, {arr(rational)}, {arr(gf2)}),")
    lines += ["  ]", "}", "", "///|", 'test "all 167 complexes on four labelled vertices match independent rational and GF2 ranks" {',
              "  for fixture in small_fixtures() {", "    let (facets, rational, gf2) = fixture",
              "    let complex = generated(facets)", "    let mut euler = 0",
              "    for k in 0..<4 {", "      verify(complex, k, rational[k], [])",
              "      assert_eq(gf2_betti(complex, k), gf2[k])",
              "      euler += if k % 2 == 0 { rational[k] } else { -rational[k] }", "    }",
              "    assert_eq(euler_characteristic(complex), @oracle.integer(euler))", "  }", "}", ""]
    for name, faces, builder in [("projective plane", rpfaces, "projective_plane"),
                                 ("torus", tfaces, "torus")]:
        lines += ["///|", f'test "{name} boundaries and field ranks match independent Python matrices" {{',
                  f"  let complex = {builder}()"]
        for k in range(4):
            matrix, width = boundary(faces, k)
            lines += [f"  assert_eq(int_rows(boundary(complex, @oracle.nat({k})).unwrap()), {arr(matrix)})",
                      f"  assert_eq(@matrix.width(boundary(complex, @oracle.nat({k})).unwrap()), @oracle.nat({width}))",
                      f"  assert_eq(gf2_betti(complex, {k}), {betti(faces, mod2=True)[k]})"]
        lines += ["}", ""]
    lines += ["// RP2 independent integer check: all 3003 maximal minors of d2",
              "// have gcd 2, so the torsion product is 2, not just an even order.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatter = ROOT / ".tools/moon/bin/moonfmt"
    executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None:
        raise SystemExit("moonfmt is required to canonicalize generated MoonBit fixtures")
    content = subprocess.run([executable, "-"], input=render(), text=True,
                             check=True, capture_output=True).stdout
    if args.check:
        assert OUTPUT.read_text() == content, f"stale fixture: {OUTPUT}"
    else:
        OUTPUT.write_text(content)
    print("167 complexes; rational/GF2 boundaries; RP2 3003 maximal minors gcd=2")


if __name__ == "__main__":
    main()
