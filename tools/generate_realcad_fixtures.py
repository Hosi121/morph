#!/usr/bin/env python3
"""Generate exact, independent SymPy sign-cell fixtures for univariate CAD."""
from pathlib import Path
import argparse
import itertools
import json
from functools import lru_cache
import re
import sympy as sp

ROOT = Path(__file__).resolve().parent.parent
X = sp.Symbol('x', real=True)
RELATIONS = ['LessZero', 'AtMostZero', 'EqualZero', 'NotZero', 'AtLeastZero', 'GreaterZero']

@lru_cache(maxsize=None)
def polynomial(coefficients):
    return sum(sp.Integer(c) * X**i for i, c in enumerate(coefficients))

def atoms(formula):
    if formula[0] == 'atom':
        return [tuple(formula[1])]
    if formula[0] == 'truth':
        return []
    result = []
    for child in formula[1:]:
        for p in atoms(child):
            if p not in result:
                result.append(p)
    return result

def exact_sign(value):
    sign = sp.sign(sp.simplify(value))
    if sign not in (-1, 0, 1):
        raise ValueError(f'undecided exact sign: {value} -> {sign}')
    return int(sign)

def evaluate(formula, sample):
    op = formula[0]
    if op == 'truth':
        return formula[1]
    if op == 'not':
        return not evaluate(formula[1], sample)
    if op in ('and', 'or'):
        a, b = evaluate(formula[1], sample), evaluate(formula[2], sample)
        return (a and b) if op == 'and' else (a or b)
    sign = exact_sign(polynomial(formula[1]).subs(X, sample))
    return {'LessZero': sign < 0, 'AtMostZero': sign <= 0, 'EqualZero': sign == 0,
            'NotZero': sign != 0, 'AtLeastZero': sign >= 0, 'GreaterZero': sign > 0}[formula[2]]

def signs(formula):
    roots = set()
    for coefficients in atoms(formula):
        p = polynomial(coefficients)
        if p != 0:
            roots.update(sp.Poly(p, X).real_roots())
    roots = sorted(roots)
    if not roots:
        return [evaluate(formula, sp.Integer(0))], 0
    samples = [roots[0] - 1]
    for i, root in enumerate(roots):
        samples.append(root)
        samples.append((root + roots[i+1])/2 if i+1 < len(roots) else root+1)
    return [evaluate(formula, point) for point in samples], len(roots)

def moon(formula):
    op = formula[0]
    if op == 'truth':
        return f'Truth({str(formula[1]).lower()})'
    if op == 'atom':
        return f'Atom(poly({list(formula[1])}), {formula[2]})'
    if op == 'not':
        return f'Negation({moon(formula[1])})'
    name = 'Conjunction' if op == 'and' else 'Disjunction'
    return f'{name}({moon(formula[1])}, {moon(formula[2])})'

def generate():
    cases = []
    for coefficients in itertools.product(range(-2, 3), repeat=3):
        for relation in RELATIONS:
            cases.append(('atom', coefficients, relation))
    chosen = [(0,1), (-1,1), (1,1), (-2,0,1), (-3,0,1), (1,-2,1), (-2,1,1), (1,0,1)]
    for i, left in enumerate(chosen):
        for j, right in enumerate(chosen):
            a = ('atom',left,RELATIONS[(i+j)%6])
            b = ('atom',right,RELATIONS[(2*i+j+1)%6])
            cases += [('and',a,b),('or',a,b),('not',('and',a,('not',b)))]
    cases += [('truth',False),('truth',True)]
    data=[]
    lines=['// Generated by tools/generate_realcad_fixtures.py using SymPy 1.14.0.',
           '///|', 'test "independent exact SymPy sign cells for Boolean polynomial formulas" {']
    for index,formula in enumerate(cases):
        expected, count = signs(formula)
        bools = '['+', '.join(str(v).lower() for v in expected)+']'
        body = [f'    let result = solve({moon(formula)})',
                  f'    assert_eq(@oracle.array(roots(result)).length(), {count}, msg="root count case {index}")',
                  '    let actual = @oracle.array(cells(result)).map(fn(cell) { cell.holds })',
                  f'    assert_eq(actual, {bools}, msg="sign-cell case {index}")',
                  f'    assert_eq(witness(result) is Some(_), {str(any(expected)).lower()})',
                  f'    assert_eq(universally_true(result), {str(all(expected)).lower()})']
        if index + 1 == len(cases):
            # moon fmt unwraps a final redundant scope; generate that form.
            lines += [line[2:] for line in body]
        else:
            lines += ['  {', *body, '  }']
        data.append({'formula':formula, 'truth_cells':expected, 'distinct_roots':count})
    lines += ['}']
    return '\n'.join(lines)+'\n',json.dumps({'oracle':'SymPy '+sp.__version__, 'cases':data},indent=2)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    source, data=generate()
    outputs=[(ROOT/'src/realcad/fixtures_wbtest.mbt',source),(ROOT/'docs/research/realcad-20261116-fixtures.json',data)]
    for path, content in outputs:
        if args.check:
            actual = path.read_text()
            def tokens(text):
                return re.findall(r'"(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z_0-9]*|[0-9]+|[^\s,]', text)
            same = actual == content if path.suffix == '.json' else tokens(actual) == tokens(content)
            if not same:
                raise SystemExit(f'Stale fixture: {path.relative_to(ROOT)} (regenerate, then moon fmt)')
        else:
            path.write_text(content)
    print(f'Generated {len(json.loads(data)["cases"])} exact sign-cell fixtures.')

if __name__=='__main__':
    main()
