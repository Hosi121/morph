#!/usr/bin/env python3
"""Build finite-field factorization fixtures using native dense arithmetic.

Known candidates are checked independently by exhaustive monic trial division.
Products and expected multiplicities are then generated without Berlekamp,
Frobenius matrices, or the MoonBit implementation.
"""
from pathlib import Path
from itertools import product
import random

ROOT = Path(__file__).resolve().parent.parent


def trim(values, p):
    values = [x % p for x in values]
    while values and not values[-1]:
        values.pop()
    return values


def multiply(a, b, p):
    result = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            result[i + j] += x * y
    return trim(result, p)


def remainder(a, b, p):
    result = trim(a, p)
    inverse = next(x for x in range(1, p) if x * b[-1] % p == 1)
    while len(result) >= len(b):
        shift = len(result) - len(b)
        scalar = result[-1] * inverse % p
        for j, coefficient in enumerate(b):
            result[shift + j] = (result[shift + j] - scalar * coefficient) % p
        result = trim(result, p)
    return result


def irreducible(values, p):
    return all(remainder(values, list(low) + [1], p) for degree in range(1, (len(values) - 1) // 2 + 1) for low in product(range(p), repeat=degree))


def literal(values):
    return "[" + ", ".join(map(str, values)) + "]"


def digits(code, p, width):
    result = []
    for _ in range(width):
        result.append(code % p)
        code //= p
    return trim(result, p)


def first_irreducible(p, degree):
    return next(list(low) + [1] for low in product(range(p), repeat=degree) if low[0] and irreducible(list(low) + [1], p))


def field_power(value, exponent, modulus, p):
    result = [1]
    for _ in range(exponent):
        result = remainder(multiply(result, value, p), modulus, p)
    return result


def extension_fixtures():
    rng = random.Random(202611150)
    fields = [(2, [1, 1, 0, 1, 1, 0, 0, 0, 1]), (3, first_irreducible(3, 4)), (5, first_irreducible(5, 3)), (7, first_irreducible(7, 3))]
    lines = ["// Generated by tools/generate_fppoly.py; exhaustive native inverse/product oracle."]
    count = 0
    for p, modulus in fields:
        assert irreducible(modulus, p)
        degree = len(modulus) - 1
        size = p**degree
        for case in range(3):
            a = digits(rng.randrange(1, size), p, degree)
            b = digits(rng.randrange(size), p, degree)
            answer = remainder(multiply(a, b, p), modulus, p)
            reciprocal = next(digits(code, p, degree) for code in range(1, size) if remainder(multiply(a, digits(code, p, degree), p), modulus, p) == [1])
            conjugate, trace, norm = a, [0] * degree, [1]
            for _ in range(degree):
                for index, coefficient in enumerate(conjugate):
                    trace[index] = (trace[index] + coefficient) % p
                norm = remainder(multiply(norm, conjugate, p), modulus, p)
                conjugate = field_power(conjugate, p, modulus, p)
            assert conjugate == a
            assert not any(trace[1:]) and len(norm) <= 1
            lines += ["", "///|", f'test "native extension oracle GF({p}^{degree}) fixture {case}" {{', f"  assert_extension_fixture({p}, {literal(modulus)}, {literal(a)}, {literal(b)}, {literal(answer)}, {literal(reciprocal)}, {trace[0]}, {norm[0] if norm else 0})", "}"]
            count += 1
    path = ROOT / "src/galois/oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {count} independently checked extension fixtures to {path.relative_to(ROOT)}")


def main():
    cases = [
        (2, 1, [([1, 1, 1], 1), ([1, 1, 0, 0, 1], 1), ([1, 0, 0, 1, 1], 1)]),
        (2, 1, [([1, 1, 1], 3), ([1, 1, 0, 0, 1], 2)]),
        (2, 1, [([1, 1], 16)]),
        (3, 2, [([1, 0, 1], 3), ([1, 1], 2)]),
        (3, 1, [([1, 2, 0, 1], 1), ([2, 2, 0, 1], 1), ([1, 0, 1], 1)]),
        (3, 2, [([2, 1], 9)]),
        (5, 4, [([2, 0, 1], 5)]),
        (5, 3, [([2, 0, 1], 2), ([3, 0, 1], 3), ([1, 1], 1)]),
        (7, 6, [([1, 0, 1], 2), ([5, 1], 3)]),
        (7, 2, [([1, 0, 1], 1), ([2, 0, 1], 1)]),
    ]
    lines = ["// Generated by tools/generate_fppoly.py; native trial-division/product oracle."]
    for index, (p, unit, factors) in enumerate(cases):
        result = [unit]
        for values, multiplicity in factors:
            assert irreducible(values, p), (p, values)
            for _ in range(multiplicity):
                result = multiply(result, values, p)
        expected = "[" + ", ".join(f"({literal(values)}, {multiplicity})" for values, multiplicity in factors) + "]"
        lines += ["", "///|", f'test "native product factorization fixture {index} in characteristic {p}" {{', f"  assert_factor_fixture({p}, {literal(result)}, {unit}, {expected})", "}"]
    path = ROOT / "src/fppoly/oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(cases)} independently checked factorization fixtures to {path.relative_to(ROOT)}")
    extension_fixtures()


if __name__ == "__main__":
    main()
