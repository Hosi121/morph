#!/usr/bin/env python3
"""Build finite-field factorization fixtures using native dense arithmetic.

Known candidates are checked independently by exhaustive monic trial division.
Products and expected multiplicities are then generated without Berlekamp,
Frobenius matrices, or the MoonBit implementation.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def trim(values, p):
    values = [x % p for x in values]
    while values and not values[-1]:
        values.pop()
    return values


def multiply(a, b, p):
    result = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            result[i + j] += x * y
    return trim(result, p)


def remainder(a, b, p):
    result = trim(a, p)
    inverse = next(x for x in range(1, p) if x * b[-1] % p == 1)
    while len(result) >= len(b):
        shift = len(result) - len(b)
        scalar = result[-1] * inverse % p
        for j, coefficient in enumerate(b):
            result[shift + j] = (result[shift + j] - scalar * coefficient) % p
        result = trim(result, p)
    return result


def irreducible(values, p):
    from itertools import product
    return all(remainder(values, list(low) + [1], p) for degree in range(1, (len(values) - 1) // 2 + 1) for low in product(range(p), repeat=degree))


def literal(values):
    return "[" + ", ".join(map(str, values)) + "]"


def main():
    cases = [
        (2, 1, [([1, 1, 1], 1), ([1, 1, 0, 0, 1], 1), ([1, 0, 0, 1, 1], 1)]),
        (2, 1, [([1, 1, 1], 3), ([1, 1, 0, 0, 1], 2)]),
        (2, 1, [([1, 1], 16)]),
        (3, 2, [([1, 0, 1], 3), ([1, 1], 2)]),
        (3, 1, [([1, 2, 0, 1], 1), ([2, 2, 0, 1], 1), ([1, 0, 1], 1)]),
        (3, 2, [([2, 1], 9)]),
        (5, 4, [([2, 0, 1], 5)]),
        (5, 3, [([2, 0, 1], 2), ([3, 0, 1], 3), ([1, 1], 1)]),
        (7, 6, [([1, 0, 1], 2), ([5, 1], 3)]),
        (7, 2, [([1, 0, 1], 1), ([2, 0, 1], 1)]),
    ]
    lines = ["// Generated by tools/generate_fppoly.py; native trial-division/product oracle."]
    for index, (p, unit, factors) in enumerate(cases):
        result = [unit]
        for values, multiplicity in factors:
            assert irreducible(values, p), (p, values)
            for _ in range(multiplicity):
                result = multiply(result, values, p)
        expected = "[" + ", ".join(f"({literal(values)}, {multiplicity})" for values, multiplicity in factors) + "]"
        lines += ["", "///|", f'test "native product factorization fixture {index} in characteristic {p}" {{', f"  assert_factor_fixture({p}, {literal(result)}, {unit}, {expected})", "}"]
    path = ROOT / "src/fppoly/oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(cases)} independently checked factorization fixtures to {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
