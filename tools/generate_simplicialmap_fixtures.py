#!/usr/bin/env python3
"""Independent finite-set/permutation model for simplicial-map chain matrices.

Only test fixtures use Python numbers and mutable containers. Production uses
the project's immutable Nat, Chain, Integer and checked matrix operations.
"""
from pathlib import Path
from itertools import combinations, product
import argparse
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/simplicialmap/fixtures_wbtest.mbt"


def closure(facets):
    return {face for facet in facets for k in range(1, len(facet) + 1)
            for face in combinations(facet, k)}


def small_complexes():
    possible = [face for k in range(1, 4) for face in combinations(range(3), k)]
    result = []
    for mask in range(1 << len(possible)):
        faces = {f for i, f in enumerate(possible) if mask & (1 << i)}
        if closure(faces) == faces:
            facets = sorted(f for f in faces if not any(set(f) < set(g) for g in faces))
            result.append((faces, facets))
    assert len(result) == 19
    return result


def simplices(faces, k):
    return sorted(f for f in faces if len(f) == k + 1)


def boundary(faces, k):
    columns = simplices(faces, k)
    rows = simplices(faces, k - 1) if k else []
    position = {f: i for i, f in enumerate(rows)}
    result = [[0] * len(columns) for _ in rows]
    for j, simplex in enumerate(columns):
        if k:
            for deleted in range(len(simplex)):
                face = simplex[:deleted] + simplex[deleted + 1:]
                result[position[face]][j] = (-1) ** deleted
    return result


def chain_map(source, target, mapping, k):
    rows, columns = simplices(target, k), simplices(source, k)
    result = [[0] * len(columns) for _ in rows]
    position = {f: i for i, f in enumerate(rows)}
    for j, simplex in enumerate(columns):
        image = [mapping[v] for v in simplex]
        if len(set(image)) < len(image):
            continue
        inversions = sum(image[i] > image[t] for i in range(len(image))
                         for t in range(i + 1, len(image)))
        result[position[tuple(sorted(image))]][j] = (-1) ** inversions
    return result


def multiply(a, b, width):
    return [[sum(x * b[t][j] for t, x in enumerate(row))
             for j in range(width)] for row in a]


def checked_matrices(source, target, mapping, degrees):
    matrices = [chain_map(source, target, mapping, k) for k in range(degrees)]
    for k in range(1, degrees):
        width = len(simplices(source, k))
        assert multiply(boundary(target, k), matrices[k], width) == \
            multiply(matrices[k - 1], boundary(source, k), width)
    return matrices


def arr(value):
    if isinstance(value, (tuple, list)):
        return "[" + ", ".join(arr(x) for x in value) + "]"
    return str(value)


def render():
    complexes = small_complexes()
    total, valid = 0, 0
    lines = ["// Generated by tools/generate_simplicialmap_fixtures.py; do not edit.",
             "///|", "fn small_complexes() -> Array[Array[Array[Int]]] {",
             "  " + arr([facets for _, facets in complexes]), "}", ""]
    for i, (source, _) in enumerate(complexes):
        domain = [f[0] for f in simplices(source, 0)]
        widths = [len(simplices(source, k)) for k in range(4)]
        cases = []
        for j, (target, _) in enumerate(complexes):
            codomain = [f[0] for f in simplices(target, 0)]
            for images in product(codomain, repeat=len(domain)):
                total += 1
                mapping = dict(zip(domain, images))
                preserves = all(tuple(sorted({mapping[v] for v in face})) in target
                                for face in source)
                expected = "None"
                if preserves:
                    valid += 1
                    expected = "Some(" + arr(checked_matrices(source, target, mapping, 4)) + ")"
                cases.append(f"    ({j}, {arr(images)}, {expected}),")
        lines += ["///|", f"fn small_maps_{i}() -> Array[(Int, Array[Int], Array[Array[Array[Int]]]?)] {{", "  [",
                  *cases, "  ]", "}", "", "///|",
                  f'test "independent total vertex maps from three-label complex {i}" {{',
                  "  let complexes = small_complexes()",
                  f"  let source = generated(complexes[{i}])",
                  f"  for fixture in small_maps_{i}() {{",
                  "    let (target_index, images, expected) = fixture",
                  f"    verify_fixture(source, generated(complexes[target_index]), {arr(domain)}, images, {arr(widths)}, expected)",
                  "  }", "}", ""]
    assert (total, valid) == (3439, 2449)
    tetrahedron = closure([(0, 1, 2, 3)])
    tetra_cases = []
    for images in product(range(4), repeat=4):
        matrices = checked_matrices(tetrahedron, tetrahedron, dict(enumerate(images)), 5)
        tetra_cases.append(f"    ({arr(images)}, {arr(matrices)}),")
    lines += ["///|", "fn tetrahedron_maps() -> Array[(Array[Int], Array[Array[Array[Int]]])] {", "  [",
              *tetra_cases, "  ]", "}", "", "///|",
              'test "all 256 tetrahedron vertex maps match independent signed chain matrices" {',
              "  let tetrahedron = generated([[0, 1, 2, 3]])",
              "  for fixture in tetrahedron_maps() {",
              "    let (images, expected) = fixture",
              "    verify_fixture(tetrahedron, tetrahedron, [0, 1, 2, 3], images, [4, 6, 4, 1, 0], Some(expected))",
              "  }", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatter = ROOT / ".tools/moon/bin/moonfmt"
    executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None:
        raise SystemExit("moonfmt is required to canonicalize generated fixtures")
    content = subprocess.run([executable, "-"], input=render(), text=True,
                             check=True, capture_output=True).stdout
    if args.check:
        assert OUTPUT.read_text() == content, f"stale fixture: {OUTPUT}"
    else:
        OUTPUT.write_text(content)
    print("19 complexes; 3439 total functions: 2449 valid, 990 rejected; 256 tetrahedron endomaps")


if __name__ == "__main__":
    main()
