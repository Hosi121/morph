#!/usr/bin/env python3
"""Independent SymPy and native rational-root Zassenhaus/Hensel fixtures.

The Hensel oracle uses SymPy's quadratic, divide-and-conquer lifting rather than
MoonBit's linear simultaneous corrections. The exhaustive degree-two/three grid
also checks irreducibility using only integer rational-root enumeration.
"""
from argparse import ArgumentParser
from itertools import product
from math import gcd
from pathlib import Path
import json
import subprocess
import warnings

import sympy as sp
from sympy.polys.factortools import dup_zz_hensel_lift
from sympy.polys.domains import ZZ
from sympy.utilities.exceptions import SymPyDeprecationWarning

ROOT = Path(__file__).resolve().parents[1]
x = sp.Symbol('x')


def coeffs(expr):
    return [int(c) for c in reversed(sp.Poly(expr, x).all_coeffs())]


def arr(values):
    return '[' + ', '.join(map(str, values)) + ']'


def rational_root_reducible(values):
    """Degree 2 or 3 over Q: reducible iff a rational root exists."""
    assert len(values) in (3, 4) and values[-1] > 0
    if values[0] == 0:
        return True
    degree = len(values) - 1
    for numerator in range(-abs(values[0]), abs(values[0]) + 1):
        if numerator == 0 or values[0] % numerator:
            continue
        for denominator in range(1, values[-1] + 1):
            if values[-1] % denominator:
                continue
            if sum(c * numerator**i * denominator**(degree-i)
                   for i, c in enumerate(values)) == 0:
                return True
    return False


def add_integer_fixture(lines, expr, label, records):
    content, factors = sp.factor_list(expr, x)
    expected = [(coeffs(f), int(k)) for f, k in factors]
    values = coeffs(expr)
    records.append(dict(input=values, content=int(content), factors=expected))
    lines += ['///|', f'test "{label}" {{',
              f'  assert_factor_fixture({arr(values)}, {int(content)},',
              '    [' + ', '.join('(' + arr(f) + ', ' + str(k) + ')'
                                  for f, k in expected) + '])', '}', '']
    return expected


def generate():
    lines = ['// Generated by tools/generate_zassenhaus_fixtures.py; independent SymPy/native oracles.', '']
    cases = [(x**4-1, 5, 4),
             ((2*x+1)*(3*x+2)*(x*x+x+1), 5, 4),
             (-6*(2*x+1)*(x*x+2), 5, 3),
             (x**6+x**3+1, 2, 5),
             ((x*x+1)*(x*x+2), 3, 4)]
    hensel_records = []
    for i, (expr, p, exponent) in enumerate(cases):
        poly = sp.Poly(expr, x, domain=ZZ)
        _, factors = sp.factor_list(poly, modulus=p)
        assert all(k == 1 for _, k in factors), (expr, p)
        descending = [[int(c) % p for c in f.monic().all_coeffs()]
                      for f, _ in factors]
        lifted = dup_zz_hensel_lift(
            p, [ZZ(c) for c in poly.all_coeffs()], descending, exponent, ZZ)
        ascending = [[int(c) % p**exponent for c in reversed(f)]
                     for f in lifted]
        inputs = [list(reversed(f)) for f in descending]
        hensel_records.append(dict(input=coeffs(expr), prime=p, exponent=exponent,
                                   factors=inputs, lifts=ascending))
        lines += ['///|', f'test "SymPy multifactor Hensel fixture {i}" {{',
                  f'  assert_lift_fixture({arr(coeffs(expr))}, {p}, {exponent},',
                  '    [' + ', '.join(arr(f) for f in inputs) + '],',
                  '    [' + ', '.join(arr(f) for f in ascending) + '])', '}', '']

    integer_cases = [
        7, -18, x, 2*x+1, -6*x-3,
        x*x-1, x**4-1, x**4+1, x**4+4,
        x**6+x**3+1, x**6-1,
        (2*x+1)*(3*x+2)*(x*x+x+1),
        -12*(2*x+1)**3*(3*x-2)**2*(x*x+1),
        18*x**3*(x-1)**2*(x+2),
        (x*x+x+1)**3*(x*x-x+1)**2,
        5*x**5+3*x**4+7*x**3-2*x+9,
        (5*x*x+3*x+2)*(7*x*x-4*x+1),
        30*(x*x+2)*(x*x+3)*(x*x+5),
        (2*x+1)*(2*x-1)*(3*x+1)*(3*x-1),
    ]
    integer_records = []
    for i, expr in enumerate(integer_cases):
        add_integer_fixture(lines, expr, f'SymPy ZZ factorization fixture {i}', integer_records)

    rational_cases = [
        (x*x-1)/6,
        -sp.Rational(7, 30)*(2*x+1)**2*(3*x-2),
        (sp.Rational(2, 3)*x+sp.Rational(1, 5))*(sp.Rational(3, 7)*x-sp.Rational(2, 11)),
        sp.Rational(-3, 14), sp.Rational(3, 11)*(x**4+1),
    ]
    rational_records = []
    for i, expr in enumerate(rational_cases):
        poly = sp.Poly(expr, x, domain=sp.QQ)
        denominator, integer = poly.clear_denoms(convert=True)
        content, factors = sp.factor_list(integer)
        unit = sp.Rational(content, denominator)
        inp = [(int(c.p), int(c.q)) for c in reversed(poly.all_coeffs())]
        expected = [(coeffs(f.as_expr()), int(k)) for f, k in factors]
        rational_records.append(dict(input=inp, unit=[int(unit.p), int(unit.q)], factors=expected))
        lines += ['///|', f'test "SymPy QQ factorization fixture {i}" {{',
                  '  assert_rational_fixture([' + ', '.join(f'({a}, {b})' for a, b in inp) +
                  f'], ({int(unit.p)}, {int(unit.q)}),',
                  '    [' + ', '.join('(' + arr(f) + ', ' + str(k) + ')'
                                      for f, k in expected) + '])', '}', '']

    grid_records = []
    for degree in (2, 3):
        for leading in (1, 2, 3):
            for lower in product(range(-2, 3), repeat=degree):
                values = list(lower) + [leading]
                if gcd(*values) != 1:
                    continue
                expr = sum(c*x**i for i, c in enumerate(values))
                label = f'SymPy primitive small coefficient grid {len(grid_records)}'
                expected = add_integer_fixture(lines, expr, label, grid_records)
                is_irreducible = len(expected) == 1 and expected[0][1] == 1
                assert is_irreducible == (not rational_root_reducible(values)), values
                grid_records[-1]['rational_root_reducible'] = not is_irreducible
    assert len(grid_records) == 412
    statistics = dict(
        hensel=len(hensel_records), integer=len(integer_records),
        rational=len(rational_records), exhaustive_grid=len(grid_records),
        grid_irreducible=sum(not r['rational_root_reducible'] for r in grid_records),
        grid_reducible=sum(r['rational_root_reducible'] for r in grid_records),
    )
    artifacts = dict(sympy=sp.__version__, statistics=statistics, hensel=hensel_records,
                     integer=integer_records, rational=rational_records, grid=grid_records)
    formatter = ROOT / '.tools/moon/bin/moonfmt'
    formatted = subprocess.run([str(formatter), '-'], input='\n'.join(lines),
                               text=True, capture_output=True, check=True).stdout
    return {
        ROOT/'src/zassenhaus/fixtures_wbtest.mbt': formatted,
        ROOT/'docs/research/zassenhaus-20261116-fixtures.json': json.dumps(artifacts, indent=2)+'\n',
    }, statistics


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='reject stale generated fixtures')
    args = parser.parse_args()
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', SymPyDeprecationWarning)
        artifacts, statistics = generate()
    for path, text in artifacts.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale generated artifact: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
    print(json.dumps(statistics, sort_keys=True))


if __name__ == '__main__':
    main()
