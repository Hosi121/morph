#!/usr/bin/env python3
"""Independent SymPy (quadratic Hensel + ZZ/QQ factor_list) fixture producer."""
from pathlib import Path
import json
import sympy as sp
from sympy.polys.factortools import dup_zz_hensel_lift
from sympy.polys.domains import ZZ

ROOT = Path(__file__).resolve().parents[1]
x = sp.Symbol('x')
def coeffs(expr):
    return [int(c) for c in reversed(sp.Poly(expr, x).all_coeffs())]
def arr(values):
    return '[' + ', '.join(map(str, values)) + ']'

cases = [(x**4-1, 5, 4), ((2*x+1)*(3*x+2)*(x*x+x+1), 5, 4), (-6*(2*x+1)*(x*x+2), 5, 3), (x**6+x**3+1, 2, 5), ((x*x+1)*(x*x+2), 3, 4)]
records = []
lines = ['// Generated by tools/generate_zassenhaus_fixtures.py; independent SymPy oracle.', '']
for i, (expr, p, exponent) in enumerate(cases):
    poly = sp.Poly(expr, x, domain=ZZ)
    _, fs = sp.factor_list(poly, modulus=p)
    assert all(k == 1 for _, k in fs), (expr, p)
    factors = [[int(c) % p for c in f.monic().all_coeffs()] for f, _ in fs]
    lifted = dup_zz_hensel_lift(p, [ZZ(c) for c in poly.all_coeffs()], factors, exponent, ZZ)
    ascending = [[int(c) % p**exponent for c in reversed(f)] for f in lifted]
    inputs = [[c for c in reversed(f)] for f in factors]
    records.append(dict(input=coeffs(expr), prime=p, exponent=exponent, factors=inputs, lifts=ascending))
    lines += ['///|', f'test "SymPy multifactor Hensel fixture {i}" {{', f'  assert_lift_fixture({arr(coeffs(expr))}, {p}, {exponent},', '    ['+', '.join(arr(f) for f in inputs)+'],', '    ['+', '.join(arr(f) for f in ascending)+'])', '}', '']
(ROOT/'src/zassenhaus/fixtures_wbtest.mbt').write_text('\n'.join(lines))
(ROOT/'docs/research/zassenhaus-20261116-fixtures.json').write_text(json.dumps(dict(sympy=sp.__version__, hensel=records),indent=2)+'\n')
print(f'generated {len(records)} Hensel fixtures using SymPy {sp.__version__}')

integer_cases = [
    7, -18, x, 2*x+1, -6*x-3,
    x*x-1, x**4-1, x**4+1, x**4+4,
    x**6+x**3+1, x**6-1,
    (2*x+1)*(3*x+2)*(x*x+x+1),
    -12*(2*x+1)**3*(3*x-2)**2*(x*x+1),
    18*x**3*(x-1)**2*(x+2),
    (x*x+x+1)**3*(x*x-x+1)**2,
    5*x**5+3*x**4+7*x**3-2*x+9,
    (5*x*x+3*x+2)*(7*x*x-4*x+1),
    30*(x*x+2)*(x*x+3)*(x*x+5),
    (2*x+1)*(2*x-1)*(3*x+1)*(3*x-1),
]
integer_records=[]
for i,expr in enumerate(integer_cases):
    content, fs=sp.factor_list(expr, x)
    expected=[(coeffs(f), int(k)) for f,k in fs]
    integer_records.append(dict(input=coeffs(expr), content=int(content), factors=expected))
    lines += ['///|',f'test "SymPy ZZ factorization fixture {i}" {{',f'  assert_factor_fixture({arr(coeffs(expr))}, {int(content)},', '    ['+', '.join('('+arr(f)+', '+str(k)+')' for f,k in expected)+'])', '}', '']

rational_cases=[(x*x-1)/6, -sp.Rational(7,30)*(2*x+1)**2*(3*x-2), (sp.Rational(2,3)*x+sp.Rational(1,5))*(sp.Rational(3,7)*x-sp.Rational(2,11)), sp.Rational(-3,14), sp.Rational(3,11)*(x**4+1)]
rational_records=[]
for i,expr in enumerate(rational_cases):
    poly=sp.Poly(expr,x,domain=sp.QQ)
    denominator, integer=poly.clear_denoms(convert=True)
    content,fs=sp.factor_list(integer)
    unit=sp.Rational(content,denominator)
    inp=[(int(c.p),int(c.q)) for c in reversed(poly.all_coeffs())]
    expected=[(coeffs(f.as_expr()), int(k)) for f,k in fs]
    rational_records.append(dict(input=inp,unit=[int(unit.p),int(unit.q)],factors=expected))
    lines += ['///|',f'test "SymPy QQ factorization fixture {i}" {{','  assert_rational_fixture(['+', '.join('('+str(a)+', '+str(b)+')' for a,b in inp)+f'], ({int(unit.p)}, {int(unit.q)}),','    ['+', '.join('('+arr(f)+', '+str(k)+')' for f,k in expected)+'])','}','']
(ROOT/'src/zassenhaus/fixtures_wbtest.mbt').write_text('\n'.join(lines))
(ROOT/'docs/research/zassenhaus-20261116-fixtures.json').write_text(json.dumps(dict(sympy=sp.__version__,hensel=records,integer=integer_records,rational=rational_records),indent=2)+'\n')
print(f'generated {len(integer_records)} ZZ and {len(rational_records)} QQ factorization fixtures')
