#!/usr/bin/env python3
"""NIST-derived fixtures and independent native AES oracles.

Default generation uses the checked-in JSON (standard library only).
--import-nist DIR re-extracts the pinned official PDFs using optional pypdf.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import random
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    "fips197-upd1.pdf": ("https://nvlpubs.nist.gov/nistpubs/FIPS/NIST.FIPS.197-upd1.pdf", "62c86eb567f13edb8f71826e985da870b04ef6381634f303cdb16e84d47becd1"),
    "AES_Core128.pdf": ("https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Standards-and-Guidelines/documents/examples/AES_Core128.pdf", "59df07938ee3a0ea139268f99ad7da6d3ae9e833a521a63f56c80c116ac7c210"),
    "AES_Core192.pdf": ("https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Standards-and-Guidelines/documents/examples/AES_Core192.pdf", "2188993f2cd073189bde7b7cca9fa5c6605a5309bcb0eab4e396bf30bf3c710a"),
    "AES_Core256.pdf": ("https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Standards-and-Guidelines/documents/examples/AES_Core256.pdf", "8caf33781b8d4b9564c7e95a7690e491ca1d95efe9a31cdea2977deaf4c7b4ce"),
}


def import_nist(directory):
    from pypdf import PdfReader
    for name, (_, digest) in SOURCES.items():
        assert hashlib.sha256((directory / name).read_bytes()).hexdigest() == digest, name
    pages = PdfReader(directory / "fips197-upd1.pdf").pages

    def table(page, first):
        lines = [line.strip() for line in page.extract_text().splitlines()]
        start = lines.index(first)
        values = [int(line, 16) for line in lines[start:] if re.fullmatch(r"[0-9a-f]{2}", line)][:256]
        assert len(values) == 256
        return [values[column * 16 + row] for row in range(16) for column in range(16)]

    data = {"sources": {name: {"url": url, "sha256": digest} for name, (url, digest) in SOURCES.items()},
            "sbox": table(pages[21], "63"), "inverse_sbox": table(pages[30], "52"), "core": []}
    assert data["sbox"][0] == 0x63 and data["sbox"][0x53] == 0xed
    assert data["inverse_sbox"][0x63] == 0
    for bits, rounds in [(128, 10), (192, 12), (256, 14)]:
        text = "\n".join(page.extract_text(extraction_mode="layout") for page in PdfReader(directory / f"AES_Core{bits}.pdf").pages)
        text = text.split(f"ECB-AES{bits} (Encryption)", 1)[1].split(f"ECB-AES{bits} (Decryption)", 1)[0]
        key = "".join(re.search(r"Key is\s*((?:[0-9A-F]{8}\s+)+)Plaintext is", text)[1].split()).lower()
        plain = "".join(re.search(r"Plaintext is\s*((?:[0-9A-F]{8}\s+)+)KeyAddition", text)[1].split()).lower()
        ciphertext = "".join(re.search(r"Ciphertext is\s*((?:[0-9A-F]{8}\s*)+)", text)[1].split()).lower()
        stages = [(kind, "".join(value.split()).lower()) for kind, value in re.findall(r"(KeyAddition|Substitution|ShiftRow|MixColumn)\s+((?:[0-9A-F]{8}\s+){3}[0-9A-F]{8})", text)]
        assert len(key) == bits // 4 and len(plain) == len(ciphertext) == 128
        assert len(stages) == 16 * rounds, (bits, len(stages))
        blocks, keys = [], None
        for index in range(4):
            block_stages = stages[index * 4 * rounds:(index + 1) * 4 * rounds]
            previous = plain[index*32:(index+1)*32]
            derived_keys = []
            for kind, value in block_stages:
                if kind == "KeyAddition":
                    derived_keys.append(bytes(x ^ y for x, y in zip(bytes.fromhex(previous), bytes.fromhex(value))).hex())
                previous = value
            assert previous == ciphertext[index*32:(index+1)*32]
            assert derived_keys[0] == key[:32]
            if keys is None:
                keys = derived_keys
            assert derived_keys == keys
            blocks.append({"plaintext": plain[index*32:(index+1)*32], "ciphertext": previous, "stages": block_stages})
        data["core"].append({"key_bits": bits, "key": key, "round_keys": keys, "blocks": blocks})
    (ROOT / "src/aes/nist.json").write_text(json.dumps(data, indent=2) + "\n")


def multiply(a, b):
    result = 0
    for _ in range(8):
        if b & 1:
            result ^= a
        a = ((a << 1) ^ (0x11b if a & 0x80 else 0)) & 255
        b >>= 1
    return result


def substitution(a):
    inverse = next((b for b in range(1, 256) if multiply(a, b) == 1), 0)
    result = inverse ^ 0x63
    for shift in range(1, 5):
        result ^= ((inverse << shift) | (inverse >> (8 - shift))) & 255
    return result


def generate(data):
    expected = [substitution(value) for value in range(256)]
    assert expected == data["sbox"]
    assert all(data["inverse_sbox"][output] == value for value, output in enumerate(expected))
    literal = lambda xs: "[" + ", ".join(map(str, xs)) + "]"
    lines = ["// Generated by tools/generate_aes.py from pinned official NIST data.", "", "///|", 'test "FIPS 197 Table 4 and Table 6 match algebraic Sbox generation" {', f"  assert_sbox_fixture({literal(data['sbox'])}, {literal(data['inverse_sbox'])})", "}"]
    for core in data["core"]:
        lines += ["", "///|", f'test "official NIST AES-{core["key_bits"]} intermediate state transformations" {{', "  let context = required(tables())"]
        for block in core["blocks"]:
            lines += [f'  assert_transform_fixture(context, "{core["key"]}", "{block["plaintext"]}", [']
            lines += [f'    ("{kind}", "{value}"),' for kind, value in block["stages"]]
            lines += ["  ])"]
        lines += ["}"]
    path = ROOT / "src/aes/nist_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote official 256-entry tables and 12 block transformation traces to {path.relative_to(ROOT)}")


def refresh_openssl():
    rng = random.Random(202611153)
    cases = []
    for bits in (128, 192, 256):
        width = bits // 8
        inputs = [(bytes(width), bytes(16)), (bytes([255])*width, bytes([255])*16),
                  (bytes(range(width)), bytes(range(16))), (bytes(range(width)), bytes.fromhex("00112233445566778899aabbccddeeff"))]
        inputs += [(rng.randbytes(width), rng.randbytes(16)) for _ in range(32)]
        for key, plain in inputs:
            command = ["openssl", "enc", f"-aes-{bits}-ecb", "-K", key.hex(), "-nosalt", "-nopad"]
            answer = subprocess.run(command + ["-e"], input=plain, capture_output=True, check=True).stdout
            assert len(answer) == 16
            assert subprocess.run(command + ["-d"], input=answer, capture_output=True, check=True).stdout == plain
            cases.append({"key_bits": bits, "key": key.hex(), "plaintext": plain.hex(), "ciphertext": answer.hex()})
    data = {"oracle": subprocess.run(["openssl", "version"], capture_output=True, check=True).stdout.decode().strip(),
            "seed": 202611153, "command": "openssl enc -aes-{bits}-ecb -K <fixture-key> -nosalt -nopad -e", "blocks": cases}
    (ROOT / "src/aes/openssl.json").write_text(json.dumps(data, indent=2) + "\n")


def generate_cipher(data, external):
    lines = ["// Generated by tools/generate_aes.py; official round keys and external OpenSSL blocks."]
    for core in data["core"]:
        lines += ["", "///|", f'test "official NIST AES-{core["key_bits"]} complete key expansion" {{', "  let context = required(tables())", f'  assert_schedule_fixture(context, "{core["key"]}", [']
        lines += [f'    "{key}",' for key in core["round_keys"]]
        lines += ["  ])", "}"]
    for bits in (128, 192, 256):
        cases = [case for case in external["blocks"] if case["key_bits"] == bits]
        assert len(cases) == 36
        lines += ["", "///|", f'test "independent OpenSSL AES-{bits} block encrypt and decrypt fixtures" {{', "  let context = required(tables())"]
        lines += [f'  assert_block_fixture(context, "{case["key"]}", "{case["plaintext"]}", "{case["ciphertext"]}")' for case in cases]
        lines += ["}"]
    path = ROOT / "src/aes/cipher_oracle_wbtest.mbt"
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote 3 official complete key schedules and {len(external['blocks'])} OpenSSL block fixtures")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--import-nist", type=Path)
    parser.add_argument("--refresh-openssl", action="store_true")
    args = parser.parse_args()
    if args.import_nist:
        import_nist(args.import_nist)
    data = json.loads((ROOT / "src/aes/nist.json").read_text())
    generate(data)
    if args.refresh_openssl:
        refresh_openssl()
    generate_cipher(data, json.loads((ROOT / "src/aes/openssl.json").read_text()))


if __name__ == "__main__":
    main()
