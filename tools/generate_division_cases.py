#!/usr/bin/env python3
"""Independent Python arbitrary-precision division/GCD fixtures."""
import argparse
from math import gcd
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parent.parent
DESTINATION = ROOT / "src/binary/division_oracle_wbtest.mbt"


def generate():
    rng = random.Random(20261116)
    pairs = [(0, 0), (0, 17), (17, 0), (1, 1), (128, 256)]
    for width in [16, 64, 128, 512, 2048]:
        base = (1 << (width - 1)) | rng.getrandbits(width - 1)
        pairs.extend([(base, base), (base - 1, base), (base + 1, base),
                      (base * 6, base * 10)])
        for difference in [0, 1, 3, 8, 9, 16]:
            divisor = (1 << (width - 1)) | rng.getrandbits(width - 1)
            dividend = (1 << (width + difference - 1)) | rng.getrandbits(width + difference - 1)
            pairs.append((dividend, divisor))
    for _ in range(16):
        pairs.append((rng.getrandbits(256), rng.getrandbits(128) | 1))
    lines = ['// Generated by tools/generate_division_cases.py; Python int/math.gcd oracle.',
             '///|', 'test "arbitrary precision quotient remainder and gcd fixtures" {',
             '  let fixtures : Array[(String, String, String, String, String)] = [']
    for a, b in pairs:
        q, r = divmod(a, b) if b else (0, 0)
        values = [a, b, q, r, gcd(a, b)]
        lines.append('    (' + ', '.join('"' + format(v, 'x') + '"' for v in values) + '),')
    lines += ['  ]', '  for (a, b, q, r, g) in fixtures {',
              '    let a = @oracle.binary_from_hex(a)',
              '    let b = @oracle.binary_from_hex(b)',
              '    let q = @oracle.binary_from_hex(q)',
              '    let r = @oracle.binary_from_hex(r)',
              '    let g = @oracle.binary_from_hex(g)',
              '    for cutoff in [3, 8] {', '      let limit = @oracle.nat(cutoff)',
              '      if is_zero(b) {',
              '        assert_eq(trial_divmod(a, b, limit), None)',
              '        assert_eq(trial_remainder(a, b, limit), None)',
              '      } else {',
              '        assert_eq(trial_divmod(a, b, limit), Some((q, r)))',
              '        assert_eq(trial_remainder(a, b, limit), Some(r))',
              '      }',
              '      assert_eq(trial_gcd(a, b, limit), g)',
              '      assert_eq(trial_remainder_gcd(a, b, limit), g)',
              '    }', '  }', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        def normalized(source):
            # moon fmt adds optional trailing commas when it wraps a tuple.
            return re.sub(r',(?=[)\]])', '', re.sub(r'\s+', '', source))
        if not DESTINATION.exists() or normalized(DESTINATION.read_text()) != normalized(text):
            raise SystemExit('Division oracle fixtures are stale')
    else:
        DESTINATION.write_text(text)


if __name__ == '__main__':
    main()
