ARTIFACT=ROOT/'.tools/elimination-20261116/oracle.json'


def determinant(a):
 n=len(a);out=F(0)
 for p in permutations(range(n)):
  term=F((-1)**sum(p[i]>p[j] for i in range(n) for j in range(i+1,n)))
  for i,j in enumerate(p):term*=a[i][j]
  out+=term
 return out


def sylvester(f,g):
 m,n=len(f)-1,len(g)-1;size=m+n
 return [[F(0)]*i+list(f)+[F(0)]*(size-i-len(f)) for i in range(n)]+\
        [[F(0)]*i+list(g)+[F(0)]*(size-i-len(g)) for i in range(m)]


def bezout(f,g):
 rows=sylvester(f,g);size=len(rows)
 # Production uses transpose(rows). Its adjugate last column is the last
 # column of cofactor(rows), computed directly with permutation minors.
 return [(-1)**(i+size-1)*determinant([[v for j,v in enumerate(row) if j!=size-1]
         for r,row in enumerate(rows) if r!=i]) for i in range(size)]


def rat(q):
 q=F(q)
 return f'elimination_rat({str(q<0).lower()}, "{abs(q.numerator):x}", "{q.denominator:x}")'


def chain(values):return '@oracle.chain(['+', '.join(map(rat,values))+'])'


def cases():
 rng=random.Random(0xE11A)
 out=[([F(0)],[F(0)]),([F(2,3)],[F(-7,11)]),
      ([F(0)],[F(1),F(2),F(3)]),([F(1),F(2)],[F(3)]),
      ([F(1),F(-1)],[F(1),F(-1)]),([F(0),F(1),F(2)],[F(0),F(3),F(4)]),
      ([F(0),F(1),F(2)],[F(1),F(3)]),([F(0),F(0),F(2)],[F(1),F(3)])]
 for m in range(4):
  for n in range(4):
   for _ in range(4):
    out.append(([F(rng.randrange(-5,6),rng.choice([1,3,7])) for _ in range(m+1)],
                [F(rng.randrange(-5,6),rng.choice([1,5,11])) for _ in range(n+1)]))
 out.append(([F(2**90+3,17),F(-7,13),F(1,5)],[F(1,7),F(-(2**80+9),19)]))
 return out


def generate():
 lines=['// Generated by tools/generate_elimination.py; independent permutation/cofactor oracle.']
 records=[]
 for i,(f,g) in enumerate(cases()):
  value=determinant(sylvester(f,g));cofactors=bezout(f,g)
  n=len(g)-1
  lines+=['','///|',f'test "elimination independent Sylvester permutations {i}" {{',
          f'  elimination_fixture({chain(f)}, {chain(g)}, {rat(value)}, {chain(cofactors[:n])}, {chain(cofactors[n:])})','}']
  records.append(dict(f=list(map(str,f)),g=list(map(str,g)),resultant=str(value),cofactors=list(map(str,cofactors))))
 z=sp.Symbol('z');rng=random.Random(0xD15C);disc_records=[]
 for d in range(5):
  symbols=sp.symbols(f'a0:{d+1}')
  universal=sp.Integer(1) if d<2 else sp.discriminant(sum(symbols[i]*z**(d-i) for i in range(d+1)),z)
  for j in range(12):
   f=[F(rng.randrange(-5,6),rng.choice([1,3,7,13])) for _ in range(d+1)]
   if j%3==0:f[0]=F(0)
   if j==0:f=[F(0)]*(d+1)
   value=F(universal.subs(dict(zip(symbols,[sp.Rational(q.numerator,q.denominator) for q in f]))))
   lines+=['','///|',f'test "elimination independent universal discriminant d{d} case{j}" {{',
           f'  let f = dense({chain(f)}, @berkowitz.rationals())',
           f'  let expected = {rat(value)}',
           '  assert_eq(discriminant(f, @berkowitz.rationals()), Some(expected))',
           '  assert_true(check_discriminant(f, expected, @berkowitz.rationals(), fn(a,b) { a == b }))','}']
   disc_records.append(dict(degree=d,coefficients=list(map(str,f)),value=str(value)))
 for a in range(8):
  for b in range(8):
   f=[(a>>i)&1 for i in range(3)];g=[(b>>i)&1 for i in range(3)]
   expected=int(determinant(sylvester(f,g)))%4
   lines+=['','///|',f'test "elimination zero-divisor ring mod4 {a} {b}" {{',
           f'  elimination_mod4_fixture({f}, {g}, {expected})','}']
 return '\n'.join(lines)+'\n',dict(resultants=records,discriminants=disc_records,sympy=sp.__version__)


def mbpoly(expr,gens):
 expr=sp.expand(expr)
 terms=[] if expr==0 else (sp.Poly(expr,*gens).terms() if gens else [((),expr)])
 return f'elimination_poly({len(gens)}, ['+', '.join('('+rat(F(c))+', '+str(list(e))+')' for e,c in terms)+'])'


def projection_cases():
 x,y,z=sp.symbols('x y z');rng=random.Random(0xCAD)
 out=[([x,y],1,y*y+x,y+x,2,1),([x,y],0,x*x+y,x+y,2,1),
      ([x,y,z],1,x*y+z,y*y+x*z,1,2),([x,y,z],0,x*x+y*z,x+y+z,2,1),
      ([x,y,z],2,z*z+x*y+1,z+x-y,2,1),([y],0,y*y+sp.Rational(2,3),3*y-sp.Rational(5,7),2,1),
      ([x,y],1,x*y+1,y+1,1,1),([x,y],1,y+1,y*y+x,2,2),
      ([x,y],1,sp.Integer(0),sp.Integer(0),0,0),([x,y],1,sp.Rational(2,7),sp.Rational(-3,11),0,0),
      ([x,y],1,(y-x)**2,(y-x)*(y+1),2,2),([x,y],1,y**3+x*y+1,y*y+x,3,2)]
 for i in range(12):
  m=1+i%3;n=1+i%2
  def coefficient():return sp.Rational(rng.randrange(-3,4),rng.choice([3,7,11]))*(rng.choice([1,x,x+1,x*x+1]))
  f=sum(coefficient()*y**j for j in range(m+1));g=sum(coefficient()*y**j for j in range(n+1))
  out.append(([x,y],1,sp.expand(f),sp.expand(g),m,n))
 return out


def generate_projection():
 lines=['// Independent symbolic permutation determinant; discriminants specialize universal coefficient formulas.']
 records=[]
 for i,(gens,selected,f,g,m,n) in enumerate(projection_cases()):
  y=gens[selected];others=[v for j,v in enumerate(gens) if j!=selected]
  left=[sp.expand(f).coeff(y,j) for j in range(m,-1,-1)]
  right=[sp.expand(g).coeff(y,j) for j in range(n,-1,-1)]
  value=sp.expand(determinant(sylvester(left,right)))
  if m<2:disc=sp.Integer(1)
  else:
   a=sp.symbols(f'a0:{m+1}');t=sp.Symbol('T')
   universal=sp.discriminant(sum(a[j]*t**(m-j) for j in range(m+1)),t)
   disc=sp.expand(universal.subs(dict(zip(a,left)), simultaneous=True))
  lines+=['','///|',f'test "elimination independent polynomial coefficient projection {i}" {{',
          f'  elimination_projection_fixture({mbpoly(f,gens)}, {mbpoly(g,gens)}, {selected}, {m}, {n}, {mbpoly(value,others)}, {mbpoly(disc,others)})','}']
  records.append(dict(variables=list(map(str,gens)),selected=selected,left=str(f),right=str(g),left_degree=m,right_degree=n,resultant=str(value),discriminant=str(disc)))
 return '\n'.join(lines)+'\n',records


def tokens(source):
 source=re.sub(r',\s*([\]\)])',r'\1',source)
 return re.findall(r'"(?:\\.|[^"\\])*"|\S',source)


def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 source,data=generate()
 projection,project_records=generate_projection();data['projections']=project_records
 if args.check:
  assert tokens(OUTPUT.read_text())==tokens(source),'elimination fixture drift'
  assert tokens(PROJECTION.read_text())==tokens(projection),'projection fixture drift'
 else:
  OUTPUT.write_text(source);PROJECTION.write_text(projection)
 ARTIFACT.parent.mkdir(parents=True,exist_ok=True)
 ARTIFACT.write_text(json.dumps(data,indent=2)+'\n')
 print(f"{'Checked' if args.check else 'Wrote'} {len(data['resultants'])} permutation/cofactor cases, {len(data['discriminants'])} universal discriminants, 64 mod4 pairs, {len(project_records)} polynomial projections.")


if __name__=='__main__':main()
