#!/usr/bin/env python3
"""Rebuild committed Lucas certificate fixtures with independent Python integers.

Only fixture generation searches for factors and primitive-root witnesses. The
MoonBit kernel checks the resulting trees without calling this program or SymPy.
The small corpus uses complete trial division, so it needs no optional package.
"""
from functools import lru_cache
from math import gcd
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SMALL_LIMIT = 128
LARGE_PRIMES = [257, 65537, 998244353, 2147483647, 2305843009213693951]


def factors(n: int) -> list[int]:
    result = []
    d = 2
    while d * d <= n:
        while n % d == 0:
            result.append(d)
            n //= d
        d += 1
    if n > 1:
        result.append(n)
    return result


def is_prime(n: int) -> bool:
    return n >= 2 and factors(n) == [n]


@lru_cache(None)
def certificate(p: int) -> tuple[int, tuple[int, ...]]:
    if p == 2:
        return 1, ()
    fs = tuple(factors(p - 1))
    assert fs and all(is_prime(q) for q in fs)
    a = next(a for a in range(2, p)
             if pow(a, p - 1, p) == 1
             and all(pow(a, (p - 1) // q, p) != 1 for q in set(fs)))
    for q in fs:
        certificate(q)
    return a, fs


def numeral(n: int) -> str:
    return f'@oracle.binary_from_hex("{n:x}")'


def chain(items: list[str]) -> str:
    result = 'Nil'
    for item in reversed(items):
        result = f'Cons({item}, {result})'
    return result


def main() -> None:
    primes = [n for n in range(SMALL_LIMIT) if is_prime(n)] + LARGE_PRIMES
    for p in primes:
        certificate(p)
    # Cache helpers are emitted in numeric order, so every child is already named.
    all_primes = sorted({q for p in primes for q in descendants(p)})
    out = '// Generated by tools/generate_primality.py; Python integer oracle.\n'
    for p in all_primes:
        a, fs = certificate(p)
        expression = 'Two' if p == 2 else (
            f'Lucas({numeral(p)}, {numeral(a)}, '
            f'{chain([f"cert_{q}()" for q in fs])})')
        out += f'///|\nfn cert_{p}() -> Certificate {{\n  {expression}\n}}\n\n'
    out += '///|\nfn fixture(n : Int32) -> Certificate? {\n  match n {\n'
    for p in primes:
        if p < SMALL_LIMIT:
            out += f'    {p} => Some(cert_{p}())\n'
    out += '    _ => None\n  }\n}\n\n'
    out += '///|\nfn predecessor_factors(n : Int32) -> @core.Chain[Certificate] {\n  match n {\n'
    for n in range(2, SMALL_LIMIT):
        out += f'    {n} => {chain([f"cert_{q}()" for q in factors(n - 1)])}\n'
    out += '    _ => Nil\n  }\n}\n\n'
    out += '///|\ntest "multi-digit certified primes from independent Python witnesses" {\n'
    for p in LARGE_PRIMES:
        out += f'  assert_eq(check(cert_{p}()).map(value), Some({numeral(p)}))\n'
    out += '}\n'
    (ROOT / 'src/primality/vectors_wbtest.mbt').write_text(out)
    factor_vectors()


def factor_vectors() -> None:
    """Independent deterministic rho traces, used only to build fixtures."""
    out = '// Generated by tools/generate_primality.py; Python math.gcd oracle.\n'
    out += '///|\ntest "multi-digit rho factors agree with committed Python integer traces" {\n'
    for n in [10007 * 10009, 65537 * 4294967291, 1000003 * 1000033]:
        x = y = 2
        for iteration in range(1, 1025):
            x = (x * x + 1) % n
            y = (y * y + 1) % n
            y = (y * y + 1) % n
            d = gcd(x - y, n)
            if d != 1:
                break
        assert 1 < d < n and n % d == 0
        out += f'  let n = {numeral(n)}\n'
        out += f'  let machine = start(n, {numeral(2)}, {numeral(1)}).unwrap()\n'
        out += f'  match run(machine, @oracle.nat({iteration - 1})) {{\n'
        out += '    Suspended(next) => match step(next) {\n'
        out += f'      Found(split) => {{\n        assert_eq(divisor(split), {numeral(d)})\n'
        out += f'        assert_eq(cofactor(split), {numeral(n // d)})\n'
        out += '        assert_eq(@binary.multiply(divisor(split), cofactor(split)), n)\n'
        out += '      }\n      _ => abort("expected exact rho transition")\n    }\n'
        out += '    _ => abort("expected suspension immediately before factor")\n  }\n'
    out += '}\n'
    (ROOT / 'src/factor/vectors_wbtest.mbt').write_text(out)


def descendants(p: int) -> set[int]:
    _, fs = certificate(p)
    return {p}.union(*(descendants(q) for q in fs))


if __name__ == '__main__':
    main()
