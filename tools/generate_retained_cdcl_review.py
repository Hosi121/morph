#!/usr/bin/env python3
"""Generate monotone clause schedules with an independent exhaustive Bool oracle.

No solver evaluator, normalization or watch code is imported. Every prefix is
checked by Python assignment enumeration and materialized as a model count.
"""
from __future__ import annotations
import argparse
import hashlib
import itertools
import json
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'src/cdcl/independent_retained_schedules_wbtest.mbt'
REPORT = ROOT / 'docs/measurements/retained-cdcl-review-oracle-20261117.json'
SEED = 0x91C0D3


def models(clauses, n):
    return [list(bits) for bits in itertools.product([False, True], repeat=n)
            if all(any(bits[abs(lit)-1] == (lit > 0) for lit in clause) for clause in clauses)]


def corpus():
    randomizer = random.Random(SEED)
    result = []
    for n in range(2, 7):
        for index in range(32):
            labels = list(range(n)) if index % 2 == 0 else [0, 2, 7, 31, 255, 257][:n]
            def clause(width=None, usable=n):
                if width is None:
                    width = randomizer.choice([1, 2, 2, 3, 3, 4])
                return [randomizer.choice([-1, 1])*randomizer.randrange(1, usable+1) for _ in range(width)]
            usable=max(1,n-1)
            base=[clause(width=randomizer.choice([2, 3]),usable=usable) for _ in range(n+1)]
            if index % 4 == 0:
                base.append([1,-1])
            added=[clause() for _ in range(6)]
            # Register a new tail ID even after the tautological pair.
            added[0]=[1,-1,n,n]
            if index % 4 == 0:
                added[1]=[n,n]
            if index % 8 == 1:
                added[3]=[]
            added.extend([[n],[-n]])
            budgets=[randomizer.choice([0,0,1,1,2,3,100]) for _ in added]
            prefixes=[]
            current=[list(c) for c in base]
            for c in [None]+added:
                if c is not None:
                    current.append(c)
                assignments=models(current,n)
                prefixes.append({'models':len(assignments),'first_model':assignments[0] if assignments else None})
            result.append({'id':f'n{n}-schedule{index:02d}','labels':labels,'base':base,'added':added,
                           'budgets':budgets,'prefixes':prefixes})
    return result


def moon_array(value):
    if isinstance(value,list):return '['+', '.join(moon_array(v) for v in value)+']'
    if isinstance(value,bool):return str(value).lower()
    return str(value)


def syntax(value):
    value=re.sub(r'//[^\n]*','',value)
    return re.sub(r'\s|,(?=\s*[\]\)])','',value)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    cases=corpus()
    lines=['// Generated by tools/generate_retained_cdcl_review.py; Python exhaustive assignment oracle.']
    for n in range(2,7):
        lines+=['','///|',f'test "independent retained schedules with {n} logical variables" {{']
        for case in cases:
            if len(case['labels'])!=n:continue
            lines += ['  retained_review_schedule(',f'    "{case["id"]}",',
                      '    '+moon_array(case['labels'])+',','    '+moon_array(case['base'])+',',
                      '    '+moon_array(case['added'])+',','    '+moon_array(case['budgets'])+',',
                      '    '+moon_array([p['models'] for p in case['prefixes']])+',','  )']
        lines+=['}']
    source='\n'.join(lines)+'\n'
    provenance={'generator':'tools/generate_retained_cdcl_review.py','oracle':'independent exhaustive itertools.product Bool assignments; no solver imports',
                'seed':SEED,'schedules':len(cases),'variables':[2,3,4,5,6],'additions_per_schedule':8,
                'prefixes_per_schedule':9,'prefix_decisions':len(cases)*9,
                'execution_modes':['watched','scanning'],'interleaving_budgets':[0,1,2,3,100],
                'sparse_ids':[0,2,7,31,255,257],'full_completion_fuel':2000,
                'input_scope':'monotone external clauses; arbitrary paused/candidate additions; no deletion/assumptions',
                'source_snapshot':'21f36f13cd90e9cb5e8a29f6f0a36e5ecf130992','cases':cases}
    provenance['corpus_sha256']=hashlib.sha256(json.dumps(cases,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    if args.check:
        assert syntax(OUTPUT.read_text())==syntax(source),'generated MoonBit fixtures differ'
        assert json.loads(REPORT.read_text())==provenance,'oracle provenance differs'
    else:
        OUTPUT.write_text(source)
        REPORT.write_text(json.dumps(provenance,indent=2)+'\n')
    print(('Verified' if args.check else 'Generated')+f' {len(cases)} schedules / {len(cases)*9} independently enumerated prefix decisions; watched+scanning execution.')


if __name__=='__main__':main()
