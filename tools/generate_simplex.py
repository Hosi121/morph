#!/usr/bin/env python3
"""Exact 2D vertex-enumeration oracle, independent of tableau pivoting."""
from fractions import Fraction as Q
from itertools import combinations
from pathlib import Path
import random

rng = random.Random(20261115)
cases = []
for case_index in range(448):
    rows = [[1, 0], [0, 1]]
    bounds = [rng.randrange(1, 6), rng.randrange(1, 6)]
    for _ in range(rng.randrange(1, 4)):
        rows.append([rng.randrange(-3, 4), rng.randrange(-3, 4)])
        bounds.append(rng.randrange(0 if case_index < 192 else -8, 9))
    cost = [rng.randrange(-3, 5), rng.randrange(-3, 5)]
    constraints = list(zip(rows, bounds)) + [([-1, 0], 0), ([0, -1], 0)]
    vertices = []
    for ((a, b), u), ((c, d), v) in combinations(constraints, 2):
        det = a*d-b*c
        if not det:
            continue
        x, y = Q(u*d-b*v, det), Q(a*v-u*c, det)
        if all(a*x+b*y <= bound for (a, b), bound in constraints):
            vertices.append((x, y))
    if vertices:
        optimum = max(cost[0]*x+cost[1]*y for x, y in vertices)
        cases.append((rows, bounds, cost, optimum.numerator, optimum.denominator))
    else:
        cases.append((rows, bounds, cost, 0, 0))

lines = ['// Generated by tools/generate_simplex.py; Python Fraction vertex oracle.',
         '///|', 'test "448 exact LP feasibility and objectives versus independent 2D vertex enumeration" {',
         '  let cases : Array[(Array[Array[Int]],Array[Int],Array[Int],Int,Int)] = [']
lines += ['    '+str(case)+',' for case in cases]
lines += ['  ]', '  for (a,b,c,n,d) in cases {', '    let p = make_problem(a,b,c)',
          '    match finish(p) {', '      Optimal(result) => {',
          '        assert_true(d != 0)',
          '        assert_true(check_optimum(p,result))',
          '        assert_eq(result.value,@oracle.rational(n,d))', '      }',
          '      Infeasible(proof) => { assert_eq(d,0); assert_true(check_infeasible(p,proof)) }',
          '      _ => fail("box-constrained LP must be bounded or infeasible")', '    }', '  }', '}', '']
Path('src/simplex/vectors_wbtest.mbt').write_text('\n'.join(lines))
