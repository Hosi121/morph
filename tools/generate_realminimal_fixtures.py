#!/usr/bin/env python3
"""Independent SymPy minimal_polynomial and exact isolating-interval fixtures."""
from pathlib import Path
import json
import subprocess
import sympy as sp

ROOT=Path(__file__).resolve().parents[1]
x=sp.Symbol('x')
expressions=[
 sp.Integer(0),sp.Rational(1,2),sp.Rational(-7,3),sp.Integer(2),
 sp.sqrt(2),-sp.sqrt(2),sp.sqrt(3),1/sp.sqrt(2),
 1+sp.sqrt(2),-2+sp.sqrt(3),sp.real_root(2,3),-sp.real_root(2,3),
 sp.sqrt(2)+sp.sqrt(3),sp.sqrt(2)-sp.sqrt(3),(1+sp.sqrt(5))/2,
 2*sp.sqrt(2),sp.Rational(2,3),sp.real_root(3,3),
]

def pair(c):
 c=sp.Rational(c);return (int(c.p),int(c.q))
def cs(p):return [pair(c) for c in reversed(p.all_coeffs())]
def arr(values):return '['+', '.join(f'({a}, {b})' for a,b in values)+']'

lines=['// Generated by tools/generate_realminimal_fixtures.py; independent SymPy minpoly oracle.','']
records=[]
for i,expr in enumerate(expressions):
 minimal=sp.Poly(sp.minimal_polynomial(expr,x),x,domain=sp.QQ).monic()
 assert sp.simplify(minimal.as_expr().subs(x,expr))==0
 for repeated in (False,True):
  raw=sp.Poly(-sp.Rational(3,5)*(minimal.as_expr()**(2 if repeated else 1))*(x-5)*(1 if repeated else x*x+1),x,domain=sp.QQ)
  squarefree=raw.sqf_part()
  chosen=None
  for (lo,hi),_ in sp.intervals(raw,eps=sp.Rational(1,64)):
   if lo==hi:
    if sp.simplify(expr-hi)!=0:continue
    delta=sp.Rational(1,64)
    while squarefree.count_roots(hi-delta,hi)!=1:delta/=2
    lo=hi-delta
   if sp.sign(sp.simplify(expr-lo))==1 and sp.sign(sp.simplify(hi-expr)) in (0,1):
    assert squarefree.count_roots(lo,hi)==1
    chosen=(lo,hi);break
  assert chosen is not None,(expr,raw)
  lo,hi=chosen
  records.append(dict(expression=str(expr),repeated=repeated,input=cs(raw),lower=pair(lo),upper=pair(hi),minimal=cs(minimal)))
  k=len(records)-1
  lines += ['///|',f'test "SymPy minimal polynomial selected-root fixture {k}" {{',
   f'  assert_minpoly_fixture({arr(cs(raw))}, ({pair(lo)[0]}, {pair(lo)[1]}), ({pair(hi)[0]}, {pair(hi)[1]}),',
   f'    {arr(cs(minimal))})','}','']
path=ROOT/'src/realminimal/sympy_wbtest.mbt';path.write_text('\n'.join(lines))
subprocess.run([str(ROOT/'tools/moon'),'fmt',str(path)],cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
out=ROOT/'.tools/realminimal-20261116/sympy-fixtures.json';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(json.dumps(dict(sympy=sp.__version__,oracle='minimal_polynomial and exact root isolation/sign checks',cases=records),indent=2)+'\n')
print(f'generated {len(records)} selected-root minimal polynomial fixtures using SymPy {sp.__version__}')
