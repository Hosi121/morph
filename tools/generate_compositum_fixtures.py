#!/usr/bin/env python3
"""Independent SymPy primitive-element/minpoly and exact common-field maps."""
from pathlib import Path
import json,subprocess
import sympy as sp
from sympy.polys.numberfields import primitive_element,to_number_field
ROOT=Path(__file__).resolve().parents[1];x=sp.Symbol('x')
r2=sp.sqrt(2);r3=sp.sqrt(3);r5=sp.sqrt(5)
# expression a, expression b, optional extra defining factors.
cases=[
 (r2,r3,1,1),(r2,-r2,1,1),(r2,r2,1,1),(r2,sp.sqrt(8),1,1),
 (r2,1+r2,1,1),(r2,sp.Rational(1,2),1,1),(sp.Integer(0),r2,1,1),
 (sp.Integer(0),sp.Integer(0),1,1),(sp.Rational(-7,3),sp.Rational(2,5),1,1),
 ((1+r5)/2,r5,1,1),(r2,r5,1,1),(-r2,r3,1,1),(r3,-r3,1,1),
 (sp.real_root(2,3),r2,1,1),(r2,r2,x-3,1),(sp.Rational(1,2),r2,x-3,1),
 (sp.sqrt(6),r2,1,1),(r2,1/r2,1,1),(1+r2,r2-1,1,1),(r2,r2/3,1,1),
 (sp.Integer(3),sp.Rational(1,2),1,x-3),(sp.Integer(0),sp.Integer(0),x-1,x+1),
]
def pairs(a):return [(int(sp.Rational(c).p),int(sp.Rational(c).q)) for c in a]
def cs(p):return pairs(reversed(p.all_coeffs()))
def arr(a):return '['+', '.join(f'({n}, {d})' for n,d in a)+']'
def pair(q):n,d=pairs([q])[0];return f'({n}, {d})'
def interval(expr,p):
 for (lo,hi),_ in sp.intervals(p,eps=sp.Rational(1,32)):
  if lo==hi:
   if sp.simplify(expr-hi)!=0:continue
   padding=sp.Rational(1,32)
   while p.count_roots(hi-padding,hi)!=1:padding/=2
   lo=hi-padding
  if sp.sign(sp.simplify(expr-lo))==1 and sp.sign(sp.simplify(hi-expr)) in (0,1):return lo,hi
 raise AssertionError(('root not selected',expr,p))
lines=['// Generated by tools/generate_compositum_fixtures.py; independent SymPy common-field maps.',''];records=[]
for i,(a,b,extra_a,extra_b) in enumerate(cases):
 ma=sp.Poly(sp.minimal_polynomial(a,x)*extra_a,x,domain=sp.QQ).monic()
 mb=sp.Poly(sp.minimal_polynomial(b,x)*extra_b,x,domain=sp.QQ).monic()
 ia=interval(a,ma);ib=interval(b,mb)
 pe,_=primitive_element([a,b],x);dimension=sp.degree(pe,x)
 maps=[]
 for seed in range(6):
  theta=sp.expand(a+seed*b)
  minimal=sp.Poly(sp.minimal_polynomial(theta,x),x,domain=sp.QQ).monic()
  if minimal.degree()!=dimension:continue
  ax=to_number_field(a,theta);by=to_number_field(b,theta)
  hx=sp.Poly.from_list(ax.coeffs(),x,domain=sp.QQ);hy=sp.Poly.from_list(by.coeffs(),x,domain=sp.QQ)
  assert sp.rem(sp.Poly(ma.as_expr().subs(x,hx.as_expr()),x),minimal).is_zero
  assert sp.rem(sp.Poly(mb.as_expr().subs(x,hy.as_expr()),x),minimal).is_zero
  assert sp.rem(hx+seed*hy-sp.Poly(x,x),minimal).is_zero
  assert sp.simplify(hx.as_expr().subs(x,theta)-a)==0
  assert sp.simplify(hy.as_expr().subs(x,theta)-b)==0
  maps.append(dict(seed=seed,minimal=cs(minimal),left=cs(hx),right=cs(hy)))
 assert maps
 data=dict(left_expression=str(a),right_expression=str(b),left_definition=cs(ma),right_definition=cs(mb),left_interval=pairs(ia),right_interval=pairs(ib),dimension=int(dimension),maps=maps)
 records.append(data)
 expected='['+', '.join(f'({m["seed"]}, {arr(m["minimal"])}, {arr(m["left"])}, {arr(m["right"])})' for m in maps)+']'
 lines+=['///|',f'test "SymPy common real field and primitive maps fixture {i}" {{',
  f'  assert_compositum_fixture({arr(cs(ma))}, {pair(ia[0])}, {pair(ia[1])},',
  f'    {arr(cs(mb))}, {pair(ib[0])}, {pair(ib[1])}, {dimension}, {expected})','}','']
path=ROOT/'src/compositum/sympy_wbtest.mbt';path.write_text('\n'.join(lines))
subprocess.run([str(ROOT/'tools/moon'),'fmt',str(path)],cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
out=ROOT/'.tools/compositum-20261116/sympy-fixtures.json';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(json.dumps(dict(sympy=sp.__version__,oracle='primitive_element, minimal_polynomial, to_number_field; exact polynomial compositions and expression identities',cases=records),indent=2)+'\n')
print(f'generated {len(records)} common-field fixtures; {sum(len(r["maps"]) for r in records)} exact primitive maps, dimensions 1..6')
