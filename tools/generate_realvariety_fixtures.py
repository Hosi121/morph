#!/usr/bin/env python3
"""Independent SymPy lex bases, solve_poly_system sets and Sturm intervals."""
from argparse import ArgumentParser
from pathlib import Path
import json,subprocess
import sympy as sp
ROOT=Path(__file__).resolve().parents[1]
x,y,z=sp.symbols('x y z')
def ratio(c):
 c=sp.Rational(c);return [int(c.p),int(c.q)]
def terms(p,vs):return [[ratio(c),list(m)] for m,c in sp.Poly(p,*vs,domain=sp.QQ).terms()]
def literal_terms(p,vs):
 return '['+', '.join(f'(({a}, {b}), ['+', '.join(map(str,exps))+'])' for (a,b),exps in terms(p,vs))+']'
def literal_polys(ps,vs):return '['+', '.join(literal_terms(p,vs) for p in ps)+']'
def qlit(v):a,b=ratio(v);return f'({a}, {b})'
def ulit(p,t):return '['+', '.join(qlit(c) for c in reversed(sp.Poly(p,t).all_coeffs()))+']'
def biglit(c):
 c=sp.Rational(c)
 return f'({str(c<0).lower()}, "{abs(int(c.p)):x}", "{int(c.q):x}")'
def bigpoly(p,t):return '['+', '.join(biglit(c) for c in reversed(sp.Poly(p,t).all_coeffs()))+']'
def root_interval(expr,p,t):
 sf=sp.Poly(p,t).sqf_part()
 for (lo,hi),_ in sf.intervals(eps=sp.Rational(1,4096)):
  if lo==hi:
   pad=sp.Rational(1,4096)
   while sf.count_roots(lo-pad,hi)!=1 or sf.eval(lo-pad)==0:pad/=2
   lo-=pad
  if sp.sign(expr-lo)==1 and sp.sign(hi-expr) in (0,1):return lo,hi
 raise AssertionError((expr,p))
def same_tuple(a,b):return all(sp.simplify(c-d)==0 for c,d in zip(a,b))
def generate():
 cases=[([x],[x*x-2],'shape'),([x,y],[x-y*y,y*y-2],'shape'),([x,y],[x-y,y*y-2],'shape'),
 ([x,y,z],[x-y*y,y-z-1,z*z-2],'shape'),([x,y],[x*x-2,y-x],'shape'),
 ([x,y],[x+y-1,x*y-1],'shape'),([x,y],[x*x-y,x-y*y],'shape'),
 ([x,y,z],[x-z*z,y-z**3,z**3-z],'shape'),([x,y],[x-y,(y*y-2)**2],'shape'),
 ([x],[(x-1)**4],'shape'),([x,y],[x-y*y,y*y+1],'shape'),
 ([x,y],[x,y,x-1],'unit'),([x,y],[x*x-1,y*y-1],'unsupported'),
 ([x,y],[x-y],'unsupported'),([x,y,z],[x-y,y-z],'unsupported'),
 ([x,y],[x-y*y,(1024*y-1)*(1024*y-2)],'shape'),
 ([x,y],[x-y,(y-1)**2-sp.Rational(2,1048576)],'shape'),
 ([x],[x**4-5*x*x+4,x**3-x],'shape'),([x,y],[x*y-1,x-y],'shape'),
 ([x,y],[x*y-1,y*y-2],'shape'),([x,y,z],[x-y*z,y-z*z,z*z-3],'shape')]
 records=[];coordinate_records=[];lines=['// Generated by tools/generate_realvariety_fixtures.py; exact independent SymPy oracle.','']
 for i,(vs,inputs,kind) in enumerate(cases):
  gb=sp.groebner(inputs,*vs,order='lex');basis=[p.as_expr() for p in gb.polys]
  rec=dict(variables=[str(v) for v in vs],inputs=[str(p) for p in inputs],basis=[str(p) for p in basis],kind=kind)
  if kind!='shape':
   if kind=='unit':assert basis==[1]
   lines+=['///|',f'test "SymPy real variety fixture {i} {kind}" {{',f'  assert_nonshape_fixture({len(vs)}, {literal_polys(inputs,vs)}, {str(kind=="unit").lower()})','}','']
  else:
   t=vs[-1];g=next(p for p in basis if p.free_symbols<={t} and sp.degree(p,t)>0)
   g=sp.Poly(g,t).monic().as_expr();hs=[]
   for v in vs[:-1]:
    row=next(p for p in basis if sp.degree(p,v)==1 and p.free_symbols<={v,t} and sp.diff(p,v).free_symbols==set())
    h=sp.cancel(-row.subs(v,0)/sp.diff(row,v));h=sp.rem(h,g,t);hs.append(h)
   hs.append(t)
   sf=sp.Poly(g,t).sqf_part();roots=sp.real_roots(sf)
   points=[tuple(sp.simplify(h.subs(t,a)) for h in hs) for a in roots]
   solved=sp.solve_poly_system(inputs,*vs)
   real_solved=[tuple(v) for v in (solved or []) if all(c.is_real is True for c in v)]
   assert len(real_solved)==len(points),(inputs,points,real_solved)
   assert all(any(same_tuple(a,b) for b in real_solved) for a in points),(inputs,points,real_solved)
   intervals=[]
   for (lo,hi),_ in sf.intervals(eps=sp.Rational(1,4096)):
    if lo==hi:
     pad=sp.Rational(1,4096)
     while sf.count_roots(lo-pad,hi)!=1 or sf.eval(lo-pad)==0:pad/=2
     lo-=pad
    intervals.append((lo,hi))
   assert len(intervals)==len(points)
   for a,(lo,hi) in zip(roots,intervals):assert sp.sign(a-lo)==1 and sp.sign(hi-a) in (0,1)
   rec.update(eliminant=terms(g,[t]),coordinates=[terms(h,[t]) for h in hs],real_solutions=[[str(c) for c in p] for p in points],intervals=[[ratio(lo),ratio(hi)] for lo,hi in intervals])
   ilit='['+', '.join(f'({qlit(lo)}, {qlit(hi)})' for lo,hi in intervals)+']'
   lines+=['///|',f'test "SymPy real variety fixture {i} shape" {{',f'  assert_variety_fixture({len(vs)}, {literal_polys(inputs,vs)},',f'    {ulit(g,t)}, ['+', '.join(ulit(h,t) for h in hs)+f'], {ilit})','}','']
   w=sp.Symbol('w')
   for point_index,point in enumerate(points):
    for coordinate_index,(h,value) in enumerate(zip(hs,point)):
     char=sp.resultant(g,w-h,t).expand()
     minimum=sp.minpoly(value,w)
     lo,hi=root_interval(value,minimum,w)
     assert sp.degree(char,w)==sp.degree(g,t)
     coordinate_records.append(dict(system=i,point=point_index,index=coordinate_index,expression=str(value),characteristic=terms(char,[w]),minimal=terms(minimum,[w]),lower=ratio(lo),upper=ratio(hi)))
     lines+=['///|',f'test "SymPy coordinate norm {i} point {point_index} coordinate {coordinate_index}" {{',
             f'  assert_coordinate_fixture({len(vs)}, {literal_polys(inputs,vs)}, {point_index}, {coordinate_index},',
             f'    {bigpoly(char,w)}, {bigpoly(minimum,w)}, {biglit(lo)}, {biglit(hi)})','}','']
  records.append(rec)
 text=subprocess.run([str(ROOT/'.tools/moon/bin/moonfmt'),'-'],input='\n'.join(lines),text=True,capture_output=True,check=True).stdout
 stats={k:sum(r['kind']==k for r in records) for k in ['shape','unit','unsupported']};stats['real_points']=sum(len(r.get('real_solutions',[])) for r in records);stats['coordinate_evaluations']=len(coordinate_records)
 return {ROOT/'src/realvariety/fixtures_wbtest.mbt':text,ROOT/'docs/research/realvariety-20261116-fixtures.json':json.dumps(dict(sympy=sp.__version__,statistics=stats,cases=records,coordinates=coordinate_records),indent=2)+'\n'},stats

def main():
 p=ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args();artifacts,stats=generate()
 for path,text in artifacts.items():
  if args.check:
   if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale artifact: {path.relative_to(ROOT)}')
  else:path.write_text(text)
 print(json.dumps(stats,sort_keys=True))
if __name__=='__main__':main()
