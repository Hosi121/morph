#!/usr/bin/env python3
"""Independent indexed Fraction oracle for exact finite Markov kernels.

Production uses immutable unary/list ADTs. This oracle uses host indexing,
ordinary integer exponent schedules, and Fraction matrix arithmetic. --check
regenerates the complete MoonBit corpus, including all canonical expected values.
"""
from argparse import ArgumentParser
from fractions import Fraction as Q
from pathlib import Path
from random import Random
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/markov/fraction_fixtures_wbtest.mbt"


def multiply(a, b):
    return [[sum((a[i][k] * b[k][j] for k in range(len(b))), Q())
             for j in range(len(b[0]))] for i in range(len(a))]


def power(a, exponent):
    result = [[Q(i == j) for j in range(len(a))] for i in range(len(a))]
    for _ in range(exponent):
        result = multiply(result, a)
    return result


def vector(values):
    return "[" + ", ".join(f"({v.numerator}, {v.denominator})" for v in values) + "]"


def matrix(rows):
    return "[" + ", ".join(vector(row) for row in rows) + "]"


def fixtures():
    for a in range(5):
        for b in range(5):
            yield [[Q(a, 4), 1-Q(a, 4)], [Q(b, 4), 1-Q(b, 4)]]
    yield [[Q(1)]]
    yield [[Q(1),Q(),Q()], [Q(),Q(1),Q()], [Q(1,3),Q(2,3),Q()]]
    yield [[Q(),Q(1),Q()], [Q(),Q(),Q(1)], [Q(1),Q(),Q()]]
    yield [[Q(1,2),Q(1,2),Q(),Q()], [Q(),Q(1,3),Q(2,3),Q()],
           [Q(),Q(),Q(1,4),Q(3,4)], [Q(),Q(),Q(),Q(1)]]


def render():
    lines = ["// Generated by tools/generate_markov_fixtures.py; independent Python Fraction oracle.", ""]
    count = 0
    for index, rows in enumerate(fixtures()):
        initial = [Q(i+1, sum(range(1, len(rows)+1))) for i in range(len(rows))]
        lines += ["///|", f'test "Fraction Markov evolution and powers {index}" {{']
        for exponent in range(7):
            expected = power(rows, exponent)
            evolved = multiply([initial], expected)[0]
            lines += [f"  fraction_kernel_fixture({matrix(rows)}, {exponent}, {matrix(expected)}, {vector(initial)}, {vector(evolved)})"]
            count += 1
        lines += ["}", ""]
    rng = Random(20261118)
    for index in range(8):
        n = 1 + index % 4
        def stochastic():
            weights = [[rng.randrange(1, 5) for _ in range(n)] for _ in range(n)]
            return [[Q(v, sum(row)) for v in row] for row in weights]
        a, b = stochastic(), stochastic()
        lines += ["///|", f'test "Fraction Markov ordered composition {index}" {{',
                  f"  fraction_composition_fixture({matrix(a)}, {matrix(b)}, {matrix(multiply(a,b))})", "}", ""]
    return "\n".join(lines), count


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, count = render()
    formatter = ROOT / ".tools/moon/bin/moonfmt"
    executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None:
        raise SystemExit("moonfmt is required to canonicalize generated fixtures")
    source = subprocess.run([executable, "-"], input=source, text=True,
                            capture_output=True, check=True).stdout
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != source:
            raise SystemExit("Markov Fraction fixture drift: " + str(OUTPUT))
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(source)
    print(f"{count} complete exact powers/evolutions and 8 ordered compositions.")


if __name__ == "__main__":
    main()
