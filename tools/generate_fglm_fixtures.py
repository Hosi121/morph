#!/usr/bin/env python3
"""SymPy QQ FGLM/direct-order and independent staircase enumeration fixtures."""
from itertools import product
from pathlib import Path
from random import Random
import json
import subprocess
import sympy as sp
from sympy.polys.orderings import monomial_key

ROOT=Path(__file__).resolve().parents[1]
x,y,z,w=sp.symbols('x y z w')
cases=[
 ((x,y),[x*x-y,x*y-1]),
 ((x,y,z),[x-z**3,y-z**2,z**5-1]),
 ((x,y),[x*x,y**3]),
 ((x,y),[x*x+y*y-1,x-y]),
 ((x,y),[x*x+y*y-1,x*y-sp.Rational(1,4)]),
 ((x,y),[x*x+y,x*y+1,y*y+x]),
 ((x,y,z),[x+y+z,x*y+y*z+z*x,x*y*z-1]),
 ((x,y,z),[x*x+y*y+z*z-1,x-y,y-z]),
 ((x,y,z),[x*y-z,y*z-x,z*x-y]),
 ((x,y,z),[x*x,y**3,z*z]),
 ((x,y),[(x-y)**2,y*y-1]),
 ((x,y,z,w),[x+y+z+w,x-y,y-z,z-w]),
 ((x,y),[sp.Rational(2,3)*x*x-sp.Rational(3,5)*y,sp.Rational(7,11)*x*y-sp.Rational(13,17)]),
 ((x,y,z),[x-z**4,y-z**3,z**7-1]),
 ((x,),[x**5-x+1]),
]
rng=Random(20261116)
for _ in range(12):
 a,b,c,d,e=[rng.randrange(-2,3) for _ in range(5)]
 exprs=[x*x+a*x*y+b*y+c,y*y+d*x+e]
 basis=sp.groebner(exprs,x,y,order='lex',domain=sp.QQ)
 if basis.is_zero_dimensional or list(basis)==[1]:cases.append(((x,y),exprs))


def staircase(basis,variables,order):
 leads=[tuple(p.LM(order=order).exponents) for p in basis.polys]
 n=len(variables)
 if any(all(e==0 for e in m) for m in leads):return []
 bounds=[]
 for i in range(n):
  powers=[m[i] for m in leads if m[i] and all(m[j]==0 for j in range(n) if j!=i)]
  assert powers,(leads,i)
  bounds.append(min(powers))
 result=[m for m in product(*(range(b) for b in bounds)) if not any(all(a<=b for a,b in zip(lm,m)) for lm in leads)]
 return sorted(result,key=monomial_key(order))


def terms(expr,variables):
 return [(int(c.p),int(c.q),list(m)) for m,c in sp.Poly(expr,*variables,domain=sp.QQ).terms() if c]


def render_terms(values):
 return '['+', '.join(f'({a}, {b}, ['+', '.join(map(str,m))+'])' for a,b,m in values)+']'

records=[];lines=['// Generated by tools/generate_fglm_fixtures.py; independent SymPy QQ/order oracle.','']
for i,(variables,inputs) in enumerate(cases):
 source=sp.groebner(inputs,*variables,order='lex',domain=sp.QQ)
 source_staircase=staircase(source,variables,'lex')
 for target,moon in [('lex','Lex'),('grlex','GradedLex'),('grevlex','GrevLex')]:
  direct=sp.groebner(inputs,*variables,order=target,domain=sp.QQ)
  if source.is_zero_dimensional:
   converted=source.fglm(target)
   assert [p.as_expr() for p in converted.polys]==[p.as_expr() for p in direct.polys]
  expected_staircase=staircase(direct,variables,target)
  assert len(expected_staircase)==len(source_staircase)
  source_data=[terms(p,variables) for p in inputs]
  expected=[terms(p.as_expr(),variables) for p in direct.polys]
  records.append(dict(variables=[str(v) for v in variables],inputs=source_data,target=target,basis=expected,dimension=len(source_staircase),standard_monomials=expected_staircase))
  lines += ['///|',f'test "SymPy FGLM quotient and {target} fixture {i}" {{',
   f'  assert_sympy_fixture({len(variables)}, {moon},',
   '    ['+', '.join(render_terms(p) for p in source_data)+'],',
   '    ['+', '.join(render_terms(p) for p in expected)+'],',
   f'    {len(source_staircase)}, ['+', '.join('['+', '.join(map(str,m))+']' for m in expected_staircase)+'])','}','']
path=ROOT/'src/fglm/sympy_wbtest.mbt';path.write_text('\n'.join(lines))
subprocess.run([str(ROOT/'tools/moon'),'fmt',str(path)],cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
out=ROOT/'.tools/fglm-20261116/sympy-fixtures.json';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(json.dumps(dict(sympy=sp.__version__,source_order='lex',domain='QQ',cases=records),indent=2)+'\n')
print(f'generated {len(records)} FGLM order/dimension fixtures from {len(cases)} ideals using SymPy {sp.__version__}')
