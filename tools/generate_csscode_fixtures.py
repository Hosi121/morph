#!/usr/bin/env python3
"""Independent exhaustive bit-mask oracle for binary CSS stabilizer algebra.

Uses explicit sets of all row combinations and all vectors; no row-reduction,
MoonBit, homology, or numerical-library implementation is imported. Enumerates
every pair of subspaces on at most three coordinates, and finite simplicial
examples. Integer masks are exclusively an oracle representation.
"""
from __future__ import annotations

import argparse
from itertools import combinations
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/csscode/fixtures_wbtest.mbt"
RP2 = [(0, 1, 2), (0, 2, 3), (0, 1, 5), (0, 4, 5), (0, 3, 4),
       (1, 2, 4), (1, 3, 4), (1, 3, 5), (2, 3, 5), (2, 4, 5)]
TORUS = [(0, 1, 2), (1, 2, 4), (1, 3, 4), (1, 3, 6), (0, 1, 5),
         (1, 5, 6), (2, 3, 5), (2, 4, 5), (2, 3, 6), (0, 2, 6),
         (0, 3, 4), (0, 3, 5), (4, 5, 6), (0, 4, 6)]


def span(rows):
    result = {0}
    for row in rows:
        result |= {x ^ row for x in result}
    return frozenset(result)


def syndrome(rows, vector):
    return sum((((row & vector).bit_count() & 1) << i)
               for i, row in enumerate(rows))


def oracle(n, hx, hz):
    assert all(0 <= row < 1 << n for row in [*hx, *hz])
    if any((x & z).bit_count() & 1 for x in hx for z in hz):
        return None
    sx, sz = span(hx), span(hz)
    rx, rz = len(sx).bit_length() - 1, len(sz).bit_length() - 1
    lx = {v for v in range(1 << n) if syndrome(hz, v) == 0 and v not in sx}
    lz = {v for v in range(1 << n) if syndrome(hx, v) == 0 and v not in sz}
    dx = min((v.bit_count() for v in lx), default=-1)
    dz = min((v.bit_count() for v in lz), default=-1)
    assert bool(lx) == bool(lz) == (n - rx - rz > 0)
    return [rx, rz, n - rx - rz, dx, dz], sx, sz, lx, lz


def subspaces(n):
    spaces = {}
    for length in range(n + 1):
        for basis in combinations(range(1, 1 << n), length):
            spaces.setdefault(span(basis), basis)
    return list(spaces.values())


def topology(facets, degree):
    faces = {f for facet in facets for k in range(1, len(facet) + 1)
             for f in combinations(facet, k)}
    qubits = sorted(f for f in faces if len(f) == degree + 1)
    lower = sorted(f for f in faces if len(f) == degree) if degree else []
    upper = sorted(f for f in faces if len(f) == degree + 2)
    hx = [sum((1 << i) for i, q in enumerate(qubits) if set(f) < set(q))
          for f in lower]
    hz = [sum((1 << i) for i, q in enumerate(qubits) if set(q) < set(f))
          for f in upper]
    return len(qubits), hx, hz


def arr(value):
    if isinstance(value, (tuple, list)):
        return "[" + ", ".join(arr(x) for x in value) + "]"
    return str(value)


def packed(values):
    return sum(1 << value for value in values)


def render():
    lines = ["// Generated by tools/generate_csscode_fixtures.py; do not edit.",
             "///|", 'test "all commuting subspaces through three qubits match independent exhaustive bitmask oracle" {']
    count = rejected = vectors = 0
    for n in range(4):
        for hx in subspaces(n):
            for hz in subspaces(n):
                result = oracle(n, hx, hz)
                if result is None:
                    rejected += 1
                    lines.append(f"  assert_eq(validate(masks({n}, {arr(hx)}), masks({n}, {arr(hz)})), None)")
                    continue
                params, sx, sz, lx, lz = result
                sets = [packed(s) for s in (sx, sz, lx, lz)]
                lines.append(f"  verify_fixture({n}, {arr(hx)}, {arr(hz)}, {arr(params)}, {arr(sets)})")
                count += 1
                vectors += 1 << n
    lines.extend(["}", ""])
    summary = {"valid_pairs": count, "rejected_pairs": rejected,
               "vectors": vectors}
    for name, facets in [("projective_plane", RP2), ("torus", TORUS)]:
        n, hx, hz = topology(facets, 1)
        params = oracle(n, hx, hz)[0]
        summary[name] = dict(n=n, rank_x=params[0], rank_z=params[1],
                             k=params[2], dx=params[3], dz=params[4])
        lines.extend(["///|", f'test "{name} edge code matches independent full vector enumeration" {{',
                      f"  let code = from_complex(complex({arr(facets)}), @oracle.nat(1)).unwrap()",
                      f"  assert_eq(checks(code, X), masks({n}, {arr(hx)}))",
                      f"  assert_eq(checks(code, Z), masks({n}, {arr(hz)}))",
                      f"  verify_topology(code, {arr([n, *params])})", "}", ""])
    return "\n".join(lines), summary


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw, summary = render()
    formatter = ROOT / ".tools/moon/bin/moonfmt"
    executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None:
        raise SystemExit("moonfmt is required to canonicalize generated fixtures")
    content = subprocess.run([executable, "-"], input=raw, text=True,
                             check=True, capture_output=True).stdout
    if args.check:
        assert OUTPUT.read_text() == content, f"stale fixture: {OUTPUT}"
    else:
        OUTPUT.write_text(content)
    print(summary)


if __name__ == "__main__":
    main()
