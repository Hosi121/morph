#!/usr/bin/env python3
"""Generate pure-ADT grouped tail-comparison candidates for a fixed search."""
from pathlib import Path
import argparse
import subprocess
import shutil

ROOT=Path(__file__).resolve().parent.parent
DEST=ROOT/'src/binary/comparison_candidates_wbtest.mbt'


def format_source(source):
    formatter=ROOT/'.tools/moon/bin/moonfmt'
    if not formatter.is_file():
        formatter=shutil.which('moonfmt')
        if formatter is None:
            raise SystemExit('MoonBit formatter is missing: run tools/bootstrap or put moonfmt on PATH.')
    return subprocess.run([str(formatter),'-'],input=source,text=True,capture_output=True,check=True).stdout


def spine(names, tail):
    for name in reversed(names):
        tail=f'Cons({name}, {tail})'
    return tail


def candidate(width):
    name=f'comparison_group_{width}'
    namesx=[f'x{i}' for i in range(width)]
    namesy=[f'y{i}' for i in range(width)]
    next='previous'
    for x,y in zip(namesx,namesy):
        next=f'match ({x}, {y}) {{ (false, true) => @core.Less; (true, false) => @core.Greater; _ => {next} }}'
    return f'''///|
fn {name}(xs : @core.Chain[Bool], ys : @core.Chain[Bool]) -> @core.Ordering {{
  fn walk(xs : @core.Chain[Bool], ys : @core.Chain[Bool], previous : @core.Ordering) -> @core.Ordering {{
    match (xs, ys) {{
      ({spine(namesx,'xt')}, {spine(namesy,'yt')}) => {{
        let next : @core.Ordering = {next}
        walk(xt, yt, next)
      }}
      (Nil, Nil) => previous
      (Nil, Cons(_, _)) => Less
      (Cons(_, _), Nil) => Greater
      (Cons(x, xt), Cons(y, yt)) => {{
        let next : @core.Ordering = match (x, y) {{
          (false, true) => Less
          (true, false) => Greater
          _ => previous
        }}
        walk(xt, yt, next)
      }}
    }}
  }}
  walk(xs, ys, Equal)
}}
'''


def protected_candidate(depth):
    name=f'comparison_protected_{depth}'
    lines=['///|', f'fn {name}(xs : @core.Chain[Bool], ys : @core.Chain[Bool]) -> @core.Ordering {{']
    for stage in reversed(range(depth)):
        following=f'stage_{stage + 1}' if stage + 1 < depth else 'comparison_group_4'
        lines += [f'  fn stage_{stage}(xs : @core.Chain[Bool], ys : @core.Chain[Bool]) -> @core.Ordering {{',
            '    match (xs, ys) {', '      (Nil, Nil) => Equal', '      (Nil, Cons(_, _)) => Less',
            '      (Cons(_, _), Nil) => Greater',
            '      (Cons(x, xt), Cons(y, yt)) =>', f'        match {following}(xt, yt) {{',
            '          Equal => match (x, y) { (false, true) => Less; (true, false) => Greater; _ => Equal }',
            '          order => order', '        }', '    }', '  }']
    lines += ['  stage_0(xs, ys)', '}']
    return '\n'.join(lines) + '\n'


def plain_candidate():
    return """///|
fn comparison_plain(xs : @core.Chain[Bool], ys : @core.Chain[Bool]) -> @core.Ordering {
  fn walk(xs : @core.Chain[Bool], ys : @core.Chain[Bool], previous : @core.Ordering) -> @core.Ordering {
    match (xs, ys) {
      (Nil, Nil) => previous
      (Nil, Cons(_, _)) => Less
      (Cons(_, _), Nil) => Greater
      (Cons(x, xt), Cons(y, yt)) => {
        let next : @core.Ordering = match (x, y) {
          (false, true) => Less
          (true, false) => Greater
          _ => previous
        }
        walk(xt, yt, next)
      }
    }
  }
  walk(xs, ys, Equal)
}
"""


def production():
    grouped=candidate(4).replace('///|\nfn comparison_group_4(', '///|\n#inline(never)\nfn compare_bits_grouped(', 1)
    outer=protected_candidate(8).replace('comparison_protected_8', 'compare_bits_tail', 1).replace('comparison_group_4', 'compare_bits_grouped')
    source='// Generated by tools/generate_comparison_candidates.py.\n// Eight bounded prefix frames protect short words; the suffix uses a grouped tail loop.\n\n'+grouped+'\n'+outer
    return format_source(source)


def generate():
    text='// Generated by tools/generate_comparison_candidates.py.\n\n'
    text+=plain_candidate()+'\n'
    text+='\n'.join(candidate(width) for width in [2,4,8])
    text+='\n'.join(protected_candidate(depth) for depth in [2,4,8])
    text+='''
///|
test "grouped comparison candidates agree on every small raw-list pair" {
  let words=[@core.Nil]
  for width in 1..<=7 {
    for value in 0..<(1 << width) { words.push(comparison_small_word(width, value)) }
  }
  for xs in words { for ys in words {
    let expected=compare_bits_reference(xs, ys)
    assert_eq(comparison_plain(xs, ys), expected)
    assert_eq(comparison_group_2(xs, ys), expected)
    assert_eq(comparison_group_4(xs, ys), expected)
    assert_eq(comparison_group_8(xs, ys), expected)
    assert_eq(comparison_protected_2(xs, ys), expected)
    assert_eq(comparison_protected_4(xs, ys), expected)
    assert_eq(comparison_protected_8(xs, ys), expected)
  } }
}

///|
test "grouped tail comparisons against fixed old recursion" (b : @bench.T) {
  let short=[]
  for x in 0..<=15 { for y in 0..<=15 { short.push((bits(@oracle.binary(x)),bits(@oracle.binary(y)))) } }
  let converters=[compare_bits_reference,comparison_plain,comparison_group_4,comparison_protected_2,comparison_protected_4,comparison_protected_8]
  let labels=["old","plain","group4","protect2","protect4","protect8"]
  for index in 0..<converters.length() {
    let convert=converters[index]
    let label=labels[index]
    b.bench(name="\\{label} short 256 pairs", fn() { for pair in short { b.keep(convert(pair.0,pair.1)) } })
  }
  for width in [64,2048] {
    let equal=Array::make(width,true)
    let dense=[for bit in 0..<width => bit % 3 != 0]
    dense[width-1]=true
    let short=Array::make(width-1,true)
    let xs=comparison_array_word(equal)
    for data_index in 0..<3 {
      let data=[equal,dense,short][data_index]
      let data_label=["equal","dense","width"][data_index]
      let ys=comparison_array_word(data)
      for index in 0..<converters.length() {
        let convert=converters[index]
        let label=labels[index]
        b.bench(name="\\{label} \\{data_label} \\{width}", fn() { b.keep(convert(xs,ys)) })
      }
    }
  }
}
'''
    return format_source(text)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs={DEST:generate(),ROOT/'src/binary/comparison.mbt':production()}
    for path,source in outputs.items():
        if args.check:
            if not path.exists() or path.read_text()!=source:raise SystemExit(f'Comparison generated source is stale: {path}')
        else:path.write_text(source)


if __name__=='__main__':main()
