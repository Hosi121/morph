#!/usr/bin/env python3
"""Independent arbitrary-width binary-polynomial BCH fixtures.

The kernel constructs minimal polynomials from Frobenius conjugates. This oracle
instead searches all monic binary polynomials in increasing degree for the first
one vanishing at each designated root, and takes their carryless gcd/lcm. No
symbolic-kernel code is called and no generator table is embedded.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/bch/oracle_wbtest.mbt"
ARTIFACT = ROOT / ".tools/bch-20261116/oracle-summary.json"


def multiply(a: int, b: int) -> int:
    result = 0
    while b:
        if b & 1:
            result ^= a
        a <<= 1
        b >>= 1
    return result


def divide(value: int, divisor: int) -> tuple[int, int]:
    assert divisor
    quotient = 0
    while value and value.bit_length() >= divisor.bit_length():
        shift = value.bit_length() - divisor.bit_length()
        quotient ^= 1 << shift
        value ^= divisor << shift
    return quotient, value


def gcd(a: int, b: int) -> int:
    while b:
        a, b = b, divide(a, b)[1]
    return a


def gf_multiply(modulus: int, a: int, b: int) -> int:
    return divide(multiply(a, b), modulus)[1]


def power(modulus: int, a: int, exponent: int) -> int:
    result = 1
    while exponent:
        if exponent & 1:
            result = gf_multiply(modulus, result, a)
        a = gf_multiply(modulus, a, a)
        exponent >>= 1
    return result


def evaluate(modulus: int, polynomial: int, point: int) -> int:
    result = 0
    for i in reversed(range(polynomial.bit_length())):
        result = gf_multiply(modulus, result, point) ^ ((polynomial >> i) & 1)
    return result


def minimal(modulus: int, point: int) -> int:
    for degree in range(1, modulus.bit_length()):
        for tail in range(1 << degree):
            polynomial = (1 << degree) | tail
            if evaluate(modulus, polynomial, point) == 0:
                return polynomial
    raise AssertionError("no binary minimal polynomial")


def generator(modulus: int, root: int, t: int) -> tuple[int, list[int]]:
    result = 1
    factors = []
    for j in range(1, 2 * t + 1):
        factor = minimal(modulus, power(modulus, root, j))
        result = multiply(divide(result, gcd(result, factor))[0], factor)
        if factor not in factors:
            factors.append(factor)
    return result, factors


def irreducible(modulus: int) -> bool:
    degree = modulus.bit_length() - 1
    return all(divide(modulus, (1 << d) | tail)[1]
               for d in range(1, degree // 2 + 1)
               for tail in range(1 << d))


def exact_order(modulus: int, root: int, n: int) -> bool:
    current = 1
    for i in range(1, n + 1):
        current = gf_multiply(modulus, current, root)
        if current == 1:
            return i == n
    return False


def poly_product(modulus: int, a: list[int], b: list[int]) -> list[int]:
    product = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            product[i+j] ^= gf_multiply(modulus, x, y)
    return product


def encode(g: int, message: int) -> int:
    shifted = message << (g.bit_length() - 1)
    return shifted ^ divide(shifted, g)[1]


def bool_literal(value: int, width: int) -> str:
    return "[" + ", ".join("true" if value >> i & 1 else "false" for i in range(width)) + "]"


def int_literal(values: list[int]) -> str:
    return "[" + ", ".join(map(str, values)) + "]"


def fixtures() -> tuple[str, list[dict]]:
    specifications = [(0b111, 2, 1), (0b1011, 2, 1), (0b1011, 2, 2),
                      (0b10011, 2, 2), (0b10011, 2, 3), (0b10011, 2, 7),
                      (0b11111, 3, 2), (0b100101, 2, 2), (0b100101, 2, 4),
                      (0b1000011, 2, 3), (0b1000011, 2, 5), (0b1000011, 2, 11),
                      (0b10000011, 2, 3), (0b100011101, 2, 4)]
    lines = ["// Generated by tools/generate_bch.py; arbitrary-width carryless integer oracle."]
    summaries = []
    for index, (modulus, root, t) in enumerate(specifications):
        degree = modulus.bit_length() - 1
        n = (1 << degree) - 1
        assert irreducible(modulus) and exact_order(modulus, root, n)
        g, factors = generator(modulus, root, t)
        parity = g.bit_length() - 1
        k = n - parity
        assert 0 <= 2*t < n and k > 0
        assert divide((1 << n) | 1, g)[1] == 0
        assert all(evaluate(modulus, g, power(modulus, root, j)) == 0
                   for j in range(1, 2*t + 1))
        # Leave the highest information coefficient zero to exercise fixed width.
        message = sum(1 << i for i in range(max(0, k-1)) if (i*i + 3*i + index) % 5 < 2)
        codeword = encode(g, message)
        candidate_positions = [0, n-1, n//2] + list(range(1, n))
        positions = []
        for position in candidate_positions:
            if position not in positions and len(positions) < t:
                positions.append(position)
        positions.sort()
        mask = sum(1 << position for position in positions)
        received = codeword ^ mask
        syndromes = [evaluate(modulus, received, power(modulus, root, j))
                     for j in range(1, 2*t + 1)]
        locator = [1]
        for position in positions:
            locator = poly_product(modulus, locator, [1, power(modulus, root, position)])
        lines += ["", "///|", f'test "independent BCH fixture {index} length {n} radius {t}" {{',
                  "  assert_fixture(", f"    {modulus}, {root}, {n}, {t},",
                  f"    {bool_literal(g, parity+1)},", f"    {bool_literal(message, k)},",
                  f"    {bool_literal(codeword, n)},", f"    {int_literal(positions)},",
                  f"    {int_literal(syndromes)},", f"    {int_literal(locator)},", "  )", "}"]
        summaries.append(dict(index=index, modulus=modulus, root=root, n=n, k=k, t=t,
                              generator_hex=hex(g), minimal_polynomials_hex=list(map(hex, factors)),
                              message_hex=hex(message), codeword_hex=hex(codeword),
                              positions=positions, syndromes=syndromes, locator=locator))
    return "\n".join(lines) + "\n", summaries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated fixtures without rewriting")
    args = parser.parse_args()
    content, summaries = fixtures()
    if args.check:
        # Formatting may split arrays and add optional trailing commas. Preserve
        # string tokens while comparing every other non-whitespace token.
        def tokens(source: str) -> list[str]:
            source = re.sub(r",\s*([\]\)])", r"\1", source)
            return re.findall(r'"(?:\\.|[^"\\])*"|\S', source)
        assert tokens(OUTPUT.read_text()) == tokens(content), "BCH fixture regeneration drift"
    else:
        OUTPUT.write_text(content)
    ARTIFACT.parent.mkdir(parents=True, exist_ok=True)
    ARTIFACT.write_text(json.dumps(summaries, indent=2) + "\n")
    print(f"{'Checked' if args.check else 'Wrote'} {len(summaries)} independent BCH fixtures; arbitrary-width generator, encoding, syndromes and locator.")


if __name__ == "__main__":
    main()
