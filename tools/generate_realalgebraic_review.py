#!/usr/bin/env python3
"""Independent Fraction/root-product/Leibniz determinant review oracle.

No SymPy, production interpolation, polynomial package, or Gaussian elimination.
"""
from fractions import Fraction as Q
from itertools import permutations
from math import comb
from pathlib import Path
import json
import random
import subprocess

ROOT=Path(__file__).resolve().parents[1]

def mul(a,b):
    out=[Q(0)]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):out[i+j]+=x*y
    return out

def roots_poly(roots):
    out=[Q(1)]
    for r in roots:out=mul(out,[-r,Q(1)])
    return out

def evaluate(cs,x):return sum(c*x**i for i,c in enumerate(cs))

def determinant(a):
    total=Q(0); size=len(a)
    for perm in permutations(range(size)):
        value=Q(1)
        for i,j in enumerate(perm):
            value*=a[i][j]
            if not value:break
        if value:
            inversions=sum(perm[i]>perm[j] for i in range(size) for j in range(i+1,size))
            total+=(-1 if inversions%2 else 1)*value
    return total

def sample(left,right,point,operation):
    m,n=len(left)-1,len(right)-1
    if operation=='Sum':
        transformed=[sum(right[j]*comb(j,k)*point**(j-k)*(-1)**k for j in range(k,n+1)) for k in range(n+1)]
    else:
        transformed=[Q(0)]*(n+1)
        for j,c in enumerate(right):transformed[n-j]=c*point**j
    size=m+n; rows=[]
    for coeffs,count in ((left,n),(transformed,m)):
        for shift in range(count):
            row=[Q(0)]*shift+list(reversed(coeffs))
            rows.append((row+[Q(0)]*size)[:size])
    degree=max((i for i,c in enumerate(transformed) if c),default=-1)
    return determinant(rows),degree

def pairs(cs):return [(c.numerator,c.denominator) for c in cs]
def render(cs):return '['+', '.join(f'({a}, {b})' for a,b in pairs(cs))+']'

root_sets=[[Q(0)],[Q(1)],[Q(-1)],[Q(1,2)],
           [Q(0),Q(0)],[Q(0),Q(1)],[Q(-1),Q(1)],
           [Q(0),Q(0),Q(2)],[Q(-2),Q(1,2)],
           [Q(-1),Q(0),Q(2)],[Q(0),Q(1),Q(2)],
           [Q(-1),Q(-1),Q(1)]]
indices=[(i,j) for i in range(len(root_sets)) for j in range(len(root_sets))]
rng=random.Random(20261116);rng.shuffle(indices)
indices=[(4,7),(9,10),(0,0),(5,7),(11,11),(8,9)]+indices[:18]
cases=[]
for i,j in indices:
    roots_a,roots_b=root_sets[i],root_sets[j]
    a,b=roots_poly(roots_a),roots_poly(roots_b)
    for op in ('Sum','Product'):
        expected=roots_poly([x+y if op=='Sum' else x*y for x in roots_a for y in roots_b])
        scale_a=Q(-2,3) if i%2 else Q(3,2)
        scale_b=Q(5,7) if j%2 else Q(-7,5)
        cases.append(([scale_a*c for c in a],[scale_b*c for c in b],op,expected))
for a in (-2,0,2,3):
    for b in (-2,0,2,3):
        p,q=[Q(-a),Q(0),Q(1)],[Q(-b),Q(0),Q(1)]
        cases.append((p,q,'Sum',[Q((a-b)**2),Q(0),Q(-2*(a+b)),Q(0),Q(1)]))
        cases.append((p,q,'Product',[Q(a*a*b*b),Q(0),Q(-2*a*b),Q(0),Q(1)]))
lines=['// Generated by tools/generate_realalgebraic_review.py; stdlib-only independent oracle.','']
records=[]
for i,(a,b,op,expected) in enumerate(cases):
    left=[c/a[-1] for c in a];right=[c/b[-1] for c in b]
    bound=(len(a)-1)*(len(b)-1)
    evaluations=[sample(left,right,Q(x),op) for x in range(bound+1)]
    samples=[value for value,_ in evaluations]
    assert all(evaluate(expected,Q(x))==v for x,v in enumerate(samples))
    records.append(dict(left=pairs(a),right=pairs(b),operation=op,expected=pairs(expected),samples=pairs(samples),degree_bound=bound,specialized_degrees=[degree for _,degree in evaluations]))
    lines += ['///|',f'test "independent Fraction realalgebraic resultant review fixture {i}" {{',
              f'  assert_review_resultant({render(a)}, {render(b)}, {op},',
              f'    {render(expected)}, {render(samples)})','}','']
path=ROOT/'src/realalgebraic/independent_review_fixtures_wbtest.mbt'
path.write_text('\n'.join(lines))
subprocess.run([str(ROOT/'tools/moon'),'fmt',str(path)],cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
out=ROOT/'.tools/realalgebraic-independent-review-20261116/resultant-fixtures.json'
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(json.dumps(dict(oracle='Fraction root products and Leibniz Sylvester determinant',cases=records),indent=2)+'\n')
print(f'generated {len(cases)} independent resultant review fixtures')
