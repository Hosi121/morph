#!/usr/bin/env python3
"""Exact univariate RCF SMT oracle from known rational factor roots.

No production executable, CAD, Sturm sequence, or SymPy is used. The two test
polynomials are supplied as products of rational linear factors, so the union
of their listed roots gives every real sign cell, including isolated roots.
"""

from __future__ import annotations

import argparse
from fractions import Fraction as F
import itertools
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/realnlsmt/generated_fixtures_wbtest.mbt"
MANIFEST = ROOT / "docs/measurements/realnlsmt-fixtures-20261116.json"
RELATIONS = ["LessZero", "AtMostZero", "EqualZero", "NotZero", "AtLeastZero", "GreaterZero"]
POLYS = {"p": (F(-1), F(0), F(1)), "q": (F(0), F(-2), F(1))}
ROOTS = {"p": (F(-1), F(1)), "q": (F(0), F(2))}


def sign_at(name, point):
    value = sum(coefficient * point ** exponent
                for exponent, coefficient in enumerate(POLYS[name]))
    return (value > 0) - (value < 0)


def holds(formula, point):
    op, *args = formula
    if op == "Atom":
        name, relation = args
        sign = sign_at(name, point)
        return {
            "LessZero": sign < 0, "AtMostZero": sign <= 0,
            "EqualZero": sign == 0, "NotZero": sign != 0,
            "AtLeastZero": sign >= 0, "GreaterZero": sign > 0,
        }[relation]
    if op == "Negation":
        return not holds(args[0], point)
    if op == "Conjunction":
        return holds(args[0], point) and holds(args[1], point)
    if op == "Disjunction":
        return holds(args[0], point) or holds(args[1], point)
    raise AssertionError(op)


def polynomials(formula):
    if formula[0] == "Atom":
        return {formula[1]}
    return set().union(*(polynomials(arg) for arg in formula[1:]))


def samples(formula):
    roots = sorted(set().union(*(ROOTS[name] for name in polynomials(formula))))
    out = [roots[0] - 1]
    for index, root in enumerate(roots):
        out.append(root)
        out.append((root + roots[index + 1]) / 2 if index + 1 < len(roots) else root + 1)
    return out


def render(formula):
    op, *args = formula
    if op == "Atom":
        name, relation = args
        return f"Atom({name}, {relation})"
    return op + "(" + ", ".join(map(render, args)) + ")"


def cases():
    for left, right in itertools.product(RELATIONS, repeat=2):
        yield ("same_polynomial_and", ("Conjunction", ("Atom", "p", left), ("Atom", "p", right)))
        yield ("same_polynomial_or", ("Disjunction", ("Atom", "p", left), ("Atom", "p", right)))
        yield ("different_polynomial_and", ("Conjunction", ("Atom", "p", left), ("Atom", "q", right)))
    for relation in RELATIONS:
        yield ("negated_boolean", ("Negation", ("Disjunction", ("Atom", "p", relation), ("Negation", ("Atom", "q", relation)))))


def generate():
    lines = ["// Generated by tools/generate_realnlsmt_fixtures.py; do not edit.",
             "// Complete real sign-cell oracle from known rational linear factors.", ""]
    data = []
    for index, (family, formula) in enumerate(cases()):
        points = samples(formula)
        truth = [holds(formula, point) for point in points]
        expected = any(truth)
        lines += ["///|", f'test "independent nonlinear SMT fixture {index:03d} {family}" {{',
                  "  let p = test_polynomial(1, [(1, 1, [2]), (-1, 1, [0])])"]
        if "q" in polynomials(formula):
            lines.append("  let q = test_polynomial(1, [(1, 1, [2]), (-2, 1, [1])])")
        lines += [f"  check_generated_fixture({render(formula)}, {str(expected).lower()})", "}", ""]
        data.append({"index": index, "family": family, "formula": render(formula),
                     "samples": list(map(str, points)), "truth": truth, "satisfiable": expected})
    manifest = {"oracle": "Python Fraction complete real sign cells from known rational factors; no CAD/Sturm/SymPy",
                "polynomials": {name: list(map(str, coefficients)) for name, coefficients in POLYS.items()},
                "all_real_roots": {name: list(map(str, roots)) for name, roots in ROOTS.items()},
                "fixtures": len(data), "satisfiable": sum(case["satisfiable"] for case in data),
                "unsatisfiable": sum(not case["satisfiable"] for case in data), "cases": data}
    return {OUTPUT: "\n".join(lines), MANIFEST: json.dumps(manifest, indent=2) + "\n"}


def tokens(source):
    source = re.sub(r",\s*([\]\)])", r"\1", source)
    return re.findall(r'"(?:\\.|[^"\\])*"|\S', source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if not path.exists() or (tokens(path.read_text()) != tokens(text) if path.suffix == ".mbt" else path.read_text() != text):
                raise SystemExit(f"stale fixture: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print("realnlsmt Fraction sign-cell fixtures are current")


if __name__ == "__main__":
    main()
