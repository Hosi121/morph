#!/usr/bin/env python3
"""Independent Fraction long division/Gaussian inverse/Leibniz determinant oracle.
SymPy is used only to cross-check irreducibility and the independently obtained data.
"""
from pathlib import Path
from fractions import Fraction as F
from itertools import permutations
import random,json,subprocess
import sympy as sp
ROOT=Path(__file__).resolve().parents[1]
x=sp.Symbol('x')
def trim(a):
 a=list(map(F,a))
 while a and not a[-1]:a.pop()
 return a
def add(a,b):return trim([(a[i] if i<len(a) else F(0))+(b[i] if i<len(b) else F(0)) for i in range(max(len(a),len(b)))])
def neg(a):return [-c for c in a]
def mul(a,b):
 if not a or not b:return []
 out=[F(0)]*(len(a)+len(b)-1)
 for i,c in enumerate(a):
  for j,d in enumerate(b):out[i+j]+=c*d
 return trim(out)
def rem(a,m):
 a=trim(a)
 while len(a)>=len(m):
  k=len(a)-len(m);c=a[-1]/m[-1]
  for i,d in enumerate(m):a[i+k]-=c*d
  a=trim(a)
 return a
def mat(a,m):
 d=len(m)-1
 cs=[rem([F(0)]*j+a,m) for j in range(d)]
 return [[cs[j][i] if i<len(cs[j]) else F(0) for j in range(d)] for i in range(d)]
def det(a):
 n=len(a);out=F(0)
 for p in permutations(range(n)):
  z=F(-1 if sum(p[i]>p[j] for i in range(n) for j in range(i+1,n))%2 else 1)
  for i in range(n):z*=a[i][p[i]]
  out+=z
 return out
def inv(a,m):
 if not a:return None
 # Solve multiplication matrix times vector = (1,0,...). No Euclid.
 rows=[r+[F(i==0)] for i,r in enumerate(mat(a,m))];n=len(rows)
 for j in range(n):
  k=next(i for i in range(j,n) if rows[i][j]);rows[j],rows[k]=rows[k],rows[j]
  c=rows[j][j];rows[j]=[z/c for z in rows[j]]
  for i in range(n):
   if i!=j:
    c=rows[i][j];rows[i]=[u-c*v for u,v in zip(rows[i],rows[j])]
 return trim([r[-1] for r in rows])
def expr(a):return sum(sp.Rational(c.numerator,c.denominator)*x**i for i,c in enumerate(a))
def pairs(a):return [(c.numerator,c.denominator) for c in a]
def arr(a):return '['+', '.join(f'({c.numerator}, {c.denominator})' for c in a)+']'
def pair(a):return f'({a.numerator}, {a.denominator})'
rng=random.Random(20261116)
families=[([0,1],(-1,0)),([-2,1],(1,2)),([-2,0,1],(1,2)),([-1,-1,1],(1,2)),([-2,0,0,1],(1,2)),([-1,-1,0,1],(1,2)),([1,0,-10,0,1],(3,4)),([F(-1,2),0,1],(0,1))]
lines=['// Generated by tools/generate_numberfield_fixtures.py; independent Fraction oracle.','']
records=[]
for fi,(raw,interval) in enumerate(families):
 m=list(map(F,raw));mp=sp.Poly(expr(m),x,domain=sp.QQ)
 assert mp.is_irreducible
 for k in range(8):
  def sample():return trim([F(rng.randrange(-3,4),rng.randrange(1,4)) for _ in range(rng.randrange(1,len(m)+4))])
  a=[] if k==0 else sample();b=sample();c=sample();ar=rem(a,m);br=rem(b,m)
  inverse=inv(ar,m);matrix=mat(ar,m);tr=sum(matrix[i][i] for i in range(len(matrix)));norm=det(matrix)
  # Orthogonal SymPy checks, while expected coefficients originate from Fraction routines.
  assert sp.Poly(expr(rem(mul(a,b),m)),x,domain=sp.QQ)==sp.rem(sp.Poly(expr(a)*expr(b),x,domain=sp.QQ),mp)
  assert sp.Rational(norm.numerator,norm.denominator)==sp.resultant(mp.as_expr(),expr(ar),x)
  if inverse is not None:
   assert sp.rem(sp.Poly(expr(ar)*expr(inverse)-1,x),mp).is_zero
   assert sp.Poly(expr(inverse),x,domain=sp.QQ)==sp.Poly(sp.invert(expr(ar),mp.as_expr()),x,domain=sp.QQ)
  record=dict(family=fi,modulus=pairs(m),interval=interval,a=pairs(a),b=pairs(b),c=pairs(c),residue=pairs(ar),sum=pairs(rem(add(a,b),m)),difference=pairs(rem(add(a,neg(b)),m)),product=pairs(rem(mul(a,b),m)),inverse=None if inverse is None else pairs(inverse),trace=pairs([tr])[0],norm=pairs([norm])[0],matrix=[pairs(r) for r in matrix])
  records.append(record);n=len(records)-1
  inv_text='None' if inverse is None else f'Some({arr(inverse)})'
  matrix_text='['+', '.join(arr(r) for r in matrix)+']'
  lines += ['///|',f'test "Fraction residue and Gaussian inverse oracle fixture {n}" {{',
   f'  assert_field_fixture({arr(m)}, ({interval[0]}, 1), ({interval[1]}, 1),',
   f'    {arr(a)}, {arr(b)}, {arr(c)}, {arr(ar)}, {arr(rem(add(a,b),m))}, {arr(rem(add(a,neg(b)),m))}, {arr(rem(mul(a,b),m))},',
   f'    {inv_text}, {pair(tr)}, {pair(norm)}, {matrix_text})','}','']
path=ROOT/'src/numberfield/fraction_wbtest.mbt';path.write_text('\n'.join(lines))
subprocess.run([str(ROOT/'tools/moon'),'fmt',str(path)],cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
out=ROOT/'.tools/numberfield-20261116/fraction-fixtures.json';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(json.dumps(dict(oracle='stdlib Fraction: long division, Gaussian inverse, Leibniz determinant; SymPy cross-check',sympy=sp.__version__,cases=records),indent=2)+'\n')
print(f'generated {len(records)} independently checked quotient-field fixtures across {len(families)} moduli, degrees 1..4')
