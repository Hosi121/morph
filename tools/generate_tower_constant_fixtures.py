#!/usr/bin/env python3
"""Independent Fraction fixtures for exact tower rational embeddings; --check guards drift."""
from argparse import ArgumentParser
from fractions import Fraction
from pathlib import Path
import sys


def render():
    samples = [(0, 1), (0, 9), (1, 1), (-1, 1), (2, 3), (-2, 3),
               (6, 9), (-14, 21), (12, 4), (-12, 4), (35, 49), (27, 81)]
    rows = []
    for n, d in samples:
        q = Fraction(n, d)
        rows.append(f"    ({n}, {d}, {q.numerator}, {q.denominator}),")
    return """// Generated by tools/generate_tower_constant_fixtures.py using Python Fraction.

///|
test "independent Fraction normalization oracle for tower embeddings" {
  let fixtures : Array[(Int32, Int32, Int32, Int32)] = [
""" + "\n".join(rows) + """
  ]
  for depth in 0..<5 {
    let field = ct_field(depth)
    for (n, d, expected_n, expected_d) in fixtures {
      ct_assert_sample(field, depth, n, d, expected_n, expected_d)
    }
  }
}
"""


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/realtower/conversion_fraction_fixtures_wbtest.mbt')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.exists() or args.output.read_text() != expected:
            sys.exit('tower Fraction fixtures differ; regenerate')
        print('tower Fraction fixtures match independent generator')
    else:
        args.output.write_text(expected)


if __name__ == '__main__':
    main()
