#!/usr/bin/env python3
"""Generate all 12 depth-two read-once full-adder cofactor trees.

Each candidate is emitted as MoonBit and as a Lean Bool function. This is a
bounded candidate family, not a claim of globally optimal machine code.
"""
from pathlib import Path
from itertools import product
import subprocess

ROOT = Path(__file__).resolve().parent.parent
VARIABLES = ("a", "b", "carry")


def constant(value):
    return "true" if value else "false"


def leaf(known, variable):
    rows = []
    for bit in (False, True):
        values = {**known, variable: bit}
        total = sum(values.values())
        rows.append((total % 2 == 1, total >= 2))
    results = []
    for output in range(2):
        low, high = rows[0][output], rows[1][output]
        if low == high:
            results.append(constant(low))
        else:
            results.append(VARIABLES[variable] if high else "!" + VARIABLES[variable])
    return "(" + ", ".join(results) + ")"


def tree(root, second_false, second_true, lean=False):
    marker = "| " if lean else ""
    branches = []
    for root_value, second in ((False, second_false), (True, second_true)):
        remaining = next(i for i in range(3) if i not in (root, second))
        leaves = []
        for value in (False, True):
            leaves.append(f"{marker}{constant(value)} => {leaf({root: root_value, second: value}, remaining)}")
        if lean:
            branches.append(f"  | {constant(root_value)} =>\n    match {VARIABLES[second]} with\n      " + "\n      ".join(leaves))
        else:
            branches.append(f"    {constant(root_value)} => match {VARIABLES[second]} {{ " + "; ".join(leaves) + " }")
    if lean:
        return f"match {VARIABLES[root]} with\n" + "\n".join(branches)
    return f"match {VARIABLES[root]} {{\n" + "\n".join(branches) + "\n  }"


def main():
    candidates = []
    for root in range(3):
        remaining = [i for i in range(3) if i != root]
        for a, b in product(remaining, repeat=2):
            candidates.append((root, a, b))
    moon = ["// Generated by tools/generate_adder_candidates.py; test-only candidates."]
    lean = ["import Std.Tactic", "namespace Morph.AdderCandidates", "",
            "def reference (a b carry : Bool) : Bool × Bool :=",
            "  match a, b, carry with",
            "  | false, false, false => (false, false)",
            "  | false, false, true | false, true, false | true, false, false => (true, false)",
            "  | true, true, true => (true, true)",
            "  | _, _, _ => (false, true)"]
    for index, candidate in enumerate(candidates):
        moon += ["", "///|", f"fn candidate_{index}(a : Bool, b : Bool, carry : Bool) -> (Bool, Bool) {{", "  " + tree(*candidate), "}",
                 "", "///|", f"fn candidate_bits_{index}(xs : @core.Chain[Bool], ys : @core.Chain[Bool], carry : Bool) -> @core.Chain[Bool] {{",
                 "  match (xs, ys) {", "    (Cons(a, xs), Cons(b, ys)) => {",
                 f"      let (sum, next) = candidate_{index}(a, b, carry)",
                 f"      Cons(sum, candidate_bits_{index}(xs, ys, next))", "    }",
                 "    (rest, Nil) | (Nil, rest) => match carry { false => rest; true => increment_bits(rest) }", "  }", "}"]
        lean += ["", f"def candidate_{index} (a b carry : Bool) : Bool × Bool :=", "  " + tree(*candidate, lean=True),
                 f"theorem candidate_{index}_equal (a b carry : Bool) : candidate_{index} a b carry = reference a b carry := by",
                 "  cases a <;> cases b <;> cases carry <;> decide",
                 f"#print axioms candidate_{index}_equal"]
    moon += ["", "///|", 'test "all generated cofactor candidates agree on all Bool inputs and word sums" {']
    for a, b, c in product((False, True), repeat=3):
        args = ", ".join(map(constant, (a, b, c)))
        for index in range(len(candidates)):
            moon.append(f"  assert_eq(candidate_{index}({args}), full_adder({args}))")
    moon += ["  for seed in 0..<128 {", "    let left = @oracle.binary(seed * 127 + 3)",
             "    let right = @oracle.binary(seed * 59 + 7)", "    let expected = @oracle.binary(seed * 186 + 10)"]
    for index in range(len(candidates)):
        moon.append(f"    assert_eq(Binary::{{ bits: candidate_bits_{index}(left.bits, right.bits, false), }}, expected)")
    moon += ["  }", "}"]
    for width in (256, 2048):
        moon += ["", "///|", f'test "cofactor addition candidates at {width} bits" (b : @bench.T) {{',
                 f"  let left = @oracle.chain(Array::makei({width}, fn(i) {{ i == {width-1} || (i * 17 + 3) % 11 < 6 }}))",
                 f"  let right = @oracle.chain(Array::makei({width}, fn(i) {{ i == {width-1} || (i * 13 + 7) % 7 < 4 }}))",
                 '  b.bench(name="reference", fn() { b.keep(add_bits(left, right, false)) })']
        for index, candidate in enumerate(candidates):
            label = "".join(map(str, candidate))
            moon.append(f'  b.bench(name="candidate {index}: {label}", fn() {{ b.keep(candidate_bits_{index}(left, right, false)) }})')
        moon += ["}"]
    lean += ["", "end Morph.AdderCandidates", ""]
    moon_path = ROOT / "src/binary/adder_candidates_wbtest.mbt"
    moon_path.write_text("\n".join(moon) + "\n")
    (ROOT / "formal/AdderCandidates.lean").write_text("\n".join(lean))
    print(f"Generated {len(candidates)} cofactor candidates in MoonBit and Lean.")
    subprocess.run([str(ROOT / "tools/moon"), "fmt", str(moon_path)], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
