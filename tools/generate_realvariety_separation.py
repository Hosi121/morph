#!/usr/bin/env python3
"""Independent separating-form lex bases and complete real tuple sets (SymPy)."""
from argparse import ArgumentParser
from functools import cmp_to_key
from pathlib import Path
import json,subprocess
import sympy as sp
ROOT=Path(__file__).resolve().parents[1]
x,y,z,t=sp.symbols('x y z t')
def ratio(c):c=sp.Rational(c);return [int(c.p),int(c.q)]
def terms(p,vs):return [[ratio(c),list(m)] for m,c in sp.Poly(p,*vs,domain=sp.QQ).terms()]
def input_literal(ps,vs):
 result=[]
 for p in ps:
  result.append('['+', '.join(f'(({a}, {b}), ['+', '.join(map(str,e))+'])' for (a,b),e in terms(p,vs))+']')
 return '['+', '.join(result)+']'
def biglit(c):
 c=sp.Rational(c);return f'({str(c<0).lower()}, "{abs(int(c.p)):x}", "{int(c.q):x}")'
def bigpoly(p,v):return '['+', '.join(biglit(c) for c in reversed(sp.Poly(p,v).all_coeffs()))+']'
def shape(basis,vs):
 p=vs[-1]
 gs=[g for g in basis if g.free_symbols<={p} and sp.degree(g,p)>0]
 if not gs:return None
 g=sp.Poly(gs[0],p).monic().as_expr();hs=[]
 for v in vs[:-1]:
  rows=[q for q in basis if sp.degree(q,v)==1 and q.free_symbols<={v,p} and not sp.diff(q,v).free_symbols]
  if not rows:return None
  h=sp.cancel(-rows[0].subs(v,0)/sp.diff(rows[0],v));hs.append(sp.rem(h,g,p))
 hs.append(p)
 assert all(sp.rem(q.subs(dict(zip(vs,hs)),simultaneous=True),g,p)==0 for q in basis)
 return g,hs

def generate():
 cases=[([x,y],[x*x-1,y*y-1],3,'complete'),([x,y],[x*x-2,y*y-3],2,'complete'),
 ([x,y],[x*x-2,y*y-2],3,'complete'),
 ([x,y,z],[x*x-2,y-x,z*z-3],2,'complete'),([x],[2*x*x-3],1,'complete'),
 ([x,y],[x*x+1,y*y+1],3,'complete'),([x],[(x-1)**3],1,'complete'),
 ([x,y],[x*x+y*y-1,x*y],3,'complete'),
 ([x,y,z],[x*x-2,y*y-3,z-x*y],2,'complete'),
 ([x,y],[x*x,y*y],4,'paused'),([x,y],[x-y],2,'paused'),
 ([x],[x,x-1],1,'unit')]
 lines=['// Generated by tools/generate_realvariety_separation.py; independent exact SymPy oracle.',''];records=[]
 for index,(vs,inputs,attempts,kind) in enumerate(cases):
  original=list(sp.groebner(inputs,*vs,order='lex'))
  original_shape=shape(original,vs) is not None if original!=[1] else False
  record=dict(variables=[str(v) for v in vs],inputs=[str(p) for p in inputs],attempt_limit=attempts,kind=kind,original_shape=original_shape,attempts=[])
  accepted=None
  for seed in range(attempts):
   linear=sum(sp.Integer(seed)**i*v for i,v in enumerate(vs))
   augmented=inputs+[t-linear]
   basis=list(sp.groebner(augmented,*vs,t,order='lex'))
   form=None if basis==[1] else shape(basis,vs+[t])
   record['attempts'].append(dict(seed=seed,relation=str(t-linear),basis=[str(p) for p in basis],shape=form is not None,unit=basis==[1]))
   if basis==[1] or form is not None:
    accepted=(seed,basis,form,linear);break
  if kind in ('paused','unit'):
   assert (accepted is None) if kind=='paused' else (accepted is not None and accepted[1]==[1])
   lines+=['///|',f'test "SymPy separating search {index} {kind}" {{',f'  assert_search_stopped_fixture({len(vs)}, {input_literal(inputs,vs)}, {attempts}, {str(kind=="unit").lower()})','}','']
  else:
   assert accepted is not None
   seed,basis,(g,hs),linear=accepted
   solved=sp.solve_poly_system(inputs,*vs)
   real=[tuple(c) for c in (solved or []) if all(q.is_real is True for q in c)]
   tagged=[(sp.simplify(linear.subs(dict(zip(vs,point)))),point) for point in real]
   tagged.sort(key=cmp_to_key(lambda a,b:int(sp.sign(a[0]-b[0]))))
   assert all(sp.simplify(a[0]-b[0])!=0 for i,a in enumerate(tagged) for b in tagged[i+1:])
   for alpha,point in tagged:
    assert sp.simplify(g.subs(t,alpha))==0
    assert all(sp.simplify(h.subs(t,alpha)-v)==0 for h,v in zip(hs[:-1],point))
   sf=sp.Poly(g,t).sqf_part();intervals=[]
   for (lo,hi),_ in sf.intervals(eps=sp.Rational(1,4096)):
    if lo==hi:
     pad=sp.Rational(1,4096)
     while sf.count_roots(lo-pad,hi)!=1 or sf.eval(lo-pad)==0:pad/=2
     lo-=pad
    intervals.append((lo,hi))
   assert len(intervals)==len(tagged),(inputs,tagged,intervals)
   for (alpha,_),(lo,hi) in zip(tagged,intervals):assert sp.sign(alpha-lo)==1 and sp.sign(hi-alpha) in (0,1)
   record.update(seed=seed,eliminant=terms(g,[t]),coordinates=[terms(h,[t]) for h in hs[:-1]],real_solutions=[[str(q) for q in point] for _,point in tagged],parameter_values=[str(alpha) for alpha,_ in tagged],intervals=[[ratio(lo),ratio(hi)] for lo,hi in intervals])
   ilit='['+', '.join(f'({biglit(lo)}, {biglit(hi)})' for lo,hi in intervals)+']'
   lines+=['///|',f'test "SymPy separating search {index} complete" {{',f'  assert_search_fixture({len(vs)}, {input_literal(inputs,vs)}, {attempts}, {seed}, {str(original_shape).lower()},',f'    {bigpoly(g,t)}, ['+', '.join(bigpoly(h,t) for h in hs[:-1])+f'], {ilit})','}','']
  records.append(record)
 stats={key:sum(r['kind']==key for r in records) for key in ['complete','paused','unit']};stats['real_points']=sum(len(r.get('real_solutions',[])) for r in records);stats['attempts']=sum(len(r['attempts']) for r in records)
 output=subprocess.run([str(ROOT/'.tools/moon/bin/moonfmt'),'-'],input='\n'.join(lines),capture_output=True,text=True,check=True).stdout
 return {ROOT/'src/realvariety/separation_fixtures_wbtest.mbt':output,ROOT/'docs/research/realvariety-20261116-separation-fixtures.json':json.dumps(dict(sympy=sp.__version__,statistics=stats,cases=records),indent=2)+'\n'},stats

def main():
 p=ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args();files,stats=generate()
 for path,text in files.items():
  if args.check:
   if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale artifact: {path.relative_to(ROOT)}')
  else:path.write_text(text)
 print(json.dumps(stats,sort_keys=True))
if __name__=='__main__':main()
