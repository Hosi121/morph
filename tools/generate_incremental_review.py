#!/usr/bin/env python3
"""Exact independent CAD-search fixtures, deterministic Z3 replay provenance.

The symbolic Python polynomial/AST transport is shared with the earlier review;
case derivations and direct full-CAD/search comparisons are specific to cylinders.
No oracle runs in the MoonBit kernel. --check tolerates moon fmt only.
"""
from __future__ import annotations
import argparse
from fractions import Fraction as F
import hashlib
import importlib.metadata
import json
from pathlib import Path
import generate_realnlsmt_review as transport
from generate_realnlsmt_review import A, AND, OR, NOT, Case, variables

ROOT = Path(__file__).resolve().parent.parent
FULL_STRESS_NAME = 'three coordinate two future coefficients vanish'


def corpus():
    cases = []
    def add(name, n, source, expected, reason):
        cases.append(Case(name, n, source, expected, reason))
    x, y = variables(2)
    add('sector sample is not a cylindrical truth', 2,
        AND(A(x, 'gt'), A(y-x)), True, 'x=y=1; y=x is not constant over the suffix at x=1.')
    add('negative sector square root', 2,
        AND(A(x, 'lt'), A(y*y+x)), True, 'x=-1,y=1.')
    add('positive sector square root obstruction', 2,
        AND(A(x, 'gt'), A(y*y+x)), False, 'y^2+x>0 for every x>0.')
    d=x*x-2
    add('irrational section nullifies an impossible affine fibre', 2,
        AND(A(d), A(d*y-1)), False, 'At both roots of x^2-2, the second polynomial is -1.')
    add('irrational section nullifies a free suffix', 2,
        AND(A(d), A(d*y)), True, 'x=sqrt(2) makes the entire y cylinder valid.')
    add('combined coefficient cancellation leaves nonzero constant', 2,
        AND(A(x-1), A((x-1)*y+x-2)), False, 'x=1 kills the y coefficient and leaves -1.')
    add('closed boundary forbids strictly positive nullified product', 2,
        AND(A(x, 'ge'), A(x, 'le'), A(x*y, 'gt')), False, 'The closed bounds force x=0, hence xy=0.')
    add('closed boundary admits nonnegative nullified product', 2,
        AND(A(x, 'ge'), A(x, 'le'), A(x*y, 'ge')), True, 'x=0 makes xy=0 for every y.')
    add('irrational section rejects disequality after nullification', 2,
        AND(A(d), A(d*y, 'ne')), False, 'The zero coefficient forces d*y=0.')
    add('negative scaling retains relation orientation', 2,
        AND(A(x), A(-3*x*y+2, 'lt')), False, 'x=0 leaves positive constant 2, not a negative value.')
    add('Boolean alternative closes sectors and nullified sections', 2,
        OR(A(d, 'ne'), A(d*y+1, 'gt')), True, 'When d is nonzero the first disjunct holds; when d=0 the second is 1>0.')
    add('exact rational coefficient nullification', 2,
        AND(A(x-F(1,3)), A((3*x-1)*y-2, 'ge')), False, 'x=1/3 makes the second polynomial -2.')
    add('negated strict boundary survives at section', 2,
        AND(A(x), NOT(A(x*y, 'gt'))), True, 'x=0 gives xy=0 and negates strict positivity.')
    add('same future monomial combines several prefix terms', 2,
        AND(A(x-2), A((x*x-3*x+2)*y+3, 'eq')), False, 'At x=2 the grouped y coefficient is 4-6+2=0 and constant 3 remains.')
    x, y, z = variables(3)
    add('three coordinate affine coefficient vanishes before contradictory constant', 3,
        AND(A(x), A(y-1), A(x*z+y-2)), False, 'x=0 removes the z coefficient; y=1 then leaves -1. This tractable affine regression replaces the separately preserved quadratic-in-z stress input.')
    add('three coordinate nullification admits full last cylinder', 3,
        AND(A(x), A(y-1), A(x*z*z+(y-1)*z)), True, 'x=0,y=1 makes the last polynomial zero for every z.')
    return cases


def stress_case():
    x,y,z=variables(3)
    return Case(FULL_STRESS_NAME, 3, AND(A(x), A(y-1), A(x*z*z+(y-1)*z-1)), False, 'At x=0,y=1 both z coefficients vanish and -1 remains. Exact Z3 UNSAT; morph execution is a censored cost observation, not a completed result.')


def main():
    import z3
    transport.z3 = z3
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--emit-full-stress', action='store_true', help='also emit an opt-in test under .tools; copy it into src/cad temporarily to run the expensive full-CAD control')
    options=parser.parse_args()
    rows=['// Generated by tools/generate_incremental_review.py; exact independent Z3 qfnra-nlsat decisions.']
    evidence=[]
    for case in corpus()+[stress_case()]:
        vs=z3.Reals(' '.join(f'x{i}' for i in range(case.n)))
        solver=z3.Tactic('qfnra-nlsat').solver(); solver.set(timeout=30000)
        formula=transport.zformula(case.formula,vs); solver.add(formula)
        result=solver.check()
        assert result in (z3.sat,z3.unsat),(case.name,result,solver.reason_unknown())
        assert (result==z3.sat)==case.expected,(case.name,result,case.expected)
        if result==z3.sat:
            assert z3.is_true(solver.model().eval(formula,model_completion=True))
        declarations='\n'.join(f'(declare-fun x{i} () Real)' for i in range(case.n))
        smt=f'(set-logic QF_NRA)\n{declarations}\n(assert {transport.smtformula(case.formula)})\n(check-sat-using qfnra-nlsat)\n'
        replay=z3.Tactic('qfnra-nlsat').solver(); replay.set(timeout=30000)
        replay.from_string(smt[:smt.index('(check-sat-using')]); assert replay.check()==result
        evidence.append({'name':case.name,'arity':case.n,'expected':str(result),'closed_form_reason':case.proof,'smt2':smt,'sha256':hashlib.sha256(smt.encode()).hexdigest(),'default_regression':case.name != FULL_STRESS_NAME,'default_full_cad_comparison':case.name != FULL_STRESS_NAME})
        if case.name == FULL_STRESS_NAME:
            continue
        source=transport.moonformula(case.formula).replace('review_polynomial','incremental_review_polynomial')
        rows += ['', '///|', f'test "independent incremental Z3 {case.name}" {{', f'  let source = {source}', f'  incremental_review_expect({case.n}, source, {str(case.expected).lower()}, {str(case.name != FULL_STRESS_NAME).lower()})', '}']
    source='\n'.join(rows)+'\n'
    library=Path(z3.__file__).parent/'lib/libz3.so'
    provenance={
      'reference':'Z3 qfnra-nlsat, independently replayed exact SMT-LIB',
      'z3_version':z3.get_full_version(), 'wheel_version':importlib.metadata.version('z3-solver'),
      'libz3_sha256':hashlib.sha256(library.read_bytes()).hexdigest(),
      'transport_source_sha256':hashlib.sha256(Path(transport.__file__).read_bytes()).hexdigest(),
      'scope':'16 default exact search/model/proof and checked full-CAD differential cases, plus one preserved optional stress input checked only by external Z3',
      'full_reference_policy':'Original quadratic-in-z case 14 remains as an optional stress input: neither full nor pruned morph completion is claimed. The default cohort uses a distinct, explicitly named affine replacement. --emit-full-stress emits the original input test under .tools, outside default package tests.',
      'stress_cost_observation':{'baseline':'09c4f7e','target':'native','profile':'debug','cpu':10,'classification':'unresolved cost, not wrong result and not passed','full_plus_search_single_case_execution_timeout_seconds':10,'initial_full_control_cohort_stopped_after_seconds':72,'full_disabled_cohort_stopped_after_seconds':52,'cohort_times_are_not_individual_case_times':True,'phase_diagnostic_execution_timeout_seconds':8,'last_completed_phase_in_line_buffered_diagnostic':'prepare','active_phase_at_timeout':'search/lifting (before checker)'},
      'input_coefficients':'Fraction/QQ; no floats or approximate roots',
      'cases':evidence,
    }
    output=ROOT/'src/cad/independent_incremental_z3_wbtest.mbt'
    report=ROOT/'docs/measurements/incremental-review-oracle-20261117.json'
    if options.check:
        assert output.exists() and transport.syntax(output.read_text())==transport.syntax(source),'generated fixture differs'
        assert json.loads(report.read_text())==provenance,'provenance differs'
    else:
        output.write_text(source); report.write_text(json.dumps(provenance,indent=2)+'\n')
    if options.emit_full_stress:
        case=stress_case()
        formula=transport.moonformula(case.formula).replace('review_polynomial','incremental_review_polynomial')
        stress='// Opt-in full CAD control; generated by --emit-full-stress.\n\n///|\ntest \"independent incremental optional expensive full CAD control\" {\n  let source = '+formula+'\n  incremental_review_expect('+str(case.n)+', source, false, true)\n}\n'
        target=ROOT/'.tools/incremental-review-20261117/optional_full_stress_wbtest.mbt'
        target.parent.mkdir(parents=True,exist_ok=True); target.write_text(stress)
        print('Optional full reference: '+str(target.relative_to(ROOT))+'; temporarily copy to src/cad/independent_incremental_optional_full_stress_wbtest.mbt, run its named test, then remove the copy.')
    cases=corpus()
    print(('Verified' if options.check else 'Generated')+f' {len(cases)} default exact cylindrical-search cases: {sum(c.expected for c in cases)} SAT, {sum(not c.expected for c in cases)} UNSAT; preserved optional stress input independently Z3 UNSAT.')


if __name__=='__main__': main()
