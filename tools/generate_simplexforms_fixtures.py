#!/usr/bin/env python3
"""Independent affine-simplex Fraction oracle using iterated polynomial integrals.

Coefficient/pullback dictionaries are the independent host forms model. Integration
expands bounds 0<=x_last<=1-sum(others), not factorial or production moment recurrences.
"""
from argparse import ArgumentParser
from fractions import Fraction as Q
from itertools import product
from pathlib import Path
from random import Random
import shutil
import subprocess
import generate_forms_fixtures as F

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/simplexforms/fraction_fixtures_wbtest.mbt"


def integrate_polynomial(p,n):
    for dimension in reversed(range(1,n+1)):
        bound = {(0,)*(dimension-1):Q(1)}
        for i in range(dimension-1):
            exponent = [0]*(dimension-1); exponent[i] = 1
            bound[tuple(exponent)] = Q(-1)
        result = {}
        for exponent,q in p.items():
            term = {exponent[:-1]:q/Q(exponent[-1]+1)}
            for _ in range(exponent[-1]+1): term = F.multiply_poly(term,bound)
            result = F.add_poly(result,term)
        p = result
    return p.get((),Q())


def affine_coordinates(vertices):
    k = len(vertices)-1
    result = []
    for coordinate in range(len(vertices[0])):
        p = {(0,)*k:vertices[0][coordinate]}
        for j in range(k):
            exponent = [0]*k; exponent[j] = 1
            p[tuple(exponent)] = vertices[j+1][coordinate]-vertices[0][coordinate]
        result.append({e:q for e,q in p.items() if q})
    return result


def integral(vertices,a):
    k = len(vertices)-1
    pulled = F.pullback(a,affine_coordinates(vertices),k)
    assert all(indices == tuple(range(k)) for indices in pulled)
    return sum((integrate_polynomial(p,k) for p in pulled.values()),Q())


def standard(n):
    return [[Q()]*n]+[[Q(i == j) for j in range(n)] for i in range(n)]


def value(q):
    assert abs(q.numerator)<2**31 and q.denominator<2**31, q
    return f"({q.numerator}, {q.denominator})"


def vector(row): return "["+", ".join(value(q) for q in row)+"]"
def matrix(rows): return "["+", ".join(vector(row) for row in rows)+"]"


def raw_form(rng,n,k):
    if k and not n: return []
    return [(F.poly([(Q(rng.randrange(-2,3),rng.choice([1,2,3])),[rng.randrange(2) for _ in range(n)]) for _ in range(2)]),
             tuple(rng.randrange(n) for _ in range(k))) for _ in range(3)]


def render():
    rng = Random(20261119)
    lines = ["// Generated by tools/generate_simplexforms_fixtures.py; exact iterated Fraction integration oracle.",""]
    integrals = []
    for n in range(5):
        limit = 4 if n<4 else 3
        for exponent in product(range(limit),repeat=n):
            a = {tuple(range(n)):{tuple(exponent):Q(2,3)}}
            integrals.append((n,standard(n),a))
    for n in range(5):
        for k in range(min(n+2,4)):
            for _ in range(2):
                vertices = [[Q(rng.randrange(-2,3),rng.choice([1,2])) for _ in range(n)] for _ in range(k+1)]
                integrals.append((n,vertices,F.normalize(raw_form(rng,n,k))))
                if k:
                    degenerate = [list(v) for v in vertices]; degenerate[1] = list(degenerate[0])
                    integrals.append((n,degenerate,F.normalize(raw_form(rng,n,k))))
    for index,(n,vertices,a) in enumerate(integrals):
        expected = integral(vertices,a)
        lines += ["///|",f'test "Fraction oriented affine form integral {index}" {{',
                  f"  fraction_integral_fixture({n}, {matrix(vertices)}, {F.form_text(a)}, {value(expected)})","}",""]
    stokes_count = 0
    for n in range(5):
        for k in range(1,min(n+2,4)):
            for _ in range(4):
                vertices = [[Q(rng.randrange(-2,3),rng.choice([1,2])) for _ in range(n)] for _ in range(k+1)]
                a = F.normalize(raw_form(rng,n,k-1)); differential = F.exterior(a,n)
                faces = [vertices[:i]+vertices[i+1:] for i in range(k+1)]
                face_values = [integral(face,a) for face in faces]
                expected = integral(vertices,differential)
                assert expected == sum(((-1)**i*q for i,q in enumerate(face_values)),Q())
                lines += ["///|",f'test "Fraction complete polynomial Stokes certificate {stokes_count}" {{',
                          f"  fraction_stokes_fixture({n}, {matrix(vertices)}, {F.form_text(a)}, {F.form_text(differential)}, {vector(face_values)}, {value(expected)})","}",""]
                stokes_count += 1
    return "\n".join(lines),len(integrals),stokes_count


def main():
    parser = ArgumentParser(description=__doc__); parser.add_argument("--check",action="store_true"); args = parser.parse_args()
    source,integrals,stokes = render()
    formatter = ROOT / ".tools/moon/bin/moonfmt"; executable = str(formatter) if formatter.exists() else shutil.which("moonfmt")
    if executable is None: raise SystemExit("moonfmt required")
    source = subprocess.run([executable,"-"],input=source,text=True,capture_output=True,check=True).stdout
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text()!=source: raise SystemExit("Simplex forms Fraction fixture drift: "+str(OUTPUT))
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True); OUTPUT.write_text(source)
    print(f"{integrals} full oriented integrals and {stokes} full Stokes certificates/all face values.")


if __name__ == "__main__": main()
